    <ol class="lrr">
    <li data-src="1,8">Players can use the abilities of hazardous, cultural, and industrial relic fragments in their play area to draw cards from the relic deck.</li>
    <ol><li data-src="1,2,8">Relic fragments can be found when exploring planets and frontier tokens, and can be exchanged with other players as part of transactions.</li></ol>
    <li data-src="1,2,7,8">When a player is instructed to gain a relic, they draw the top card of the relic deck and place it faceup in their play area.</li>
    <ol><li data-src="1">If there are no cards in the relic deck, they do not gain a relic.</li></ol>
    <li data-src="1">A player can use the abilities of relics that are in their play area.</li>
    <li data-src="1,8">Relics cannot be traded.</li>
    </ol>

