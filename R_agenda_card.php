<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '7.' counter(item, decimal);} </style>
<p data-src="1,3">Agenda cards represent galactic laws and policies. During each agenda phase, players cast votes for specific outcomes on two agenda cards.</p>
    <ol class="lrr">
    <li data-src="1,3">There are two types of agenda cards: laws and directives.</li>
    <li data-src="1,3">Laws can permanently change the rules of the game.</li>
    <li data-src="1,2,3">When resolving a law, if a &ldquo;For&rdquo; outcome received the most votes, or if the law requires an election, the law&rsquo;s ability becomes a permanent part of the game. Players resolve the outcome and place the agenda card either in the common play area or in a player&rsquo;s play area, as dictated by the card.</li>
    <li data-src="1">If a law is in a player&rsquo;s play area as opposed to the common play area, that player owns that law.</li>
    <li data-src="1">If a law is discarded from play, that law&rsquo;s ability is no longer in effect. Place that card on the top of the agenda card discard pile.</li>
    <li data-src="1,2,3">If an &ldquo;Against&rdquo; outcome of a law received the most votes, players resolve the outcome and discard the agenda.</li>
    <li data-src="1,2">Directives provide one&ndash;time game effects.</li>
    <li data-src="1,2,3">When resolving a directive, players resolve the outcome that received the most votes and discard the agenda card.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>When resolving the primary ability of the <a href="/R_politics"><i>Politics</i></a> card, the active player cannot show the agenda cards they drew to any other player.<sup>2</sup></li>
    <li>During the agenda phase, if the outcome of an agenda affects multiple players, it does so in speaker order, starting with the <a href="/R_speaker">speaker</a> and proceeding clockwise. If an agenda is resolved during the action phase, such as with the <a href="/F_keleres">Keleres</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Council_Keleres#Thunder's_Edge_2:~:text=Executive%20Order"><i>Executive Order</i></a> technology, it does so in <a href="/R_initiative_order">initiative order</a>.<sup>2,4</sup></li>
    </ol>

