<h2>Notes</h2>
    <ol class="note">
    <li>Units are component limited.<sup>1</sup></li>
    <ol><li>Fighters and infantry are semi&ndash;limited, via the use of tokens.<sup>1,2</sup></li></ol>
    <li>A faction&ndash;specific unit counts as its base unit type for all purposes. For example, the <a href="/F_muaat">Muaat</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Embers_of_Muaat#War_Sun:~:text=Prototype%20War%20Sun">Prototype War Sun</a> is a war sun. Only the researched unit upgrade card is a technology; the unit printed on a faction sheet is not.<sup>2</sup></li>
    <li>If an effect allows a player to produce a ship of a specific type, then factional variations do not prevent that player from producing that type of ship.<sup>2</sup></li>
    <li>A player cannot remove their own units from the game board at will; units are only removed by game effects, such as being destroyed or captured. The exception is that a player may remove a unit from the board in order to place it when there are none of that type in their reinforcements.<sup>2</sup></li>
    </ol>

