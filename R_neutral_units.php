<h2>Rules Reference</h2>
<p>There currently does not exist a Living Rules Reference section regarding neutral units.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>Neutral units are placed in some systems within The Fracture when it enters play. Several other game effects also place neutral units.<sup>7,11</sup></li>
    <li>If a player has ships in a space area that contains neutral units, they will resolve a space combat against those units.<sup>7</sup></li>
    <li>If a player has ground forces on a planet that contains neutral units, they will resolve a ground combat against those units.<sup>7</sup></li>
    <li>Any player other than the active player may roll the combat and unit ability dice during a combat involving neutral units. The combat values and unit abilities are found on the neutral unit reference card.<sup>7</sup></li>
    <li>Neutral units will always use each and every unit ability that they can.<sup>7</sup></li>
    <li>Neutral units do not take turns, own technology, or draw action cards, and so on.<sup>7</sup></li>
    <li>When a hit is assigned against a group of neutral units, it is assigned to the unit that is lowest on the neutral unit reference card.<sup>6,7</sup></li>
    <li>Neutral units are considered to be another player&rsquo;s ships for abilities and other game effects. However, there is no neutral player.<sup>7</sup></li>
    <li>Neutral units with <a href="/R_sustain_damage"><sc>Sustain Damage</sc></a> use it to cancel hits before any remaining hits are assigned. For example, if a neutral destroyer and a neutral dreadnought take one hit, the dreadnought uses <a href="/R_sustain_damage"><sc>Sustain Damage</sc></a> to cancel it.<sup>6</sup></li>
    <li>Neutral units cannot make decisions. If a decision must be made for a neutral unit, the speaker makes it.<sup>7</sup></li>
    <ol><li>During combat, hits against neutral units are always assigned in the order on the neutral unit reference card, so the speaker does not choose. The speaker does choose which neutral units are hit outside of combat, such as by <a href="/R_space_cannon"><sc>Space Cannon</sc></a>.<sup>6</sup></li></ol>
    <li>If there are no neutral units of a given type left in the supply, and one would be placed, it is not placed.<sup>6</sup></li>
    </ol>

