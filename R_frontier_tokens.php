<p data-src="1">Frontier tokens can be explored for a variety of game effects.</p>
    <ol class="lrr">
    <li data-src="1,2,8">Frontier tokens are placed on the game board during setup. One frontier token is placed in each system that does not contain any planets.</li>
    <ol>
        <li data-src="1">Frontier tokens are not placed on hyperlane tiles.</li>
        <li data-src="1">A system cannot have more than one frontier token.</li>
        <li data-src="1,8">Frontier tokens are placed in anomalies that do not have planets.</li>
        <li data-src="1">A frontier token is placed in the <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Faction_Abilities:~:text=Creuss%20gate">Creuss gate</a> system.</li>
    </ol>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>Players may explore space areas that contain frontier tokens if they own the <a href="https://twilight-imperium.fandom.com/wiki/Propulsion_Technologies#Dark_Energy_Tap"><i>Dark Energy Tap</i></a> technology or if another game effect allows them to.<sup>1,8</sup></li>
    <li>If a system tile contains a <a href="/R_space_stations">space station</a>, but no planets, then a frontier token will be placed in that system during game setup.<sup>7</sup></li>
    <li>Frontier tokens are not placed in systems in <a href="/R_fracture">The Fracture</a> when it is brought into play, as frontier tokens are only placed during setup. However, if The Fracture is in play when the <a href="/F_empyrean">Empyrean</a> player resolves their <a href="https://twilight-imperium.fandom.com/wiki/The_Empyrean#Leaders:~:text=Multiverse%20Shift"><i>Multiverse Shift</i></a> hero ability, frontier tokens will be placed in the systems in The Fracture that do not contain a planet.<sup>2,6</sup></li>
    <li>If <a href="https://twilight-imperium.fandom.com/wiki/Thunder&#x27;s_Edge">Thunder&rsquo;s Edge</a> is placed in a system containing a frontier token, that token is not removed.<sup>7</sup></li>
    </ol>

