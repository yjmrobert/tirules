<h2 id="alliance"><a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Alliance">Alliance</a></h2>
    <ol class="note">
    <li>If the active player receives an <i>Alliance</i>, they cannot then attempt to trade it with another player. It must be placed face up in their play area immediately.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;Can I trade on a promissory note I received from another player &hellip;?&rdquo;: &ldquo;Notes face up in your play area, like Support for the Throne, can&rsquo;t be traded or handed back voluntarily.&rdquo; Alliance card text: &ldquo;When you receive this card, if you are not the (color) player, you must place it face up in your play area.&rdquo;</li>
        </ul></li>
    <li>If an effect other than activating a system during a tactical action places a command token in a system with the other player&rsquo;s units (for example, the primary ability of the <a href="/R_diplomacy"><i>Diplomacy</i></a> strategy card), this will not cause <i>Alliance</i> to be returned.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, on Support for the Throne: &ldquo;Putting a command token in a system by other means is not activating it.&rdquo; Alliance card text: &ldquo;If you activate a system that contains 1 or more of the (color) player&rsquo;s units, return this card to the (color) player.&rdquo;</li>
        </ul></li>
    <li>Activating a system containing only a player&rsquo;s structures will still cause their <i>Alliance</i> to be returned.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, on Support for the Throne: &ldquo;Units include their ships, ground forces, space docks and PDS.&rdquo; Alliance card text: &ldquo;If you activate a system that contains 1 or more of the (color) player&rsquo;s units, return this card to the (color) player.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="ceasefire"><a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Ceasefire">Ceasefire</a></h2>
    <ol class="note">
    <li>The active player may still use the <a href="/R_space_cannon"><sc>Space Cannon</sc></a> ability of any units during the <b>Space Cannon Offense</b> step of the tactical action.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do Ceasefire or Disable stop Space Cannon?&rdquo;: &ldquo;Ceasefire only stops ships moving in, so Space Cannon, Bombardment, invasion and production all still happen.&rdquo;</li>
        </ul></li>
    <li>If a player has units in the active system from before the tactical action in which their <i>Ceasefire</i> is played, those units will remain in the active system.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If the active player already has units with capacity in the active system, they may transport ground forces on planets in that system into the space area of that system. Those units may then be committed to invade a planet during this tactical action.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;Can ground forces already on one planet invade another planet in the same system?&rdquo;: &ldquo;Only if a ship with capacity picked them up into the space area during the movement step.&rdquo;</li>
        </ul></li>
    <li>If a system containing only a player&rsquo;s ground forces or structures is activated, that player may still play the active player&rsquo;s <i>Ceasefire</i>.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li><i>Ceasefire</i> does not prevent a player from producing units in the active system.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do Ceasefire or Disable stop Space Cannon?&rdquo;: &ldquo;Space Cannon, Bombardment, invasion and production all still happen.&rdquo;</li>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal: &ldquo;Ceasefire only prevents movement.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="political-secret"><a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Political_Secret">Political Secret</a></h2>
    <ol class="note">
    <li>The effect of <i>Political Secret</i> does not stop a player from using their passive faction ability, only the abilities that player may choose to use.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Does the &lsquo;Political Secret&rsquo; promissory note disable passive/mandatory faction abilities &hellip;? A: No. The &lsquo;Political Secret&rsquo; promissory note only prevents the use of faction abilities that a player must choose to use.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;What exactly does Political Secret stop the affected player from doing?&rdquo;: &ldquo;Mandatory and passive abilities still apply.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;the Letnev have nothing to fear from &lsquo;Political Secret&rsquo; &hellip; Any faction ability that requires the player to make any kind of active decision cannot be used.&rdquo;</li>
        </ul></li>
    <li>A player may still use abilities from their faction technology after their <i>Political Secret</i> has been played.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;The &lsquo;Political Secret&rsquo; promissory note does not prevent a player from using faction-specific technology.&rdquo;</li>
        </ul></li>
    <ol><li>If a player has had their <i>Political Secret</i> played, other players may still use that player&rsquo;s other promissory notes.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li></ol>
    <li>If an agenda is discarded, the effect of each <i>Political Secret</i> that has been played ends. The affected players may vote on the next agenda as normal.<sup>1,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;If a player&rsquo;s &lsquo;Political Secret&rsquo; promissory note is used against them, but that agenda is subsequently discarded &hellip; A: Yes. It is a new agenda and thus the effect of the player&rsquo;s &lsquo;Political Secret&rsquo; is ended.&rdquo;</li>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (sigmazero13, Jun 6, 2018): &ldquo;It counts as being resolved.&rdquo; Discarded agenda counts as resolved, ending Political Secret.</li>
        </ul></li>
    </ol>

<h2 id="support-for-the-throne"><a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Support_for_the_Throne">Support For The Throne</a></h2>
    <ol class="note">
    <li>A <i>Support For The Throne</i> must be played by the receiving player as soon as it is received. It cannot be kept secret.<sup>2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play, Support for the Throne card: &ldquo;When you receive this card, if you are not the blue player, you must place it faceup in your play area and gain 1 victory point.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;promissory notes are never mandatory unless the note says to play it immediately or place it face up.&rdquo;</li>
        </ul></li>
    <ol><li>If the active player receives a <i>Support For The Throne</i>, they cannot then attempt to trade it with another player. It must be played immediately.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can I trade on a promissory note I received from another player &hellip;?&rdquo;: &ldquo;Notes face up in your play area, like Support for the Throne, can&rsquo;t be traded or handed back voluntarily.&rdquo;</li>
        </ul></li></ol>
    <li><i>Support For The Throne</i> is returned when the system is activated, even if the active player will perform no hostile acts toward the other player this turn.<sup>2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When must I return another player&rsquo;s Support for the Throne?&rdquo;: &ldquo;As soon as you activate a system containing any of that player&rsquo;s units, whether or not you move in or attack.&rdquo;</li>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play, card text: &ldquo;If you activate a system that contains 1 or more of the blue player&rsquo;s units &hellip; lose 1 victory point and return this card.&rdquo;</li>
        </ul></li>
    <li>Activating a system containing only a player&rsquo;s structures will still cause their <i>Support For The Throne</i> to be returned.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;Units include their ships, ground forces, space docks and PDS.&rdquo;</li>
        </ul></li>
    <li>Activating a system that contains only another player&rsquo;s control tokens does not cause their <i>Support For The Throne</i> to be returned, as control tokens are not units.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;not control tokens, so activating a system where they only have control tokens is fine.&rdquo;</li>
        </ul></li>
    <li>If an effect other than activating a system during a tactical action places a command token in a system with the other player&rsquo;s units (for example, the primary ability of the <a href="/R_diplomacy"><i>Diplomacy</i></a> strategy card), this will not cause <i>Support For The Throne</i> to be returned.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;Putting a command token in a system by other means is not activating it.&rdquo;</li>
        </ul></li>
    <li>A player who has given away their <i>Support For The Throne</i> may activate systems containing the holder&rsquo;s units without penalty.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can Support for the Throne be given away even if it hands someone the winning point, and can the giver attack the holder?&rdquo;: &ldquo;Only the holder risks losing it, by activating a system with the giver&rsquo;s units, any system, even by mistake. The giver can attack freely.&rdquo;</li>
        </ul></li>
    <li>If two players trade their <i>Support For The Throne</i> to one another simultaneously, the active player will be the first to gain a victory point.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;If two players swap Support for the Throne and both would hit 10, who wins?&rdquo;: &ldquo;The swapped notes resolve one after the other in normal timing order, so the player who gains the point first wins.&rdquo;</li>
        </ul></li>
    <ol><li>During the agenda phase, the first player in speaker order will be the first to gain a victory point.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;If two players could both reach 10 points in the same status phase, who wins?&rdquo;: &ldquo;The speaker-order tiebreak only covers truly simultaneous gains.&rdquo;</li>
        </ul></li></ol>
    <li>A player may give their <i>Support For The Throne</i> to another player even if doing so gives that player the victory point they need to win the game.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can Support for the Throne be given away even if it hands someone the winning point, and can the giver attack the holder?&rdquo;: &ldquo;Yes to both. Trading it is a normal transaction, and a ban is a house rule.&rdquo;</li>
        </ul></li>
    <ol><li class="ixth">Doing so is a betrayal most foul.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found. Owner&rsquo;s comment on table etiquette.</li>
        </ul></li></ol>
    </ol>

<h2 id="trade-agreement"><a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Trade_Agreement">Trade Agreement</a></h2>
    <ol class="note">
    <li><i>Trade Agreement</i> cannot be played when a player gains commodities, only when they replenish commodities.<sup>3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play, Trade Agreement card: &ldquo;When the blue player replenishes commodities: The blue player gives you all of his commodities.&rdquo;</li>
        </ul></li>
    <li>If a player has their maximum number of commodities, and is instructed to replenish their commodities, they will take no commodities. However, that player&rsquo;s <i>Trade Agreement</i> may be played.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Even if that player gains zero commodities when their commodities are refreshed, their &lsquo;Trade Agreement&rsquo; may still be played against them.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 21.2: &ldquo;The commodity value on a player&rsquo;s faction sheet indicates the maximum number of commodities that player can have.&rdquo;</li>
        </ul></li>
    <li>A player does not have to be neighbors with the player that plays their <i>Trade Agreement</i> to give them their commodities.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>
