        </ul></li>
    <li>Placing the structure will occur after the <b>Production</b> step. If the Winnu player places a <a href="/R_space_dock">Space Dock</a>, they cannot produce out of it during the same action.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> Same entry: &ldquo;a dock placed by Winnu&rsquo;s Reclamation comes after the tactical action, too late to produce in it.&rdquo;</li>
        </ul></li>
    <li>If the Winnu player gains control of a planet with multiple Reclaimers, they may place a structure for each one, if they may do so without exceeding the maximum number of that structure allowed on a planet.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>The Reclaimer need only be on the planet at the end of the tactical action the Winnu player gained it, not when the Winnu player gains control of it. This can occur from effects such as the <a href="https://twilight-imperium.fandom.com/wiki/Cybernetic_Technologies#Integrated_Economy"><i>Integrated Economy</i></a> technology, or some exploration cards.<sup>*</sup>
