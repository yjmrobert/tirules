        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;How many units can a space dock produce?&rdquo;: &ldquo;A Space Dock I has Production equal to its planet&rsquo;s resource value plus 2.&rdquo;</li>
