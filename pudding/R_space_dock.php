<p>The source text behind each note on <a href="/R_space_dock">Space Dock</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>A <a href="https://twilight-imperium.fandom.com/wiki/Space_Dock">Space Dock</a> is both a structure and a unit.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 79: &ldquo;A space dock is a structure that allows players to produce units.&rdquo;</li>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, on the Hel-Titan: &ldquo;It is a structure as well as a ground force.&rdquo;</li>
        </ul></li>
    <li>Fighters transported during movement remain assigned to the transporting ship until movement is complete.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 95.1a: &ldquo;These transported units remain with the transporting ship until it is finished moving.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;After ships stop moving, are fighters and ground forces still tied to the ship that carried them?&rdquo;: &ldquo;No &mdash; only while moving.&rdquo;</li>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (sigmazero13, Aug 24, 2018): &ldquo;The intent is that the units are dropped off after the ship has ended its movement in the active system.&rdquo; Units stay aboard until movement ends.</li>
        </ul></li>
    </ol>
