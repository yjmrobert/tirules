<p>The source text behind each note on <a href="/R_space_dock">Space Dock</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Rules Reference</h2>
    <ul>
    <li>(Thunder&rsquo;s Edge) A player whose only units on a planet are structures, such as a space dock, keeps control of that planet when another player&rsquo;s ground forces <a href="/R_coexistence">coexist</a> there.<sup>9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence and Structures&rdquo;: &ldquo;Structures without ground forces may maintain control of a planet with coexisting ground forces.&rdquo;</li>
        </ul></li>
    </ul>

<h2>Notes</h2>
    <ol class="note">
    <li>A Space Dock is both a structure and a unit.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 83 (Structures): &ldquo;A structure is a type of unit. PDS units and space docks are structures.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Are PDS and space docks ground forces?&rdquo;: &ldquo;No &mdash; PDS and space docks are structures, a separate unit type.&rdquo;</li>
        </ul></li>
    <li>Fighters transported during movement remain assigned to the transporting ship until movement is complete. They cannot be counted toward a space dock&rsquo;s allocation until after movement is complete.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 95.1a: &ldquo;These transported units remain with the transporting ship until it is finished moving.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;After ships stop moving, are fighters and ground forces still tied to the ship that carried them?&rdquo;: &ldquo;No &mdash; only while moving.&rdquo;</li>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (sigmazero13, Aug 24, 2018): &ldquo;The intent is that the units are dropped off after the ship has ended its movement in the active system.&rdquo; Units stay aboard until movement ends.</li>
        </ul></li>
    <ol><li>If a player moves one of their units with capacity into a system, transporting fighters, they cannot pick up ground forces from a planet in that system with that ship by transferring those fighters to a space dock in that system to free up capacity, as picking up ground forces is part of movement.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 95.1a: &ldquo;These transported units remain with the transporting ship until it is finished moving.&rdquo; Ground forces are picked up while the ship is moving, before the fighters can be reassigned.</li>
        </ul></li></ol>
    </ol>
