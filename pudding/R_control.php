<h2>Rules Reference</h2>
    <ul>
    <li>(Thunder&rsquo;s Edge) The player whose units trigger <a href="/R_coexistence">coexistence</a> on a planet does not gain or retain control of it; if they already controlled it, the player they now coexist with gains control of it, exhausted. If a player&rsquo;s coexisting units become the only units on a planet, that player gains control of it.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;The player whose units triggered coexistence does not gain or retain control of the planet; if they already controlled it, the player they are now coexisting with gains control of it instead, exhausted. &hellip; If a player&rsquo;s coexisting units become the only units on a planet, that player gains control of the planet.&rdquo;</li>
        </ul></li>
    </ul>

<h2>Notes</h2>
    <ol class="note">
    <li>Control tokens are not component limited.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 72.1: &ldquo;The components in a player&rsquo;s reinforcements are limited.&rdquo; Reinforcements are units and command tokens; control tokens are not listed.</li>
        </ul></li>
    <li>Different players may control different planets in the same system.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can different players control different planets in the same system?&rdquo;: &ldquo;Yes &mdash; each planet is controlled separately and nobody controls the space area.&rdquo;</li>
        </ul></li>
    <li>If a player is given another player&rsquo;s planet card, such as with the <a href="/F_hacan">Hacan</a> player&rsquo;s mech, <a href="https://twilight-imperium.fandom.com/wiki/The_Emirates_of_Hacan#Mech:~:text=Pride%20of%20Kenara">Pride of Kenara</a>, they gain control of that planet.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When a planet card is given to another player, by an exploration effect or the Hacan mech, does control go with it?&rdquo;: &ldquo;Yes &mdash; control and holding the planet card go together, so the receiver controls the planet.&rdquo;</li>
        </ul></li>
    <li>Each player controls every planet in their home system from the start of the game, even if that planet contains none of their units. As this control is not gained, it does not trigger abilities that resolve when a player gains control of a planet, such as the <a href="/F_saar">Saar</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Clan_of_Saar#Faction_Abilities:~:text=Scavenge"><sc>Scavenge</sc></a> faction ability.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do I control both planets in my home system at the start, and does that trigger &lsquo;gain control&rsquo; effects?&rdquo;: &ldquo;You control every home planet from the start, empty or not; a control token on an empty one is just a reminder. Because you begin with control rather than gaining it, abilities like Saar&rsquo;s Scavenge don&rsquo;t trigger at setup.&rdquo;</li>
        </ul></li>
    </ol>
