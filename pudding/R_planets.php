<h2>Notes</h2>
    <ol class="note">
    <li><a href="/R_mecatol_rex">Mecatol Rex</a> and planets in home systems do not have traits.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 38.1b: &ldquo;Planets that do not have traits, such as Mecatol Rex and planets in home systems, cannot be explored.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can Titans put more than one sleeper on a planet with Terragenesis, or one on Mecatol Rex?&rdquo;: &ldquo;Mecatol Rex and home planets have no trait and can&rsquo;t be explored.&rdquo;</li>
        </ul></li>
    <li>Planets with traits can be explored.<sup>2,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> Same entry: planets without a trait &ldquo;can&rsquo;t be explored.&rdquo; Planets with traits can.</li>
        <li><b>Implicit</b>: <sup>8</sup> PoK rulebook: &ldquo;A planet that does not have a type cannot be explored.&rdquo;</li>
        </ul></li>
    <li>A planet cannot be spent for both its influence and resources during a single exhaustion.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can a planet&rsquo;s resources and influence both be spent, or spent twice?&rdquo;: &ldquo;No &mdash; exhausting a planet spends either its resources or its influence, never both.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 64.9: &ldquo;A player cannot spend an exhausted planet&rsquo;s resources or influence.&rdquo; spending exhausts the planet, so it cannot then be spent again.</li>
        </ul></li>
    <li>If a planet is exhausted for its technology specialty, it does not provide influence or resources.<sup>2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;While researching technology, players may exhaust planets for their technology specialty or for their resources, but not for both.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;What happens when an exploration card adds a technology specialty &hellip;?&rdquo;: &ldquo;An attached specialty counts as the planet&rsquo;s own and is used by exhausting the planet.&rdquo;</li>
        </ul></li>
    <li>A player may only exhaust their own planets, unless a game effect specifies otherwise.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>
