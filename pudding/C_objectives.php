<h2 id="amass-wealth"><a href="https://twilight-imperium.fandom.com/wiki/Objectives#Prophecy_of_Kings_Expansion:~:text=Amass%20Wealth">Amass Wealth</a></h2>
    <ol class="note">
    <li>The influence, resources and trade goods must be spent during the status phase. Any that were spent during the action phase will have no effect.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 61.10: &ldquo;To score such an objective, a player must pay the specified cost at the time indicated on the card.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;For objectives that require spending resources, influence, tokens or trade goods, does earlier spending count?&rdquo;: &ldquo;No &mdash; you pay the full amount in one go when you score the objective, as its cost; nothing spent earlier in the round counts.&rdquo;</li>
