        </ul></li>
    <li>Trade goods may be spent as influence or resources when scoring <i>Amass Wealth</i>.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;Trade goods can stand in for resources or influence there, though a &lsquo;spend trade goods&rsquo; objective needs actual trade goods.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 19.2: trade goods &ldquo;can be spent by that player as resources, influence, or to resolve certain game effects.&rdquo;</li>
        </ul></li>
    </ol>

