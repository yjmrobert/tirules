<h2>Notes</h2>
    <ol class="note">
    <li>If a player wishes to place a unit, but there are none of that type left in their reinforcements, they may remove a unit of that type from any system that does not contain one of their command tokens and place that instead.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 23.4a: &ldquo;When a player would place a unit, if there are none of that type left in their reinforcements, that player can remove a unit from any system that does not contain one of their command tokens.&rdquo;</li>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;When a player wishes to produce a unit but has no units of that type available in their reinforcements, that player may remove one of their units of that type from a system that does not contain one of their command tokens.&rdquo;</li>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;Can I remove my own units from the board when I want to?&rdquo;: &ldquo;The one exception is taking a unit off the board when you need to place one and none are in reinforcements.&rdquo; command-token restriction stated in the structures entry.</li>
        </ul></li>
    <li>Command tokens on a player&rsquo;s command sheet are not in that player&rsquo;s reinforcements.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;What happens if I would gain a command token but have none left in my reinforcements?&rdquo;: &ldquo;Tokens you spend &hellip; go back to your reinforcements, not to your command sheet.&rdquo;</li>
        </ul></li>
    </ol>
