<p>The source text behind each note on <a href="/R_infantry_tokens">Infantry Tokens</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>As each player only has twelve plastic infantry figures, a player cannot have infantry on more than twelve planets or being transported in more than twelve space areas, or any combination thereof.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Are fighter and infantry tokens limited, and what are they for?&rdquo;: &ldquo;each stack of tokens must sit with at least one plastic piece of the same type. So your plastic fighters and infantry limit how many places you can have them.&rdquo; The cited entry (capacity) does not address this.</li>
        </ul></li>
    <li>Infantry tokens are not component limited.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Is there a limit to how many infantry can be on one planet?&rdquo;: &ldquo;No &mdash; any number of infantry can be on a planet. You are only limited by your components, and tokens can stand in for extra infantry.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 23.4: &ldquo;Units are limited to those included in the game, except for fighters and ground forces.&rdquo;</li>
        </ul></li>
    <li>A player may remove a plastic infantry figure from a planet or space area, along with any accompanying infantry tokens, if doing so allows them to swap it into the active system and allows them to commit ground forces to and fight ground combats on multiple planets during the <b>Invasion</b> step of the tactical action in that system when they could otherwise not do so.<sup>*</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;When all my plastic fighters or infantry are on the board, can I move some to where I&rsquo;m producing?&rdquo;: &ldquo;you may remove them from systems without your command token.&rdquo; Covers producing, not committing.</li>
        </ul></li>
    <li>If a player has an infantry token that is not accompanied by a plastic infantry and cannot replace it, the token is removed instead of destroyed.<sup>4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> &ldquo;When you exceed the number of plastic infantry/fighters available, are unaccompanied tokens removed or destroyed? A: Removed.&rdquo;</li>
        </ul></li>
    </ol>
