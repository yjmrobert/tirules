    <ol class="note">
    <li>If there are multiple abilities that players wish to resolve at the same time during the action phase, initiative order will determine the order they are resolved in. See the <a href="/R_abilities">abilities page</a> for more details.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 1.19: &ldquo;If there are multiple abilities that players wish to resolve at the same time during the action phase, each player takes a turn resolving an ability in initiative order, beginning with the active player.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When several players want to resolve abilities at the same time, who goes first?&rdquo;: &ldquo;In the action phase, the active player goes first, then the other players in initiative order.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (kaiteinomen, Sep 20, 2017): &ldquo;All timing conflicts are intended to follow the same rules for resolution&mdash;in initiative order, beginning with the active player.&rdquo;</li>
        </ul></li>
    <li>The initiative order of all strategy cards is:<sup>1,3</sup>
