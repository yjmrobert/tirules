<h2 id="sundered"><a href="https://twilight-imperium.fandom.com/wiki/The_Crimson_Rebellion#Faction_Abilities:~:text=Sundered">Sundered</a></h2>
    <ol class="note">
    <li><sc>Sundered</sc> only prevents the Rebellion player&rsquo;s ships from moving through wormholes other than epsilon wormholes. Other wormholes still make systems adjacent for the Rebellion player for all other purposes, such as <a href="/R_space_cannon"><sc>Space Cannon</sc></a>, neighbors, objectives, action cards, and the ability of the Exile.<sup>2,6,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Using Wormholes&rdquo;: &ldquo;They can&rsquo;t move through them. Other things are fine.&rdquo;</li>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;Does the Crimson Rebellion&rsquo;s inability to use wormholes remove wormhole adjacency?&rdquo;: &ldquo;No &mdash; it only stops them moving through wormholes, as players relay from the designer. Adjacency still counts for neighbors, breach placement, Space Cannon and objectives.&rdquo; covers most listed purposes; action cards and Exile not mentioned.</li>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus, Crimson Rebellion &ldquo;cannot use wormholes&rdquo;: &ldquo;Crimson are unable to move through wormholes. All other uses are permitted including PDS, Neighbors, placing Breaches, etc.&rdquo;</li>
        </ul></li>
    <li>The Rebellion player may use the <a href="/F_creuss">Creuss</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Faction_Promissory_Note:~:text=Creuss%20IFF"><i>Creuss IFF</i></a> promissory note, but their ships still cannot move through <a href="/F_creuss">Creuss</a> wormholes.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Can they use the Creuss IFF? A: Yes, they still may not move through the Creuss wormholes though.&rdquo;</li>
        </ul></li>
    <li>The Rebellion player may use the <a href="/F_creuss">Creuss</a> player&rsquo;s agent, <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Leaders:~:text=Emissary%20Taivra">Emissary Taivra</a>, and the <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Lost%20Star%20Chart"><i>Lost Star Chart</i></a> action card.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Can they use the Creuss agent or the Lost Star Charts action card? A: Yes&rdquo;</li>
        </ul></li>
    <li>The <a href="https://twilight-imperium.fandom.com/wiki/Agenda_Cards#Directives:~:text=Wormhole%20Reconstruction"><i>Wormhole Reconstruction</i></a> agenda does not override <sc>Sundered</sc>. However, the systems it makes adjacent are adjacent for movement, and the Rebellion player&rsquo;s ships do not need to use the wormholes to move between them.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Does Wormhole Reconstruction override SUNDERED? A: No, but those systems are adjacent for movement, they do not need to use the worm holes so functionally it overrides Sundered.&rdquo;</li>
        </ul></li>
    <li><sc>Sundered</sc> is a state&ndash;based effect, and resolves before another player would gain control of Ahk Creuxx, even if that player is the active player.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Sundered is a state-based effect which would trigger prior to gain control.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="incursion"><a href="https://twilight-imperium.fandom.com/wiki/The_Crimson_Rebellion#Faction_Abilities:~:text=Incursion">Incursion</a></h2>
    <ol class="note">
    <li>Breaches are not wormholes.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If a player has a ship in a system containing multiple breaches at the end of the status phase, they may remove any or all of them.<sup>2,6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How do Crimson Rebellion breaches work?&rdquo;: &ldquo;At the end of the status phase a player with ships there may remove any or all active breaches.&rdquo;</li>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;If a system contains multiple breaches during the status phase, how many can be removed &hellip;? A: All active breaches can be removed.&rdquo;</li>
        </ul></li>
    <li>If the Rebellion player has no more breach tokens in their reinforcements, and an ability instructs them to place a breach, they may remove an inactive breach from the game board and place that.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 16: &ldquo;If the component limit of breaches is reached, inactive breaches can be moved from elsewhere to resolve the effect.&rdquo;</li>
        </ul></li>
    <ol><li>Active breaches cannot be removed in this manner.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Same passage: &ldquo;active breaches, however, must be removed or flipped before&rdquo; they can be moved.</li>
        </ul></li></ol>
    <li>If the Rebellion player is eliminated, breach tokens remain in play, and active breaches remain adjacent to each other. Inactive breaches may be removed from the game board.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Is the Sever token removed &hellip; if the Crimson Rebellion player is eliminated &hellip;? What about the breach tokens? A: &hellip; Breach tokens also remain in play and active breaches remain adjacent. Inactive breaches may be removed.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="the-sorrow"><a href="https://twilight-imperium.fandom.com/wiki/The_Crimson_Rebellion#Faction_Abilities:~:text=The%20Sorrow">The Sorrow</a></h2>
