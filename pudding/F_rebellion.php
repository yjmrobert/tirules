    <li>If the Rebellion player is eliminated, their home system still destroys units that are placed or moved into it, and their faction sheet remains in play.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Does the Crimson home system still destroy units that are placed or moved into it after the Crimson player is eliminated. A: Yes and the Crimson faction sheet remains in play.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="sever"><a href="https://twilight-imperium.fandom.com/wiki/The_Crimson_Rebellion#Faction_Promissory_Note:~:text=Sever">Sever</a> <sub>(Promissory Note)</sub></h2>
    <ol class="note">
    <li><i>Sever</i> only prevents movement through the wormhole. Adjacency, <a href="/R_space_cannon"><sc>Space Cannon</sc></a>, the <a href="/F_creuss">Creuss</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Faction_Abilities:~:text=Quantum%20Entanglement"><sc>Quantum Entanglement</sc></a> and <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Faction_Abilities:~:text=Slipstream"><sc>Slipstream</sc></a> faction abilities, the <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Ghost%20Ship"><i>Ghost Ship</i></a> action card and the <a href="https://twilight-imperium.fandom.com/wiki/Objectives#Twilight_Imperium_Fourth_Edition_4:~:text=Become%20the%20Gatekeeper"><i>Become the Gatekeeper</i></a> objective are unaffected.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Sever (Promissory Note): Does the wormhole still count for other non-movement game effects? &hellip; A: Blocks movement. Adjacency, PDS, Ghost Ship, Become the Gatekeeper, SLIPSTREAM are all unaffected.&rdquo;</li>
        </ul></li>
    <li><i>Sever</i> affects all wormholes in the system, not just the one the token is placed on.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;If there are multiple wormholes in a system &hellip;, does Severing one block them all? A: All wormholes in the system.&rdquo;</li>
        </ul></li>
    <li>If the Rebellion player is eliminated, the <i>Sever</i> token and promissory note remain in play until the note expires at the end of the status phase, when they are removed from the game.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Is the Sever token removed at the end of the status phase if the Crimson Rebellion player is eliminated &hellip;? A: The Sever token and promissory note remain in place until the note removes them in the status phase.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="subatomic-splicer"><a href="https://twilight-imperium.fandom.com/wiki/The_Crimson_Rebellion#Faction_Technologies:~:text=Subatomic%20Splicer">Subatomic Splicer</a> <sub>(Technology)</sub></h2>
    <ol class="note">
    <li>The Rebellion player cannot use <i>Subatomic Splicer</i> to produce ships while another player&rsquo;s ships are in their home system.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Subatomic Splicer (Technology): &lsquo;A player cannot produce ships in a system that contains other players&rsquo; ships&rsquo;. Does this apply to Subatomic Splicer? A: It does apply.&rdquo;</li>
        </ul></li>
    <li>The produced ships must still be paid for.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR FAQ: &ldquo;a unit that is produced must always be paid for.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="exile"><a href="https://twilight-imperium.fandom.com/wiki/The_Crimson_Rebellion#Destroyer:~:text=Exile">Exile</a> <sub>(Unit)</sub></h2>
    <ol class="note">
    <li>The destroyer must be on the game board when the combat ends in order to place the breach. If the destroyer was in the active system, and was destroyed in the space combat, it cannot be used to place a breach.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How do Crimson Rebellion breaches work?&rdquo;: &ldquo;A breach goes in the combat&rsquo;s system at the end of combat &hellip; if one of your destroyers is in range then.&rdquo;</li>
        </ul></li>
    <li>A breach may be placed after a space combat and/or a ground combat.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> Same entry: &ldquo;at the end of combat.&rdquo; Not limited to space combat.</li>
        </ul></li>
    <li>The Rebellion player may place a breach with the ability of an Exile at the end of a combat against neutral units.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Can the Crimson destroyer, Exile, place a breach at the end of a combat with neutral units? A: Yes&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="quietus"><a href="https://twilight-imperium.fandom.com/wiki/The_Crimson_Rebellion#Flagship:~:text=Quietus">Quietus</a> <sub>(Flagship)</sub></h2>
    <ol class="note">
    <li>The <i>Quietus</i> removes only the unit abilities from other players&rsquo; units; any text abilities are unaffected.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <ol>
        <li>Text abilities that rely on unit abilities, such as the space dock II text ability that defines &ldquo;X&rdquo; in that unit&rsquo;s <a href="/R_production"><sc>Production X</sc></a> ability, will have no effect.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
        <li>If a unit loses its <a href="/R_deploy"><sc>Deploy</sc></a> ability, then the text that describes how that unit&rsquo;s <a href="/R_deploy"><sc>Deploy</sc></a> ability is used will have no effect.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>
    </ol>

<h2 id="ahk-ravin"><a href="https://twilight-imperium.fandom.com/wiki/The_Crimson_Rebellion#Leaders:~:text=Ahk%20Ravin">Ahk Ravin</a> <sub>(Agent)</sub></h2>
    <ol class="note">
    <li>Ahk Ravin is a swap, not a move. This means units will not trigger gravity rift rolls and the ability cannot be used to swap with a <a href="/F_saar">Saar</a> player&rsquo;s space dock.<sup>6,9</sup>
        <ul>
        <li><b>Implicit</b>: <sup>6</sup> Community consensus, Crimson agent swapping out of a gravity rift: &ldquo;Swapping is not movement, so no roll is required.&rdquo; only the gravity-rift half is supported; Saar Spacedock claim is not in this source.</li>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A: &ldquo;Crimson Agent&rdquo;: &ldquo;Does not have to abide by anything movement related. Does not work on saar docks.&rdquo;</li>
        </ul></li>
    <li>If the Rebellion player transports ground forces during the swap, those ground forces will be placed in the space area of their destination system. They cannot be committed to planets in that system until and unless a tactical action is resolved in that system.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;After a Crimson Rebellion swap, are the ships locked, and can moved units invade?&rdquo;: &ldquo;A swap is a component action, not a tactical action, so there&rsquo;s no invasion unless the ability says so.&rdquo;</li>
        </ul></li>
    <li>Either of the swapped ships may be a fighter.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found. Twilight Imperium Wiki FAQ (not a numbered source), Crimson Rebellion: &ldquo;Can the Rebellion agent Ahk Ravin be used to swap a non-fighter ship with a fighter? A: Ahk Ravin does not specify non-fighter ship, so yes.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="ahk-siever"><a href="https://twilight-imperium.fandom.com/wiki/The_Crimson_Rebellion#Leaders:~:text=Ahk%20Siever">Ahk Siever</a> <sub>(Commander)</sub></h2>
    <ol class="note">
    <li>Ahk Siever triggers off of combats with neutral units.<sup>6,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Does the Crimson commander, Ahk Siever, work on combats with neutral units? A: Yes, the commander triggers on any combat involving players (which is all combats).&rdquo;</li>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Crimson Commander&rdquo;: &ldquo;Does this trigger at the end of a combat with the neutral forces? Can it be used in the same combat that unlocked it? &hellip; A: Yes to both.&rdquo;</li>
        </ul></li>
    <li>If Ahk Siever is unlocked by placing a breach token into a system containing another player&rsquo;s unit at the end of a combat with the ability of an Exile, the Rebellion player will resolve the commodity ability of Ahk Siever from that same combat.<sup>9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Crimson Commander&rdquo;: &ldquo;Can it be used in the same combat that unlocked it? &hellip; A: Yes to both.&rdquo;</li>
        </ul></li>
    <li>The Rebellion player does not have to be a participant in the combat to gain or convert commodities.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If there are multiple combats in one turn, the Rebellion player may gain or convert a commodity for each. This includes for each ground combat on a separate planet.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>

