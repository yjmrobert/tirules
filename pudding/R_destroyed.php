<p>The source text behind each note on <a href="/R_destroyed">Destroyed</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>A ship removed by a <a href="/R_gravity_rift">gravity rift</a> is not destroyed.<sup>2,10</sup>
        <ul>
        <li><b>Explicit</b>: <sup>10</sup> Codex I: &ldquo;units that fail to survive the roll are removed from the board and returned to players&rsquo; reinforcements rather than being destroyed.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When a carrier leaves a gravity rift &hellip;?&rdquo;: &ldquo;Units lost this way are removed rather than destroyed.&rdquo;</li>
        </ul></li>
    <li>Units that are removed due to <a href="/R_capacity">capacity</a> limits are not destroyed. For example, removed Infantry II units do not roll for the Infantry II unit upgrade&rsquo;s ability.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;After ships stop moving, are fighters and ground forces still tied to the ship that carried them?&rdquo;: &ldquo;Units removed for lack of capacity are removed, not destroyed, so Infantry II doesn&rsquo;t trigger.&rdquo;</li>
        </ul></li>
    <li>Ships that are removed because they exceed a player&rsquo;s <a href="/R_fleet_pool">fleet pool</a> limit are not destroyed.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 61.9a: &ldquo;Forcing a player to remove a unit from the board by reducing the number of command tokens in their fleet pool is not treated as destroying a unit.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 37.3: &ldquo;If at any time the number of a player&rsquo;s non-fighter ships in a system exceeds the number of tokens in that player&rsquo;s fleet pool, they choose and remove excess ships in that system, returning those units to their reinforcements.&rdquo;</li>
        </ul></li>
    <li>If a player has a <a href="/R_fighter_tokens">fighter token</a> or <a href="/R_infantry_tokens">infantry token</a> that is not accompanied by a plastic piece of the same type and cannot replace it, the token is removed instead of destroyed.<sup>4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;When you exceed the number of plastic infantry/fighters available, are unaccompanied tokens removed or destroyed? A: Removed.&rdquo;</li>
        </ul></li>
    <li>Units destroyed by <a href="/R_space_cannon">space cannon</a> or <a href="/R_bombardment">bombardment</a> rolls are not destroyed during combat. Units destroyed by <a href="/R_anti_fighter_barrage">anti&ndash;fighter barrage</a> rolls are destroyed during combat.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Does the Vuil&rsquo;raith Devour ability capture units destroyed by Space Cannon or Bombardment?&rdquo;: &ldquo;No &mdash; those happen outside space and ground combat, so Devour doesn&rsquo;t see them; Anti-Fighter Barrage is part of combat and counts.&rdquo;</li>
        </ul></li>
    </ol>
