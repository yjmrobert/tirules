<p>The source text behind each note on <a href="/R_entropic_scars">Entropic Scars</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>An entropic scar is an anomaly that affects unit abilities and faction technologies.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge reference: &ldquo;ENTROPIC SCAR (ANOMALY) ✦ UNIT ABILITIES cannot be used by or against units inside of an entropic scar.&rdquo;</li>
        </ul></li>
    <li>A unit in an entropic scar cannot use unit abilities.<sup>2,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Entropic Scar: &ldquo;(Sustain Damage, Production, Planetary Shield, Space Cannon, Bombardment, Deploy, and Anti-Fighter Barrage) cannot be used by or against units inside of an entropic scar.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Does the Arborec commander work with a Letani in an Entropic Scar?&rdquo;: &ldquo;the scar stops unit abilities being used but doesn&rsquo;t remove them.&rdquo;</li>
        </ul></li>
    <ol>
        <li>Only unit abilities are removed; text abilities are unaffected.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Entropic Scar: &ldquo;Text abilities are unaffected.&rdquo;</li>
        </ul></li>
        <li>If a unit loses its <a href="https://twilight-imperium.fandom.com/wiki/Deploy"><sc>Deploy</sc></a> ability, then the text that describes how that unit&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/Deploy"><sc>Deploy</sc></a> ability is used will have no effect.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>
    <li>A unit outside of an entropic scar cannot use unit abilities against units that are in an entropic scar.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Entropic Scar: unit abilities &ldquo;cannot be used by or against units inside of an entropic scar.&rdquo;</li>
        </ul></li>
    <li>Wormhole tokens that would be placed in an entropic scar are discarded instead.<sup>6,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Entropic Scar: &ldquo;wormholes that would be placed inside of an entropic scar are discarded instead.&rdquo;</li>
        <li><b>Explicit</b>: <sup>6</sup> &ldquo;Wormhole Generator will exhaust and place a token, which will then be discarded.&rdquo;</li>
        </ul></li>
    <li>At the start of the status phase, a player with ships in an entropic scar may spend a command token from their strategy pool to gain one of their faction&ndash;specific technologies.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Entropic Scar: &ldquo;At the start of the status phase, a player that has ships in an entropic scar can spend a token from their strategy pool to gain one of their faction-specific technologies.&rdquo;</li>
        </ul></li>
    <ol>
        <li>A player need not meet the prerequisites for the technology they gain this way.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;If an effect lets me research a technology, do I pay for it?&rdquo;: &ldquo;&rsquo;Gain&rsquo; is different from &lsquo;research&rsquo;: gaining ignores prerequisites.&rdquo;</li>
        </ul></li>
        <li>If a player has ships in two (or more) entropic scars, they may spend two command tokens from their strategy pool at the start of the status phase to gain both of their faction&ndash;specific technologies.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> &ldquo;If you have ships in both Entropic Scar anomalies at the start of the Status phase, can you opt to gain both your faction techs? A: Yes, each Entropic Scar&rsquo;s ability can be resolved as different components.&rdquo;</li>
        </ul></li>
    </ol>
    <li>If an exploration card would place a gamma wormhole token in an entropic scar, the card is still purged as part of its resolution, and the token is discarded.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> &ldquo;If they would place a gamma wormhole in an entropic scar, are these cards still purged? A: The exploration card is still purged as part of its resolution. The token though is discarded.&rdquo;</li>
        </ul></li>
    </ol>
