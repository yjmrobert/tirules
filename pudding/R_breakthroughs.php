<p>The source text behind each note on <a href="/R_breakthroughs">Breakthroughs</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>A breakthrough is a faction specific card.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 4: &ldquo;unlock powerful new abilities via faction-specific breakthroughs.&rdquo;</li>
        </ul></li>
    <li>A breakthrough is commonly gained through an expedition. There are other game effects that can gain a player their faction&rsquo;s breakthrough.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 8: &ldquo;The first time a player claims one of the expedition slices, they gain their faction&rsquo;s breakthrough.&rdquo;</li>
        </ul></li>
    <li>When a player gains their faction&rsquo;s breakthrough, they perform a breakthrough roll, which may cause The Fracture to enter play.<sup>2,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 5: &ldquo;Roll a die on gaining breakthrough; on a roll of 1 or 10, that player puts The Fracture into play.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Does the Crimson Rebellion&rsquo;s starting breakthrough trigger the Fracture roll?&rdquo;: &ldquo;the roll triggers whenever a player gains a breakthrough from any source.&rdquo;</li>
        </ul></li>
    <li>A breakthrough has 1 or more abilities, and a synergy (other than for the <a href="/F_nekro">Nekro</a> player).<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 9: &ldquo;a breakthrough that does not have synergy (as is the case with the Nekro Virus faction).&rdquo;</li>
        </ul></li>
    <ol><li>If a breakthrough has a passive ability and an exhaust ability, the passive ability always remains in effect, even when the breakthrough is exhausted.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Are breakthroughs technologies, and do their passive abilities work while exhausted?&rdquo;: &ldquo;Their passive abilities keep working while exhausted.&rdquo;</li>
        </ul></li></ol>
    <li>A breakthrough itself is not a technology; it alone cannot be used to meet a prerequisite when researching a technology, nor can it alone be used to meet the technology requirement of an objective.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> Same entry: &ldquo;They aren&rsquo;t technologies, so a breakthrough like Mentak&rsquo;s Corsair doesn&rsquo;t count as a unit upgrade or for anything that cares about technologies.&rdquo;</li>
        </ul></li>
    <li>The <a href="/F_rebellion">Rebellion</a> player gains their breakthrough as a starting component, which triggers a breakthrough roll during setup; The Fracture may be in play from the start of the game.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Does the Crimson Rebellion&rsquo;s starting breakthrough trigger the Fracture roll?&rdquo;: &ldquo;Yes &mdash; you gain starting components at setup &hellip; a player reports the developer saying the game can start with the Fracture in play.&rdquo;</li>
        </ul></li>
    </ol>
