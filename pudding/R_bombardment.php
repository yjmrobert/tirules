<h2>Rules Reference</h2>
    <ul>
    <li>(Thunder&rsquo;s Edge) If a player makes a bombardment roll against a planet that contains <a href="/R_coexistence">coexisting</a> units, that player chooses which units with <sc>Bombardment</sc> are bombarding which other player&rsquo;s units, and rolls against each player separately.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;Coexisting units can be bombarded. When a player makes a bombardment roll against a planet, they choose which of their units with bombardment are bombarding which other player&rsquo;s units, rolling against each player separately.&rdquo;</li>
        </ul></li>
    </ul>

<h2>Notes</h2>
    <ol class="note">
    <li>Only the active player may bombard.<sup>1,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 15.1: &ldquo;The active player chooses which planet each of their units that has a &lsquo;Bombardment&rsquo; ability will bombard.&rdquo;</li>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;only the active player can use BOMBARDMENT.&rdquo;</li>
        </ul></li>
    <li>The <b>Bombardment</b> step happens outside of combat. No combat effects may affect a bombardment roll.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do Morale Boost, faction modifiers and rerolls affect &hellip; Bombardment &hellip;?&rdquo;: &ldquo;No &mdash; only rolls made against a unit&rsquo;s combat value are combat rolls.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 15.1c: &ldquo;Game effects that reroll, modify, or otherwise affect combat rolls do not affect bombardment rolls.&rdquo;</li>
        </ul></li>
    <ol><li>A player cannot score a secret objective that requires them to win a combat or similar by destroying units during the <b>Bombardment</b> step.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do Space Cannon, Bombardment or landing on an empty planet count as winning a combat for objectives?&rdquo;: &ldquo;No &mdash; &hellip; bombarding away all defenders &hellip; involves no combat.&rdquo;</li>
        </ul></li></ol>
    <li>A single planet must be chosen for each unit with the <sc>Bombardment</sc> ability; any hits generated by that unit will be assigned to units on that planet.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 15.1d: &ldquo;a player must declare which planet a unit is bombarding before making a bombardment roll.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can one ship bombard several planets, or split its dice between them?&rdquo;: &ldquo;a unit bombards a single planet with all its dice.&rdquo;</li>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;These hits can only be assigned by the bombarded player to ground forces on the planet being bombarded.&rdquo;</li>
        </ul></li>
    <li>A player may choose not to use the <sc>Bombardment</sc> abilities of their units during their tactical actions. However, if they choose to use the <sc>Bombardment</sc> ability, they must use the <sc>Bombardment</sc> ability of each unit in the active system.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <ol><li>Say a player had three dreadnoughts in the active system, and owned the <a href="https://twilight-imperium.fandom.com/wiki/Warfare_Technologies#Plasma_Scoring"><i>Plasma Scoring</i></a> technology. They would be able to roll their choice of zero, three, or four dice when resolving their <sc>Bombardment</sc> ability.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li></ol>
    <li>Mechs may use their <a href="/R_sustain_damage"><sc>Sustain Damage</sc></a> ability to cancel a hit produced by a bombardment roll.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can a ship use Sustain Damage against Space Cannon hits?&rdquo;: &ldquo;Yes &mdash; Sustain Damage can cancel any hit produced against the unit.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 87.4: &ldquo;A unit can use its &lsquo;Sustain Damage&rsquo; ability any time a hit is produced against it.&rdquo;</li>
        </ul></li>
    <li>The &ldquo;0&rdquo; side of the d10 represents a result of 10.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Are the &lsquo;0&rsquo; faces of the ten-sided dice &hellip; intended to represent the result of a &lsquo;10&rsquo;? A: Yes, the &lsquo;0&rsquo; face is a &lsquo;10&rsquo; result.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Does the 0 on the ten-sided die count as 0 or 10?&rdquo;: &ldquo;10 &mdash; the Living Rules Reference FAQ confirms the 0 face is a 10.&rdquo;</li>
        </ul></li>
    </ol>
