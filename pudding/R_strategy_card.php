<h2>Notes</h2>
    <ol class="note">
    <li>During three&ndash; and four&ndash;player games, each player will choose two strategy cards during the strategy phase.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How do strategy cards work in three- and four-player games?&rdquo;: &ldquo;Each player picks two strategy cards, in a second pass of the selection.&rdquo;</li>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;After each player has chosen one strategy card during the strategy phase, players repeat the strategy card selection process until each player has chosen a second strategy card.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 82.2a: &ldquo;During three- and four-player games, a player must resolve the strategic action on each of their chosen strategy cards before they can pass.&rdquo;</li>
        </ul></li>
    <ol><li>Players will use the lower of the two initiative numbers on their strategy cards to determine the initiative order.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;Each player&rsquo;s lowest-numbered strategy card is used to determine their placement in initiative order.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;With two strategy cards, which one sets my initiative, and must I use the lower card first?&rdquo;: &ldquo;Only your lower-numbered card sets your initiative.&rdquo;</li>
        <li><b>Explicit</b>: <sup>1</sup> LRR 48.3: &ldquo;When playing with three or four players, a player&rsquo;s initiative is determined only by their lowest-numbered strategy card.&rdquo;</li>
        </ul></li></ol>
    <li>A player with two strategy cards may perform the strategic actions of those cards in either order. They still take only one action per turn.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;With two strategy cards, which one sets my initiative, and must I use the lower card first?&rdquo;: &ldquo;You still take one turn at a time like everyone else, never two in a row, and you may use either card first.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How many actions do I take per turn, and in what order must I use action types?&rdquo;: &ldquo;Exactly one action per turn &hellip; You may use them in any order over the round.&rdquo;</li>
        </ul></li>
    </ol>
