<header><h1>Producing Units: Proof</h1></header>
<article>
<p>The source text behind each note on <a href="/R_producing_units">Producing Units</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Rules Reference</h2>
    <ul>
    <li>(Thunder&rsquo;s Edge) Units that are <a href="/R_coexistence">coexisting</a> on a planet can produce ground forces there, but cannot produce ships.<sup>9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence and PRODUCTION&rdquo;: &ldquo;Coexisting units can produce ground forces but are always blockaded and cannot produce ships.&rdquo;</li>
        </ul></li>
    </ul>

<h2>Notes</h2>
    <ol class="note">
    <li>Whenever a unit is produced, its cost must be paid, unless the effect that is producing the unit explicitly says otherwise.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do units &lsquo;placed&rsquo; by an effect cost resources, and do they count as producing?&rdquo;: &ldquo;An effect that says &lsquo;produce&rsquo; means you pay the cost unless it says otherwise.&rdquo;</li>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;a unit that is produced must always be paid for.&rdquo;</li>
        </ul></li>
    <ol><li>Units that are placed or gained by an effect, rather than produced, are free and do not count as being produced; for example, ships placed with the <a href="/F_muaat">Muaat</a> player&rsquo;s <sc>Star Forge</sc> ability.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do units &lsquo;placed&rsquo; by an effect cost resources, and do they count as producing?&rdquo;: &ldquo;&rsquo;Place&rsquo; or &lsquo;gain&rsquo; is free and isn&rsquo;t producing, so Muaat&rsquo;s Star Forge doesn&rsquo;t count as producing and doesn&rsquo;t trigger Magmus Reactor&rsquo;s trade good.&rdquo;</li>
        </ul></li></ol>
    <li>A player cannot produce one fighter and one infantry for one resource.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 67.2: &ldquo;If the cost is accompanied by two icons&mdash;typically for fighters and infantry&mdash;a player produces two of that unit for that cost.&rdquo;</li>
        </ul></li>
    <li>If an effect allows a player to produce a unit of a specific type, then factional variations do not prevent that player from producing that type of unit.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;Do faction units like the Muaat Prototype War Sun count as their base unit type?&rdquo;: &ldquo;a faction unit counts as its base unit type for every purpose.&rdquo;</li>
        </ul></li>
    <li>If a player removes a unit in order to place it, because they have none of that unit type in their reinforcements, that unit is placed undamaged.<sup>4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;If it is produced, placed, or replaced which would require a remove and place it is no longer damaged.&rdquo;</li>
        </ul></li>
    </ol>
