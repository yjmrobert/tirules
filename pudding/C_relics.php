<h2 id="book-of-latvinia"><a href="https://twilight-imperium.fandom.com/wiki/Relics#Codex_IV:~:text=Book%20of%20Latvinia">Book of Latvinia</a></h2>
    <ol class="note">
    <li>If a player owns all technologies without prerequisites when they draw the <i>Book of Latvinia</i>, they will not research any technologies.<sup>11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>11</sup> Codex IV, Book of Latvinia: &ldquo;When you gain this card, research up to 2 technologies that have no prerequisites.&rdquo; &ldquo;Up to&rdquo; allows zero.</li>
        </ul></li>
    <ol><li>If a player owns all&ndash;but&ndash;one technologies without prerequisites when they draw the <i>Book of Latvinia</i>, they will research only that one technology.<sup>11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>11</sup> Codex IV, Book of Latvinia: &ldquo;When you gain this card, research up to 2 technologies that have no prerequisites.&rdquo; &ldquo;Up to&rdquo; allows one.</li>
        </ul></li></ol>
    <li>A player cannot gain a technology with a prerequisite by ignoring that prerequisite, such as by exhausting a planet with a technology specialty.<sup>6,11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Can a tier one &hellip; technology be researched when drawing the Book of Latvinia by ignoring the prerequisite with a tech skip &hellip;? A: No, only techs with no printed prerequisites may be researched.&rdquo;</li>
        <li><b>Implicit</b>: <sup>11</sup> Codex IV, Book of Latvinia: &ldquo;technologies that have no prerequisites&rdquo; Book of Latvinia card text; only techs with no printed prerequisites qualify.</li>
        </ul></li>
    <li>If the <a href="/F_nekro">Nekro</a> player draws the <i>Book of Latvinia</i>, they will gain six command tokens and zero technologies, even if they own all technologies without prerequisites.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>When a player uses the component action of the <i>Book of Latvinia</i>, it is purged, regardless of which outcome is resolved.<sup>11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>11</sup> Codex IV, Book of Latvinia: &ldquo;ACTION: Purge this card; if you control planets that have all 4 types of technology specialties, gain 1 victory point. Otherwise, gain the speaker token.&rdquo;</li>
        </ul></li>
    <li>If a player uses the component action of the <i>Book of Latvinia</i> when they control planets with each type of technology specialty, they mandatorily gain a victory point; they cannot choose instead to gain the speaker token.<sup>11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>11</sup> Same card: &ldquo;if you control planets that have all 4 types of technology specialties, gain 1 victory point. Otherwise, gain the speaker token.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="circlet-of-the-void"><a href="https://twilight-imperium.fandom.com/wiki/Relics#Codex_IV:~:text=Circlet%20of%20the%20Void">Circlet of the Void</a></h2>
    <ol class="note">
    <li>The player that owns <i>Circlet of the Void</i> may move through or into supernovae and/or asteroid fields.<sup>11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>11</sup> Codex IV, Circlet of the Void: &ldquo;Your units do not roll for gravity rifts, and you ignore the movement effects of other anomalies.&rdquo;</li>
        </ul></li>
    <li>The player that owns <i>Circlet of the Void</i> may move through nebulae, and their ships in nebulae do not have their movement values reduced.<sup>11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>11</sup> Codex IV, Circlet of the Void: &ldquo;Your units do not roll for gravity rifts, and you ignore the movement effects of other anomalies.&rdquo;</li>
        </ul></li>
    <li>The player that owns <i>Circlet of the Void</i> still applies the movement bonus to their ships that will move through gravity rifts.<sup>11</sup>
        <ul>
        <li><b>Implicit</b>: <sup>11</sup> Codex IV, Circlet of the Void: &ldquo;Your units do not roll for gravity rifts, and you ignore the movement effects of other anomalies.&rdquo; Only the roll is removed for gravity rifts.</li>
        </ul></li>
    <li>The player that owns <i>Circlet of the Void</i> will still ignore anomaly movement effects and not roll for gravity rifts if <i>Circlet of the Void</i> is exhausted.<sup>11</sup>
        <ul>
        <li><b>Implicit</b>: <sup>11</sup> The Circlet&rsquo;s first sentence is a passive ability; only the ACTION requires exhausting the card.</li>
        </ul></li>
    </ol>

