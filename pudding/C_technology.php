<h2 id="antimass-deflectors"><a href="https://twilight-imperium.fandom.com/wiki/Propulsion_Technologies#Antimass_Deflectors">Antimass Deflectors</a></h2>
    <ol class="note">
    <li>The &minus;1 applies to space cannon rolls during both the <b>Space Cannon Offense</b> and <b>Space Cannon Defense</b> steps.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;What does Antimass Deflectors do?&rdquo;: &ldquo;other players&rsquo; Space Cannon rolls get -1 against all your units, ground forces in Space Cannon Defense included, wherever they are&rdquo; -1 applies to all Space Cannon rolls against the player, Defense explicitly included.</li>
        </ul></li>
    <li>If a player gains then loses the <i>Antimass Deflectors</i> technology, their units may remain in and move out of any <a href="/R_asteroid_field">asteroid fields</a> they are currently in, but cannot move additional units into or through.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;If I lose Antimass Deflectors while my ships sit in an asteroid field, or place units in an anomaly, what happens?&rdquo;: &ldquo;Nothing &mdash; anomaly rules restrict moving into or through them, not being in them or moving out. Ships already there stay and may leave normally&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="dark-energy-tap"><a href="https://twilight-imperium.fandom.com/wiki/Propulsion_Technologies#Dark_Energy_Tap">Dark Energy Tap</a></h2>
    <ol class="note">
    <li>A ship may be moved into the system containing the frontier token during the same action that it is explored.<sup>8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook, Dark Energy Tap: &ldquo;After you perform a tactical action in a system that contains a frontier token, if you have 1 or more ships in that system, explore that token.&rdquo;</li>
        </ul></li>
    <li>Exploring the frontier token happens at the end of the tactical action. Notably, this is after the <b>Space Cannon Offense</b> and/or <b>Space Combat</b> steps.<sup>2,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When does Dark Energy Tap explore frontier tokens, and is it mandatory?&rdquo;: &ldquo;After the tactical action ends, and only if your ships are still there, so it comes after Space Cannon Offense and production.&rdquo;</li>
        <li><b>Implicit</b>: <sup>8</sup> PoK rulebook card text: &ldquo;After you perform a tactical action.&rdquo;</li>
        </ul></li>
    <li>Exploring the frontier token is mandatory if the player has a ship in the active system at the end of the tactical action.<sup>2,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;It has no &lsquo;may&rsquo;, so it is mandatory.&rdquo;</li>
        <li><b>Implicit</b>: <sup>8</sup> PoK rulebook card text: &ldquo;if you have 1 or more ships in that system, explore that token.&rdquo;</li>
        </ul></li>
    <li>When a player gains <i>Dark Energy Tap</i>, they do not immediately explore any frontier tokens in systems containing their ships. They must activate those systems to explore those tokens.<sup>8</sup>
        <ul>
        <li><b>Implicit</b>: <sup>8</sup> PoK rulebook card text: &ldquo;After you perform a tactical action in a system that contains a frontier token.&rdquo; Gaining the technology is not a trigger.</li>
        </ul></li>
    <ol><li>If a player moves or places a ship into a system outside of a tactical action, they cannot explore a frontier token in that system.<sup>2,8</sup>
        <ul>
        <li><b>Implicit</b>: <sup>8</sup> PoK rulebook card text: the trigger is &ldquo;After you perform a tactical action.&rdquo;</li>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal: &ldquo;After the tactical action ends, and only if your ships are still there.&rdquo;</li>
        </ul></li></ol>
    <li>The <a href="/F_saar">Saar</a> player cannot explore a frontier token with a <a href="https://twilight-imperium.fandom.com/wiki/Technology#Faction_Technology:~:text=Floating%20Factory">Floating Factory</a>. However, if they produce a ship during the <b>Production</b> step, they will be able to use that ship to explore the token.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>A player cannot use <i>Dark Energy Tap</i> to retreat into a system that contains another player&rsquo;s units, including ground forces and structures on planets.<sup>8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook, Dark Energy Tap: &ldquo;Your ships can retreat into adjacent systems that do not contain other players&rsquo; units.&rdquo;</li>
        </ul></li>
    </ol>

