        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;&rsquo;Plasma Scoring&rsquo; only grants one additional die for each &lsquo;Bombardment&rsquo; or &lsquo;Space Cannon&rsquo; roll.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How many extra dice does Plasma Scoring add &hellip;?&rdquo;: &ldquo;One extra die per use of the ability, not per unit or per planet.&rdquo;</li>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play, Plasma Scoring: &ldquo;When 1 or more of your units use BOMBARDMENT or SPACE CANNON, 1 of those units may roll 1 additional die.&rdquo;</li>
        </ul></li>
    <ol>
        <li>During an invasion in a system with multiple planets, only one unit will add a dice to its bombardment roll.<sup>1,2,6</sup>
