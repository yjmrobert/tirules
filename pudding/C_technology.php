<h2 id="fleet-logistics"><a href="https://twilight-imperium.fandom.com/wiki/Propulsion_Technologies#Fleet_Logistics">Fleet Logistics</a></h2>
    <ol class="note">
    <li>A player may use the ability of <i>Fleet Logistics</i> the same turn they gain it.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can I use a technology right after researching it, such as Fleet Logistics?&rdquo;: &ldquo;Yes. Research Fleet Logistics with the Technology primary on your turn, and once that strategic action, secondaries included, is done you may take a second action that turn.&rdquo;</li>
        </ul></li>
    <li>If a player&rsquo;s turn is ended by a game effect, they cannot use <i>Fleet Logistics</i> to perform an additional action.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;When must Xxcha use Nullification Field&rdquo;: &ldquo;Once the turn ends, nothing more happens in it.&rdquo;</li>
        </ul></li>
    <li>A player cannot use <i>Fleet Logistics</i> to pass on the same turn they performed an action.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 3.1: &ldquo;During a player&rsquo;s turn, they may perform one of the following three types of actions: a strategic action, a tactical action, or a component action.&rdquo; LRR 3.2: &ldquo;If a player cannot perform an action, they must pass.&rdquo; Passing is not one of the three actions, so an additional action cannot be a pass.</li>
        </ul></li>
    <li>If a player&rsquo;s second action would be to use a component action to play an action card, and that card is canceled, they are not required to perform an alternate second action on that turn.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;If my component action card is cancelled by Sabotage, have I used my action for the turn?&rdquo;: &ldquo;If it was the optional extra action from Fleet Logistics, you can just end your turn.&rdquo;</li>
        </ul></li>
    <li>If a player&rsquo;s first action is a strategic action, the other players resolve the secondary ability of that strategy card before the player performs their second action.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;What does Fleet Logistics allow?&rdquo;: &ldquo;If the first is Warfare, other players resolve its secondary before your second action.&rdquo;</li>
        </ul></li>
    <li>Effects that trigger at the start or end of a player&rsquo;s turn will not trigger between each of those player&rsquo;s actions.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>

