    <li>Either player may initiate negotiations for a transaction.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Does the Hacan player have to initiate negotiations to perform a transaction with a player who is not their neighbor? A: As long as the active player is involved in the transaction, either player may suggest the opening of negotiations during either player&rsquo;s turn.&rdquo;</li>
        </ul></li>
    <li>The Hacan player is still limited to one transaction with every other player per turn.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How do the Hacan trade action cards?&rdquo;: &ldquo;still within one transaction per player per turn.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="arbiters"><a href="https://twilight-imperium.fandom.com/wiki/The_Emirates_of_Hacan#Faction_Abilities:~:text=Arbiters">Arbiters</a></h2>
    <ol class="note">
    <li>Any number of action cards may be traded.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;Any number of action cards can go either way in a transaction the Hacan are part of.&rdquo;</li>
        </ul></li>
    <li>If the Hacan player has more than seven action cards, they must immediately discard down to seven action cards.<sup>1,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 2.4: &ldquo;If a player ever has more than seven action cards, that player must choose seven cards to keep and discard the rest.&rdquo;</li>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;If a player exceeds this number, they must choose which seven cards they wish to keep and discard the rest.&rdquo;</li>
        </ul></li>
    <li>If the Hacan player has their <a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Political_Secret"><i>Political Secret</i></a> played during an agenda, they may still trade action cards, as <sc>Arbiters</sc> is a passive ability.<sup>1,2,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;Can Hacan trade action cards after having Political Secret played against them? A: Arbiters is a passive ability and the Emirates of Hacan can trade Action cards regardless.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;What exactly does Political Secret stop the affected player from doing?&rdquo;: &ldquo;Mandatory and passive abilities still apply, such as &hellip; Hacan&rsquo;s Arbiters.&rdquo;</li>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: Political Secret &ldquo;only prevents the use of faction abilities that a player must choose to use.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="trade-convoys"><a href="https://twilight-imperium.fandom.com/wiki/The_Emirates_of_Hacan#Faction_Promissory_Note:~:text=Trade%20Convoys">Trade Convoys</a> <sub>(Promissory Note)</sub></h2>
    <ol class="note">
    <li><i>Trade Convoys</i> is returned when the system is activated, even if the active player will perform no hostile acts toward the Hacan player this turn.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>Activating a system containing only the Hacan player&rsquo;s structures will still cause <i>Trade Convoys</i> to be returned.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If an effect other than activating a system during a tactical action places a command token in a system with the Hacan player&rsquo;s units (for example, the primary ability of the <a href="/R_diplomacy"><i>Diplomacy</i></a> strategy card), this will not cause <i>Trade Convoys</i> to be returned.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>

