        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How does Hacan&rsquo;s Quantum Datahub Node swap strategy cards?&rdquo;: &ldquo;trade goods were already collected when the cards were picked.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;In both the situations you mentioned there (Quantum Datahub Node and Acquiescence) the player who picked the strategy card originally would get the trade goods.&rdquo;</li>
        </ul></li>
    <li>In a three&ndash; or four&ndash;player game, the Hacan player chooses which strategy cards are swapped.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How does Hacan&rsquo;s Quantum Datahub Node swap strategy cards?&rdquo;: &ldquo;Hacan chooses both which of their cards to give and which face-up card to take.&rdquo;</li>
        </ul></li>
    <li>The Hacan player must have three trade goods before they spend the command token; they cannot use the <a href="/F_muaat">Muaat</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Alliance"><i>Alliance</i></a> promissory note to gain the third trade good.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>The <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Public%20Disgrace"><i>Public Disgrace</i></a> action card cannot be played against a strategy card the Hacan player takes with <i>Quantum Datahub Node</i>, as <i>Quantum Datahub Node</i> is resolved at the end of the strategy phase and is not a player &ldquo;choosing a strategy card.&rdquo;<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can Public Disgrace be played against a strategy card swap from Quantum Datahub Node or Imperial Arbiter?&rdquo;: &ldquo;No &mdash; Public Disgrace triggers when a player chooses a strategy card, and those swaps at the end of the strategy phase aren&rsquo;t choices.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="wrath-of-kenara"><a href="https://twilight-imperium.fandom.com/wiki/The_Emirates_of_Hacan#Flagship:~:text=Wrath%20of%20Kenara">Wrath of Kenara</a> <sub>(Flagship)</sub></h2>
    <ol class="note">
    <li>This ability may be triggered only once for each die rolled. The Hacan player cannot spend two (or more) trade goods to apply +2 (or more) to a single die, but they may spend two (or more) trade goods to apply +1 to each of two (or more) dice.<sup>1,2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 1.18: &ldquo;Each ability can be resolved once for each occurrence of that ability&rsquo;s timing event.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How does the Hacan flagship&rsquo;s trade-good bonus work?&rdquo;: &ldquo;spend 1 trade good for +1 on any of your units&rsquo; dice in its system, at most once per die.&rdquo;</li>
        </ul></li>
    <li>This ability only affects combat rolls. It cannot modify rolls for <a href="/R_space_cannon"><sc>Space Cannon</sc></a>, <a href="/R_anti_fighter_barrage"><sc>Anti&ndash;Fighter Barrage</sc></a>, or other unit abilities.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How does the Hacan flagship&rsquo;s trade-good bonus work?&rdquo;: &ldquo;It only modifies combat rolls, not Space Cannon or other ability rolls.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="carth-of-golden-sands"><a href="https://twilight-imperium.fandom.com/wiki/The_Emirates_of_Hacan#Leaders:~:text=Carth%20of%20Golden%20Sands">Carth of Golden Sands</a> <sub>(Agent)</sub></h2>
    <ol class="note">
    <li>A player that has their maximum number of commodities may have their commodities replenished. If this happens, they will take no commodities. However, they will still trigger any &ldquo;when [this] player replenishes commodities&rdquo; effects, most notably the <a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Trade_Agreement"><i>Trade Agreement</i></a> promissory note.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Even if that player gains zero commodities when their commodities are refreshed, their &lsquo;Trade Agreement&rsquo; may still be played against them.&rdquo;</li>
        </ul></li>
    <li>The ability of Carth of Golden Sands cannot be resolved while another ability is resolving. For example, if the Hacan player is exploring an industrial planet and has revealed the card, they cannot use the ability of Carth of Golden Sands until after they resolve the card&rsquo;s effect.<sup>4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;transactions may occur after an exploration card is revealed, before the effect is resolved, but other abilities may not be used until after the effect is resolved.&rdquo;</li>
        </ul></li>
    </ol>

