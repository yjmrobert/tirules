<p>The source text behind each note on <a href="/R_command_tokens">Command Tokens</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>Each faction has sixteen command and seventeen control tokens included in the game.<sup>3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play component list: &ldquo;17 control tokens ✦ 16 command tokens.&rdquo;</li>
        </ul></li>
    <li>Command tokens on a player&rsquo;s command sheet are not in that player&rsquo;s reinforcements.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;What happens if I would gain a command token but have none left in my reinforcements?&rdquo;: &ldquo;Tokens you spend &hellip; go back to your reinforcements, not to your command sheet.&rdquo;</li>
        </ul></li>
    <li>If an effect instructs a player to spend a command token from their reinforcements, that player must have a command token in their reinforcements to do so. The token remains in their reinforcements, unless the effect places it on the game board.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;What does spending a command token &lsquo;from your reinforcements&rsquo; mean?&rdquo;: &ldquo;You need a token in reinforcements to pay; it isn&rsquo;t purged or moved to your sheet, so it normally just stays in reinforcements, or goes on the board if the effect says so.&rdquo;</li>
        </ul></li>
    <li>Players do not spend command tokens from their <a href="/R_fleet_pool">fleet pool</a> unless a game effect specifically allows it.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 37.4: &ldquo;Players do not spend command tokens from this pool unless a game effect specifically allows it.&rdquo;</li>
        </ul></li>
    <li>A system is only <a href="/R_active_system">activated</a> by placing a command token during the Activation step of a tactical action or through the primary ability of the Warfare strategy card. Command tokens placed by other effects, such as the primary ability of the <a href="/R_diplomacy"><i>Diplomacy</i></a> strategy card or a retreat, and action cards that target a system, do not activate that system.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do Diplomacy tokens, retreats or action cards like Ghost Ship or Plague count as activating a system?&rdquo;: &ldquo;No &mdash; a system is activated only by placing a command token as the first step of a tactical action. Tokens placed by Diplomacy or a retreat and cards aimed at a system don&rsquo;t activate it.&rdquo;</li>
        </ul></li>
    </ol>
