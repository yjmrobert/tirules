<h2 id="linkship"><a href="https://twilight-imperium.fandom.com/wiki/The_Ral_Nel_Consortium#Destroyer:~:text=Linkship">Linkship</a> <sub>(Unit)</sub></h2>
    <ol class="note">
    <li>Linkships cannot fire <a href="/R_space_cannon"><sc>Space Cannon</sc></a> against adjacent units, even if the Ral Nel player has PDS II.<sup>6,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Linkship (Unit): If the Ral Nel player has the PDS II unit upgrade, can their Linkships&rsquo; SPACE CANNON be used to target ships in adjacent systems? A: No, Link Ship 1 only allows use of Space Canon unit ability.&rdquo;</li>
        <li><b>Implicit</b>: <sup>9</sup> Designer Q&amp;A: &ldquo;RalNel Linkships and PDS 2&rdquo;: &ldquo;range probably shouldn&rsquo;t be transitive.&rdquo; designer ruling, hedged.</li>
        </ul></li>
    <li>If a space dock gains <a href="/R_space_cannon"><sc>Space Cannon</sc></a> from the <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Experimental%20Battlestation"><i>Experimental Battlestation</i></a> action card, each Linkship II in the system may use that <a href="/R_space_cannon"><sc>Space Cannon</sc></a> ability.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;What is the interaction between Experimental Battlestation and Linkship II? &hellip; A: Yes, previous rulings on EBS have clarified that the dock gains the ability during the movement step, thus it can be used by Linkship&rsquo;s ability.&rdquo;</li>
        </ul></li>
    <li>Each Linkship II rolls one space cannon die, regardless of how many PDS are in its system.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Are there quick answers for &hellip; Ral Nel Linkships?&rdquo;: &ldquo;Each Linkship II rolls one Space Cannon die however many PDS share its space.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="last-dispatch"><a href="https://twilight-imperium.fandom.com/wiki/The_Ral_Nel_Consortium#Flagship:~:text=Last%20Dispatch">Last Dispatch</a> <sub>(Flagship)</sub></h2>
    <ol class="note">
    <li>The Ral Nel player chooses which ship is destroyed.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Same text: &ldquo;you may destroy 1 ship in the active system.&rdquo;</li>
        </ul></li>
    <li>A unit with <a href="/R_sustain_damage"><sc>Sustain Damage</sc></a> cannot be destroyed, even if it is damaged.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook, Last Dispatch: &ldquo;you may destroy 1 ship in the active system that does not have SUSTAIN DAMAGE.&rdquo;</li>
        </ul></li>
    <ol><li>If a unit loses the <a href="/R_sustain_damage"><sc>Sustain Damage</sc></a> ability, such as a war sun by the effect of the <a href="https://twilight-imperium.fandom.com/wiki/Agenda_Cards#Directives:~:text=Publicize%20Weapon%20Schematics"><i>Publicize Weapon Schematics</i></a> agenda, then that unit may be destroyed with the ability of the <i>Last Dispatch</i>.<sup>7</sup>
        <ul>
        <li><b>Implicit</b>: <sup>7</sup> Same text: the target must be a ship &ldquo;that does not have SUSTAIN DAMAGE.&rdquo;</li>
        </ul></li></ol>
    <li>If this ability destroys the last of the other player&rsquo;s ships in the system, the Ral Nel player&rsquo;s ships still retreat and the ability resolves.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;What happens if the flagship ability destroys the last player&rsquo;s ship in the system? Do you still retreat? A: Yes, the ships retreat and the ability resolves.&rdquo;</li>
        </ul></li>
    <li>If the Ral Nel player plays the <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Skilled%20Retreat"><i>Skilled Retreat</i></a> action card, they cannot resolve the ability of the <i>Last Dispatch</i>.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;How does Skilled Retreat differ from a normal retreat?&rdquo;: &ldquo;It isn&rsquo;t a retreat in rules terms but a move.&rdquo; The Last Dispatch triggers &ldquo;When this unit retreats.&rdquo;</li>
        </ul></li>
    <ol><li><i>Skilled Retreat</i> is not a retreat.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How does Skilled Retreat differ from a normal retreat?&rdquo;: &ldquo;It isn&rsquo;t a retreat in rules terms but a move.&rdquo;</li>
        </ul></li></ol>
    </ol>

<h2 id="kan-kip-rel"><a href="https://twilight-imperium.fandom.com/wiki/The_Ral_Nel_Consortium#Leaders:~:text=Kan%20Kip%20Rel">Kan Kip Rel</a> <sub>(Agent)</sub></h2>
    <ol class="note">
    <li>The action card that the Ral Nel player gives to another player must be one of the two that they drew, and not another action card from their hand.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>The ability of Kan Kip Rel resolves fully before the action card hand limit is checked.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Kan Kip Rel (Agent): How would this resolve if the Ral Nel player would go over their action card hand limit? A: The ability resolves before checking hand limit size.&rdquo;</li>
        </ul></li>
    <li>If the <a href="/F_yssaril">Yssaril</a> player uses this ability, they draw three action cards instead of two due to their <a href="https://twilight-imperium.fandom.com/wiki/The_Yssaril_Tribes#Faction_Abilities:~:text=Scheming"><sc>Scheming</sc></a> faction ability. They discard one card from those drawn or from their hand, then take one of the drawn cards and give another to another player, keeping the third if it was not discarded.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Draw 3 instead of 2, discard 1 from the 3 drawn or hand to scheming, then take 1 and give the other to another player keeping the 3rd if not discarded to scheming.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="watchful-ojz"><a href="https://twilight-imperium.fandom.com/wiki/The_Ral_Nel_Consortium#Leaders:~:text=Watchful%20Ojz">Watchful Ojz</a> <sub>(Commander)</sub></h2>
    <ol class="note">
    <li>Watchful Ojz can only be used if the Ral Nel player has a valid retreat path for the moved ships (separate from the system the commander allows them to retreat to).<sup>9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;RalNel Commander&rdquo;: &ldquo;Sometimes, RalNel will not have a valid, regular retreat path. Does this mean that they cannot announce a retreat, and thus cannot use their commander &hellip;? A: This means they can&rsquo;t use it.&rdquo;</li>
        </ul></li>
    <li>The destination system may contain a planet controlled by another player, which may also have that player&rsquo;s ground forces on it.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>Watchful Ojz is a &ldquo;when&rdquo; ability. It resolves before the <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Intercept"><i>Intercept</i></a> action card is played and resolved.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Watchful Ojz (Commander): How does Watchful Ojz interact with the Intercept action card &hellip;? A: Commander is a When, resolve Watchful Ojz, then Intercept is played and resolved.&rdquo;</li>
        </ul></li>
    </ol>

