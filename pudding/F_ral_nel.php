<h2 id="miniaturization"><a href="https://twilight-imperium.fandom.com/wiki/The_Ral_Nel_Consortium#Faction_Abilities:~:text=Miniaturization">Miniaturization</a></h2>
    <ol class="note">
    <li>Structures will be placed at the end of the tactical action. This will be after the production step, and so any space docks placed cannot use their <a href="/R_production"><sc>Production</sc></a> ability during the same action.<sup>7</sup>
        <ul>
        <li><b>Implicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook, Miniaturization (Ral Nel): &ldquo;At the end of your turn, you may place your structures that are in the space area of the active system onto planets you control in that system.&rdquo; placement comes after production.</li>
        </ul></li>
    <li>If the Ral Nel player&rsquo;s ships leave a system or are destroyed, their structures in the space area remain there until they are blockaded, transported, or placed onto planets.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;What happens to Ral Nel structures in space if their ships leave the system/are destroyed? A: They remain in space until they are blockaded, transported, or placed onto planets.&rdquo;</li>
        </ul></li>
    </ol>

