<p>The source text behind each note on <a href="/R_legendary_planets">Legendary Planets</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>Legendary planet ability cards exhaust and ready independently from their respective planet card.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Is a legendary planet&rsquo;s ability card exhausted when I take the planet?&rdquo;: &ldquo;It works independently of the planet: you can use it after spending the planet.&rdquo;</li>
        </ul></li>
    <li>A legendary planet ability card will ready in the status phase.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 51.4 (agents): cards &ldquo;ready during the &lsquo;Ready Cards&rsquo; step of the status phase.&rdquo; Status phase step 6 readies all exhausted cards.</li>
        </ul></li>
    <li>An ability that readies a planet cannot be used to ready a legendary planet ability card.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Is a legendary planet&rsquo;s ability card exhausted when I take the planet?&rdquo;: &ldquo;effects that ready the planet don&rsquo;t ready it.&rdquo;</li>
        </ul></li>
    <li>If an effect instructs a player to &ldquo;end your turn&rdquo;, that player may still resolve any &ldquo;at the end of your turn&rdquo; abilities, including those of legendary planets.<sup>4,6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;A previous ruling has stated that if an effect ends a player&rsquo;s turn, they may still use &lsquo;at the end of your turn&rsquo; abilities.&rdquo;</li>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;End of turn abilities can still be used.&rdquo;</li>
        </ul></li>
    <li><a href="/R_mecatol_rex">Mecatol Rex</a> is a legendary planet when the Thunder&rsquo;s Edge Mecatol Rex system tile (tile 112) is used. Its legendary planet ability card is <a href="/C_legendary_planets"><i>The Galactic Council</i></a>.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 4: &ldquo;Replace the &lsquo;Mecatol Rex&rsquo; system tile from the base game with the &lsquo;Mecatol Rex&rsquo; system tile that has a legendary planet icon.&rdquo;</li>
        </ul></li>
    </ol>
