<h2 id="umbat"><a href="https://twilight-imperium.fandom.com/wiki/The_Embers_of_Muaat#Leaders:~:text=Umbat">Umbat</a> <sub>(Agent)</sub></h2>
    <ol class="note">
    <li>The produced units must be paid for.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;a unit that is produced must always be paid for.&rdquo;</li>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;What can Integrated Economy produce?&rdquo;: &ldquo;up to the new planet&rsquo;s resource value in cost, paid normally.&rdquo;</li>
        </ul></li>
    <li>No unit is using its <a href="/R_production"><sc>Production</sc></a> ability. The <a href="https://twilight-imperium.fandom.com/wiki/Cybernetic_Technologies#Sarween_Tools"><i>Sarween Tools</i></a> technology and similar effects will not allow a more expensive ship to be produced.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;When producing a unit with an ability other than &lsquo;Production,&rsquo; does the price reduction from the &lsquo;Sarween Tools&rsquo; technology apply? A: No.&rdquo;</li>
        </ul></li>
    <li>If ground forces are produced, they may be placed in the space area or on a planet the player controls in the system with their war sun or flagship.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If the <a href="/F_naalu">Naalu</a> or <a href="/F_yin">Yin</a> players are chosen, and choose to produce fighters or infantry, they will only be able to produce two of those units; their commander will have no effect.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <ol><li>If the <a href="https://twilight-imperium.fandom.com/wiki/Agenda_Cards#Directives:~:text=Regulated%20Conscription"><i>Regulated Conscription</i></a> law is in play, then that player may use their commander to produce two units for one resource when resolving Umbat.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li></ol>
    </ol>

<h2 id="magmus"><a href="https://twilight-imperium.fandom.com/wiki/The_Embers_of_Muaat#Faction_Technologies:~:text=Magmus">Magmus</a> <sub>(Commander)</sub></h2>
    <ol class="note">
    <li>When a command token is spent to resolve the secondary ability of a strategy card, the trade good is gained after resolving the secondary ability. As such, it cannot be spent to pay for costs of the secondary ability.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If the Muaat player spends multiple tokens from their strategy pool (e.g. for the <a href="https://twilight-imperium.fandom.com/wiki/Objectives#Twilight_Imperium_Fourth_Edition:~:text=Lead%20From%20the%20Front"><i>Lead From the Front</i></a> objective), they gain that many trade goods, one at a time.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <ol>
        <li>Each trade good gained may trigger the <a href="/F_mentak">Mentak</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Mentak_Coalition#Faction_Abilities:~:text=Pillage"><sc>Pillage</sc></a> faction ability.<sup>1,2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR FAQ: Mentak &ldquo;can trigger &lsquo;Pillage&rsquo; each time the Saar gain&rdquo; a trade good from Scavenge. Each separate gain triggers Pillage.</li>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;When exactly can Mentak use Pillage?&rdquo;: &ldquo;After each instance of a neighbor gaining trade goods.&rdquo;</li>
        </ul></li>
        <li>If the Muaat player wishes to score <a href="https://twilight-imperium.fandom.com/wiki/Objectives#Twilight_Imperium_Fourth_Edition:~:text=Lead%20From%20the%20Front"><i>Lead From the Front</i></a> and <a href="https://twilight-imperium.fandom.com/wiki/Objectives#Twilight_Imperium_Fourth_Edition_4:~:text=Form%20a%20Spy%20Network"><i>Form a Spy Network</i></a> during the one status phase, they must do so simultaneously, and both happen before the <a href="/F_mentak">Mentak</a> player may use their <a href="https://twilight-imperium.fandom.com/wiki/The_Mentak_Coalition#Faction_Abilities:~:text=Pillage"><sc>Pillage</sc></a> faction ability. If the <a href="/F_mentak">Mentak</a> player subsequently uses their agent, <a href="https://twilight-imperium.fandom.com/wiki/The_Mentak_Coalition#Leaders:~:text=Suffi%20An">Suffi An</a>, when they use their <a href="https://twilight-imperium.fandom.com/wiki/The_Mentak_Coalition#Faction_Abilities:~:text=Pillage"><sc>Pillage</sc></a> faction ability on the trade goods the Muaat player gained from Magmus when spending the tokens for <a href="https://twilight-imperium.fandom.com/wiki/Objectives#Twilight_Imperium_Fourth_Edition:~:text=Lead%20From%20the%20Front"><i>Lead From the Front</i></a>, then the Muaat player cannot discard the drawn action card for <a href="https://twilight-imperium.fandom.com/wiki/Objectives#Twilight_Imperium_Fourth_Edition_4:~:text=Form%20a%20Spy%20Network"><i>Form a Spy Network</i></a>.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>
    <li>If the Muaat player uses the ability of the <a href="https://twilight-imperium.fandom.com/wiki/Relics#Prophecy_of_Kings:~:text=Scepter%20of%20Emelpar"><i>Scepter of Emelpar</i></a> relic, they will be unable to benefit from the ability of Magmus.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>The Muaat player must have Magmus unlocked before spending the strategy token in order to gain the trade good.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <ol><li>For example, if the Muaat player spends a strategy token to follow the secondary ability of the <a href="/R_warfare"><i>Warfare</i></a> strategy card, and in doing so produces the war sun that unlocks Magmus, they will not gain the trade good from spending that strategy token.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li></ol>
    </ol>

<h2 id="adjudicator-baal"><a href="https://twilight-imperium.fandom.com/wiki/The_Embers_of_Muaat#Leaders:~:text=Adjudicator%20Ba%27al">Adjudicator Ba&rsquo;al</a> &mdash; <a href="https://twilight-imperium.fandom.com/wiki/The_Embers_of_Muaat#Leaders:~:text=Nova%20Seed">Nova Seed</a> <sub>(Hero)</sub></h2>
    <ol class="note">
    <li>Any method of movement is sufficient to trigger this ability, not only tactical action movement. For example, the Muaat player may trigger <i>Nova Seed</i> when they retreat.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <ol><li>If the <a href="/F_mahact">Mahact</a> player moves the Muaat player&rsquo;s war sun via the use of their <a href="https://twilight-imperium.fandom.com/wiki/The_Mahact_Gene-Sorcerers#Leaders:~:text=Benediction"><i>Benediction</i></a> hero ability, the Muaat player cannot trigger <i>Nova Seed</i>.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li></ol>
    <li>If the war sun is in the target system when it is activated, it must move out of the system, and back in, for <i>Nova Seed</i> to be able to be triggered.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li><i>Nova Seed</i> purges all tokens on the replaced system tile other than command tokens and frontier tokens. Any faction&ndash;specific tokens, such as <a href="/F_creuss">Creuss</a> wormhole tokens or <a href="/F_ul">Ul</a> sleeper tokens, are returned to the player that owns them instead.<sup>4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;How does The Embers of Muaat Hero, Nova Seed, interact with tokens &hellip;? A: Nova Seed also purges all tokens other than command tokens and frontier tokens. Any faction specific tokens are returned to that faction.&rdquo;</li>
        </ul></li>
    <ol><li>The Avernus token is purged, not returned to the Muaat player. This also purges the Avernus planet card, <i>The Nucleus</i> legendary planet ability card, and any attachments on Avernus.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;What happens if Nova Seed is used on a system that contains the Avernus token? A: The token is purged, this causes the planet card, legendary ability card, and any attachments to be purged as well.&rdquo;</li>
        </ul></li></ol>
    <li>The Muaat player&rsquo;s units may exist in and move out of the supernova system, even if the Muaat player does not own <a href="https://twilight-imperium.fandom.com/wiki/The_Embers_of_Muaat#Faction_Technologies:~:text=Magmus%20Reactor"><i>Magmus Reactor</i></a>.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How does the Muaat hero&rsquo;s Nova Seed treat Muaat&rsquo;s own units &hellip;?&rdquo;: &ldquo;Muaat&rsquo;s own stay, the war sun included, and can leave later, since nothing stops ships moving out of a supernova.&rdquo;</li>
        </ul></li>
    <li>If the Muaat player owns <a href="https://twilight-imperium.fandom.com/wiki/The_Embers_of_Muaat#Faction_Technologies:~:text=Magmus%20Reactor"><i>Magmus Reactor &Omega;</i></a>, and resolves this ability during a tactical action, they will be able to produce units during the <b>Production</b> step, if the Muaat player still has units in the system.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li><i>Nova Seed</i> cannot target the home system of an eliminated player.<sup>6</sup>
        <ul>
        <li><b>Implicit</b>: <sup>6</sup> Community consensus, &ldquo;What happens to Avernus if Muaat is eliminated?&rdquo;: &ldquo;Avernus, its token, planet card and legendary ability remain in play. Similar to an eliminated faction&rsquo;s home system.&rdquo; An eliminated player&rsquo;s home system stays a home system.</li>
        </ul></li>
    <li><i>Nova Seed</i> may target the <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Faction_Abilities:~:text=Creuss%20Gate">Creuss Gate</a> (tile 17), the <a href="/F_rebellion">Rebellion</a>&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Crimson_Rebellion#Faction_Abilities:~:text=The%20Sorrow">Sorrow</a> (tile 94), or the Wormhole Nexus (tile 82).<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>The <a href="/F_empyrean">Empyrean</a> player cannot use the ability of their agent, Acamar, on the Muaat player after they use <i>Nova Seed</i> if the original system tile contained planets.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li><i>Nova Seed</i> cannot replace a system tile in the Fracture, such as the system containing Styx.<sup>6,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Can the Muaat Hero, Nova Seed, be used on tiles in the Fracture? A: No, you cannot nova seed tiles which contain multiple systems.&rdquo;</li>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Styx and Novaseed&rdquo;: &ldquo;No, the fracture tiles are not able to be replaced due to their unusual shape.&rdquo;</li>
        </ul></li>
    <li>If the Muaat player moves a war sun into a system containing the <a href="/F_naalu">Naalu</a> player&rsquo;s ships, the Muaat player, as the active player, may resolve <i>Nova Seed</i> before the <a href="/F_naalu">Naalu</a> player resolves their <a href="https://twilight-imperium.fandom.com/wiki/The_Naalu_Collective#Faction_Abilities:~:text=Foresight"><sc>Foresight</sc></a> faction ability.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Who goes first when the Muaat hero and Naalu Foresight both trigger as a war sun moves in?&rdquo;: &ldquo;Muaat, as the active player, so the hero can destroy the Naalu ships before Foresight.&rdquo;</li>
        </ul></li>
    </ol>

