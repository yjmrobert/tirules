<h2>Notes</h2>
    <ol class="note">
    <li>In general, only the terms of the deal that a player can immediately perform, even without the deal taking place, are binding.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When is a deal binding?&rdquo;: &ldquo;Only when its terms resolve immediately &hellip; Promises about future actions, and if-then conditions, are non-binding and can be broken.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;The &lsquo;immediate&rsquo; requirement for binding deals is satisfied only when all aspects of the deal can be acted upon during the same game effect.&rdquo;</li>
        </ul></li>
    <li>The following are examples of non&ndash;binding deals:<sup>5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;The &lsquo;immediate&rsquo; requirement for binding deals is satisfied only when all aspects of the deal can be acted upon during the same game effect.&rdquo;</li>
        </ul></li>
    <ol>
        <li>Making a deal to use a promissory note in a specific way, before the promissory note has been transacted.<sup>5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling, on a deal to trade the Creuss IFF and have it used: &ldquo;This would be non-binding, because when the deal is made, the non-Ghost player does not technically qualify to even be able to perform his side of the deal (he doesn&rsquo;t have the IFF).&rdquo;</li>
        </ul></li>
        <li>Making a deal to not make use of a unit&rsquo;s <a href="/R_space_cannon"><sc>Space Cannon</sc></a> ability during a tactical action, before ships have been moved.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When is a deal binding?&rdquo;: &ldquo;Only when its terms resolve immediately &hellip; Promises about future actions, and if-then conditions, are non-binding and can be broken.&rdquo; &ldquo;taking a trade good not to fire Space Cannon at the moment you decide whether to fire binds you.&rdquo; A deal made earlier does not.</li>
        </ul></li>
        <li>Making a deal to trade commodities in exchange for the active player to replenish another player&rsquo;s commodities during the resolution of the primary ability of the <a href="/R_trade"><i>Trade</i></a> strategic action.<sup>5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;The &lsquo;immediate&rsquo; requirement for binding deals is satisfied only when all aspects of the deal can be acted upon during the same game effect.&rdquo; &ldquo;(in the case of the &lsquo;Trade&rsquo; SC scenario, each of those bullets is an effect).&rdquo;</li>
        </ul></li>
        <li>Making a deal for a player to vote on an agenda in a certain way, when it is not yet that player&rsquo;s opportunity to vote.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Is a deal to buy someone&rsquo;s votes binding?&rdquo;: &ldquo;Only for a player about to cast votes right now &hellip; a promise to vote a certain way later can still be broken.&rdquo;</li>
        </ul></li>
        <li>Any deal that will resolve after dice are rolled.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;Can two players agree not to fight &hellip;?&rdquo;: &ldquo;rolling and assigning hits are mandatory and a deal can&rsquo;t override the rules.&rdquo;</li>
        </ul></li>
    </ol>
    <li>The following are examples of binding deals:<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;&mdash;Binding: Give me two trade goods and I&rsquo;ll let you refresh your commodities without spending a command token.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When is a deal binding?&rdquo;: &ldquo;taking a trade good not to fire Space Cannon at the moment you decide whether to fire binds you not to fire.&rdquo;</li>
        </ul></li>
    <ol>
        <li>Making a deal to use a promissory note in a specific way, when the player who would resolve it already has that promissory note and can resolve it immediately.<sup>5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling, on a deal to trade the Creuss IFF and have it used: &ldquo;If he already had the IFF, it could be a binding transaction.&rdquo;</li>
        </ul></li>
        <li>Making a deal to not make use of a unit&rsquo;s <a href="/R_space_cannon"><sc>Space Cannon</sc></a> ability, at the moment that player decides whether to use it.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When is a deal binding?&rdquo;: &ldquo;taking a trade good not to fire Space Cannon at the moment you decide whether to fire binds you not to fire.&rdquo;</li>
        </ul></li>
        <li>Making a deal to give trade goods to the active player in exchange for the active player choosing that player to replenish their commodities without spending a command token, during the resolution of the primary ability of the <a href="/R_trade"><i>Trade</i></a> strategic action.<sup>5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (Dane, via Skootur, Oct 19, 2017): &ldquo;&mdash;Binding: Give me two trade goods and I&rsquo;ll let you refresh your commodities without spending a command token.&rdquo;</li>
        </ul></li>
        <li>Making a deal for a player to vote on an agenda in a certain way, when that player is about to cast their votes.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Is a deal to buy someone&rsquo;s votes binding?&rdquo;: &ldquo;Only for a player about to cast votes right now. Paying the next voter in exchange for their vote binds it, since nothing can happen in between&rdquo;</li>
        </ul></li>
    </ol>
    </ol>
