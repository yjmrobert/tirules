<h2 id="watcher"><a href="https://twilight-imperium.fandom.com/wiki/The_Empyrean#Mech:~:text=Watcher">Watcher</a> <sub>(Mech)</sub></h2>
    <ol class="note">
    <li>This effect may cancel a <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Sabotage"><i>Sabotage</i></a> action card.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;Can Sabotage cancel another Sabotage or a promissory note?&rdquo;: &ldquo;Other cancel effects that lack that restriction can still cancel a Sabotage.&rdquo;</li>
        </ul></li>
    <li>The Watcher must be adjacent to the other player&rsquo;s units during the timing window when the action card is played in order to cancel it.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <ol><li>In particular, if an action card is played &ldquo;when/after you activate a system&rdquo; or similar, then the Watcher must be adjacent before any ships move during that tactical action.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li></ol>
    <li>If an action card is canceled by a Watcher, no costs are paid.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>A player playing an action card announces the following before a Watcher may be triggered:<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <ol>
        <li>Any targeted planets, system, units, players, cards, outcomes, and/or other such objects.<sup>1,2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR FAQ (for Sabotage): &ldquo;can be played after card targets (such as units, planets, systems, cards, outcomes, or players) have been decided on.&rdquo;</li>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;When exactly is Sabotage played&rdquo;: &ldquo;After the player announces the card&rsquo;s choices (target planet, ship or player, rider prediction, retreat destination and so on).&rdquo;</li>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling: &ldquo;For sabotage, you would play after the target is chosen.&rdquo;</li>
        </ul></li>
        <li>The value of any variable cost to be paid.<sup>5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (Dane, Jan 23, 2019), confirming a list of Sabotage timings: &ldquo;Bribery. Player declares how many TGs to be spent and which side he&rsquo;s voting for. Sabotage is played before he actually enacts it.&rdquo; Dane: &ldquo;This list is mostly correct with one correction&rdquo; (the correction concerns Focused Research only).</li>
        </ul></li>
    </ol>
    <li>Any dice are rolled and any cards are drawn only after the Empyrean player has declined to remove a Watcher.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If an action card instructs a player to research a technology, that player need not announce what technology they are researching until the Empyrean player has declined to remove a Watcher.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If an action card is played that will have an effect later, such as a rider, that card may only be canceled by a Watcher when it is originally played.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If the action card that was canceled by a Watcher was to be used to perform a component action, the active player must perform a different action, or pass.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;If my component action card is cancelled by Sabotage &hellip;?&rdquo;: &ldquo;a cancelled card counts as not played, so you still take an action (or pass, if allowed).&rdquo;</li>
        </ul></li>
    <ol><li>If the component action was to be the second action the active player was to perform on their turn, through an effect such as the <a href="https://twilight-imperium.fandom.com/wiki/Propulsion_Technologies#Fleet_Logistics"><i>Fleet Logistics</i></a> technology, the active player may end their turn without performing a second action and without passing.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;If my component action card is cancelled by Sabotage, have I used my action for the turn?&rdquo;: &ldquo;If it was the optional extra action from Fleet Logistics, you can just end your turn.&rdquo;</li>
        </ul></li></ol>
    </ol>

<h2 id="void-tether"><a href="https://twilight-imperium.fandom.com/wiki/The_Empyrean#Breakthrough:~:text=Void%20Tether">Void Tether</a> <sub>(Breakthrough)</sub></h2>
    <ol class="note">
    <li>Other players treat the systems that share the border with the Void Tether token as not being adjacent for all game effects, even if both systems contain matching <a href="/R_wormholes">wormholes</a>. The Empyrean player continues to treat them as adjacent.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Void Tether (Breakthrough): If the Void Tether token is between two systems that both contain a wormhole, do other players consider those systems adjacent? A: No, RAW the systems are not adjacent via any means.&rdquo;</li>
        </ul></li>
    <ol><li>If the Empyrean player has units or controls a planet in one of the systems, they will be neighbors with any player with units or controlling a planet in the other, and vice versa.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Does the QUANTUM ENTANGLEMENT neighbors ruling apply i.e. if Empyrean is on one side of the Void Tether token, are they neighbors &hellip;? A: Yes, they must be neighbors as Empyrean cannot block themselves with void tether.&rdquo;</li>
        </ul></li></ol>
    <li>If the Empyrean player is eliminated, <i>Void Tether</i> remains in play, and the Void Tether tokens continue to function.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Do the void tether tokens remain in play if the Empyrean player is eliminated? A: The Empyrean Breakthrough remains in play and the Void Tethers remain functional.&rdquo;</li>
        </ul></li>
    </ol>
