<h2 id="council-patronage"><a href="https://twilight-imperium.fandom.com/wiki/The_Council_Keleres#Codex_III:~:text=Council%20Patronage">Council Patronage</a></h2>
    <ol class="note">
    <li>The Keleres player must mandatorily replenish their commodities and gain a trade good every strategy phase.<sup>12</sup>
        <ul>
        <li><b>Explicit</b>: <sup>12</sup> Codex III, Council Patronage: &ldquo;Replenish your commodities at the start of the strategy phase, then gain 1 trade good.&rdquo; No &ldquo;may&rdquo;.</li>
        </ul></li>
    <li>If the Keleres player already has their maximum number of commodities, they will still replenish their commodities during the strategy phase. This will not give them additional commodities, but will trigger any effects that happen when the Keleres player replenishes their commodities.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Even if that player gains zero commodities when their commodities are refreshed, their &lsquo;Trade Agreement&rsquo; may still be played against them.&rdquo;</li>
        </ul></li>
    </ol>

