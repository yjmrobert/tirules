        </ul></li>
    <li><i>Stymie</i> is returned when the system is activated, even if the active player will perform no hostile acts toward the Arborec player this turn.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>Activating a system containing only the Arborec player&rsquo;s structures will still cause <i>Stymie</i> to be returned.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If an effect other than activating a system during a tactical action places a command token in a system with the Arborec player&rsquo;s units (for example, the primary ability of the <a href="/R_diplomacy"><i>Diplomacy</i></a> strategy card), this will not cause <i>Stymie</i> to be returned.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>

