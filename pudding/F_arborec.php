<h2 id="letani-warrior"><a href="https://twilight-imperium.fandom.com/wiki/The_Arborec#Infantry:~:text=Letani%20Warrior">Letani Warrior</a> <sub>(Unit)</sub></h2>
    <ol class="note">
    <li>When multiple units use their <a href="/R_production"><sc>Production</sc></a> ability, the <a href="/R_production"><sc>Production</sc></a> value is pooled. As such, if the Arborec player has two Letani Warrior I in a system, they may produce two infantry for one resource, rather than two.<sup>1,2,3,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Can the &lsquo;Production&rsquo; abilities of multiple Arborec &lsquo;Letani Warriors&rsquo; in a system be combined to allow the production of two infantry for one resource? A: Yes. Production value is totaled when the &lsquo;Production&rsquo; ability of units in a system is used.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;Their Production pools with your other units in the system.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;Letani Warriors in the same system can pool their production.&rdquo;</li>
        <li><b>Implicit</b>: <sup>3</sup> Learn to Play: &ldquo;When producing multiple units at a time, the cost values of those units are added together.&rdquo;</li>
        </ul></li>
    <li>If Letani Warriors are on different planets, any produced ground forces may be split between those planets, regardless of the production value of the Letani Warriors on that planet.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Where are produced ground forces placed?&rdquo;: &ldquo;With several producing planets you may split them among those planets however you like, even all on one.&rdquo;</li>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling: &ldquo;the infantry must be placed on a planet that has a Letani Warrior on it.&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="duha-menaimon"><a href="https://twilight-imperium.fandom.com/wiki/The_Arborec#Flagship:~:text=Duha%20Menaimon">Duha Menaimon</a> <sub>(Flagship)</sub></h2>
    <ol class="note">
    <li>The produced units must be paid for.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;When an ability other than &lsquo;Production&rsquo; allows you to produce one or more units, do you have to pay for the units produced? A: Yes, a unit that is produced must always be paid for.&rdquo;</li>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal on Integrated Economy (a similar non-Production effect): &ldquo;paid normally.&rdquo;</li>
        </ul></li>
    <li>The <i>Duha Menaimon</i> does not have <a href="/R_production"><sc>Production</sc></a>. As such, the <a href="https://twilight-imperium.fandom.com/wiki/Cybernetic_Technologies#Sarween_Tools"><i>Sarween Tools</i></a> technology and similar such effects do not apply to the <i>Duha Menaimon</i>.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;When producing a unit with an ability other than &lsquo;Production,&rsquo; does the price reduction from the &lsquo;Sarween Tools&rsquo; technology apply? A: No, &lsquo;Sarween Tools&rsquo; is only used with the &lsquo;Production&rsquo; ability.&rdquo;</li>
        </ul></li>
    <li>The <i>Duha Menaimon</i> must be in the system when it is activated for its effect to trigger. It will not trigger if it is moved into the active system later in the turn.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Does the Arborec flagship (The &lsquo;Duha Menaimon&rsquo;) need to be in a system when it is activated &hellip;? A: Yes. The &lsquo;Duha Menaimon&rsquo; can only be used to produce units when it is in a system at the moment it is activated.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When does the Arborec flagship produce, and can it move in first?&rdquo;: &ldquo;so it only works if it is already in the active system; it can&rsquo;t move in and then produce&rdquo;</li>
        </ul></li>
    </ol>

<h2 id="letani-ospha"><a href="https://twilight-imperium.fandom.com/wiki/The_Arborec#Leaders:~:text=Letani%20Ospha">Letani Ospha</a> <sub>(Agent)</sub></h2>
    <ol class="note">
    <li>The replaced ship is not destroyed. The replacing ship is not produced.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <ol><li>The <a href="https://twilight-imperium.fandom.com/wiki/Cybernetic_Technologies#Sarween_Tools"><i>Sarween Tools</i></a> technology and similar effects will not allow a more expensive ship to be placed.<sup>*</sup>
