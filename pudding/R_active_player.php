<p>The source text behind each note on <a href="/R_active_player">Active Player</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>During combat, the active player is the attacker.<sup>1,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 13: &ldquo;During combat, the active player is the attacker.&rdquo;</li>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;During combat, the active player is the attacker and the other player is the defender.&rdquo;</li>
        </ul></li>
    <li>The active player will have the first opportunity to resolve abilities during each timing window.<sup>1,2,5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 1.19: abilities are resolved &ldquo;in initiative order, beginning with the active player.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When must Xxcha use Nullification Field &hellip;?&rdquo;: &ldquo;The active player gets first turn in that window.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (kaiteinomen, Sep 20, 2017): &ldquo;All timing conflicts are intended to follow the same rules for resolution&mdash;in initiative order, beginning with the active player.&rdquo;</li>
        </ul></li>
    <li>All transactions during the action phase must involve the active player.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Who can make transactions, and when?&rdquo;: &ldquo;During the action phase, only the active player can transact.&rdquo;</li>
        </ul></li>
    <li>If a non&ndash;active player produces hits using the <a href="/R_space_cannon"><sc>Space Cannon Offense</sc></a> ability of one of their units, those hits must be assigned to the active player&rsquo;s units.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;During Space Cannon Offense, who can shoot at whom?&rdquo;: &ldquo;each other player with Space Cannon in range fires, but only at the active player&rsquo;s ships.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 77.5: &ldquo;The player whose units have been targeted by &lsquo;Space Cannon&rsquo; must choose and destroy one of their ships.&rdquo;</li>
        </ul></li>
    </ol>
