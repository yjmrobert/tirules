        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Does the 0 on the ten-sided die count as 0 or 10?&rdquo;: &ldquo;10 &mdash; the Living Rules Reference FAQ confirms the 0 face is a 10.&rdquo;</li>
        </ul></li>
    </ol>
