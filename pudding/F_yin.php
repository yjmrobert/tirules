<h2 id="indoctrination"><a href="https://twilight-imperium.fandom.com/wiki/The_Yin_Brotherhood#Faction_Abilities:~:text=Indoctrination">Indoctrination</a></h2>
    <ol class="note">
    <li><sc>Indoctrination</sc> is limited to once per ground combat.<sup>1,2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 1.18: &ldquo;Each ability can be resolved once for each occurrence of that ability&rsquo;s timing event.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How does the Yin&rsquo;s Devotion work?&rdquo;: &ldquo;Indoctrination works once per ground combat, at its start.&rdquo;</li>
        </ul></li>
    <li>If an invasion involves ground combats on multiple planets, <sc>Indoctrination</sc> may be used at the start of each of them.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> Same entry: &ldquo;once per ground combat.&rdquo; Each planet&rsquo;s ground combat is a separate combat.</li>
        </ul></li>
    <li>If the Yin player&rsquo;s opponent only has mechs in the ground combat, <sc>Indoctrination</sc> cannot be used.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <ol><li>If the Yin player is in a combat with the <a href="/F_naalu">Naalu</a> player, and the <a href="/F_naalu">Naalu</a> player is using the ability of their flagship, the <a href="https://twilight-imperium.fandom.com/wiki/The_Naalu_Collective#Flagship:~:text=Matriarch"><i>Matriarch</i></a>, to commit only fighters to the ground combat, <sc>Indoctrination</sc> cannot be used.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li></ol>
    <li>If the last of a player&rsquo;s ground forces in a ground combat are removed by <sc>Indoctrination</sc>, that player loses the combat immediately.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;If Yin&rsquo;s Indoctrination replaces the only defending infantry, have the Yin won the ground combat?&rdquo;: &ldquo;if it removes the last defender the Yin win.&rdquo;</li>
        </ul></li>
    </ol>

