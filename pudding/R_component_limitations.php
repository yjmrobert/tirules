<p>The source text behind each note on <a href="/R_component_limitations">Component Limitations</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>As each player only has ten plastic fighter figures and twelve plastic infantry figures, a player cannot have fighters in more than ten systems, and cannot have infantry on more than twelve planets or being carried in more than twelve space areas, or any combination thereof.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Are fighter and infantry tokens limited, and what are they for?&rdquo;: &ldquo;each stack of tokens must sit with at least one plastic piece of the same type. So your plastic fighters and infantry limit how many places you can have them.&rdquo;</li>
        </ul></li>
    <li>Players may also swap infantry and fighter plastic pieces for tokens at any time.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> Same entry: &ldquo;You may swap a plastic piece on the board for a token at any time to free the plastic for use elsewhere.&rdquo;</li>
        </ul></li>
    <li>Players may swap between three value tokens and one value tokens as desired.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 46.4: &ldquo;Infantry tokens come in values of one and three. A player can swap between these tokens as necessary.&rdquo;</li>
        </ul></li>
    <li>A player may only resolve a deploy ability to place a unit that is in their reinforcements. A player cannot remove a unit from the board to use its deploy ability.<sup>1,8</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 30.2: &ldquo;A player can only resolve a deploy ability to place a unit that is in their reinforcements.&rdquo;</li>
        <li><b>Explicit</b>: <sup>1</sup> LRR 30.2a: &ldquo;If there are no units that have a deploy ability in a player&rsquo;s reinforcements, the deploy ability cannot be used.&rdquo;</li>
        <li><b>Explicit</b>: <sup>8</sup> PoK rulebook: &ldquo;This ability can be used to place a unit from a player&rsquo;s reinforcements.&rdquo;</li>
        </ul></li>
    <li>Each faction has sixteen command and seventeen control tokens included in the game.<sup>3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play component list: &ldquo;17 control tokens ✦ 16 command tokens.&rdquo;</li>
        </ul></li>
    <li>When a discard pile is shuffled to form a new deck, any cards that have been purged are not included.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 70.1: &ldquo;If an ability instructs a player to purge a component, that component is removed from the game and returned to the box.&rdquo; purged cards are out of the game, so not in the discard pile.</li>
        </ul></li>
    <li>If a player removes a unit in order to place it, because they have none of that unit type in their reinforcements, that unit is placed undamaged.<sup>4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;If it is produced, placed, or replaced which would require a remove and place it is no longer damaged.&rdquo;</li>
        </ul></li>
    <li>If a player is instructed to &ldquo;replace&rdquo; one unit with another, and they have none of the replacement unit type in their reinforcements, they may remove a unit of that type from any system that does not contain one of their command tokens and place that unit instead.<sup>4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;Any instance of &lsquo;replace&rsquo; can be considered to say &lsquo;remove and place&rsquo; if no units are left in reinforcements, and would be covered by Component Limitations in the LRR.&rdquo;</li>
        </ul></li>
    </ol>
