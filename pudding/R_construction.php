<p>The source text behind each note on <a href="/R_construction">Construction (Strategy Card)</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Rules Reference</h2>
    <ul>
    <li>To resolve the primary ability on the <i>Construction</i> strategy card, the active player may either place one structure on a planet they control, or use the <a href="/R_production"><sc>Production</sc></a> ability of one of their space docks. Then, that player may place one structure on a planet they control.<sup>13</sup>
        <ul>
        <li><b>Explicit</b>: <sup>13</sup> Construction (Thunder&rsquo;s Edge), primary: &ldquo;Either place 1 structure on a planet you control, or use the PRODUCTION ability of 1 of your space docks. Place 1 structure on a planet you control.&rdquo;</li>
        </ul></li>
    <li>After the active player resolves the primary ability of the <i>Construction</i> strategy card, each other player, beginning with the player to the left of the active player and proceeding clockwise, may spend one command token from their strategy pool to place one structure on a planet they control. The command token is not placed in any system.<sup>2,13</sup>
        <ul>
        <li><b>Explicit</b>: <sup>13</sup> Construction (Thunder&rsquo;s Edge), secondary: &ldquo;Spend 1 token from your strategy pool to place 1 structure on a planet you control.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How does the Thunder&rsquo;s Edge Construction card differ?&rdquo;: &ldquo;Its secondary spends a strategy token to place a structure on a planet you control, but the token is no longer placed in that system.&rdquo;</li>
        </ul></li>
    </ul>

<h2>Notes</h2>
    <ol class="note">
    <li>A player may have a maximum of one space dock on each planet.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 85.4: &ldquo;A player can have a maximum of one space dock on each planet.&rdquo;</li>
        <li><b>Implicit</b>: <sup>3</sup> Learn to Play describes space docks; the limit is in the LRR.</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can I build space docks or PDS with Production?&rdquo;: &ldquo;A planet holds at most one space dock and two PDS, Mecatol Rex included.&rdquo;</li>
        </ul></li>
    <li>A player may have a maximum of two PDS units on each planet.<sup>1,2,3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 85.5: &ldquo;A player can have a maximum of two PDS units on each planet.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can I build space docks or PDS with Production?&rdquo;: &ldquo;A planet holds at most one space dock and two PDS, Mecatol Rex included.&rdquo;</li>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play: &ldquo;Players are limited to two PDS units and one space dock on each planet.&rdquo;</li>
        </ul></li>
    <li>Structures cannot be placed on the planet with the <a href="https://twilight-imperium.fandom.com/wiki/Agenda_Cards#Directives:~:text=Demilitarized%20Zone"><i>Demilitarized Zone</i></a> exploration card attached.<sup>*</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR FAQ: on a Demilitarized Zone planet, &ldquo;infantry cannot be placed on the elected planet.&rdquo; Structures are not addressed.</li>
        </ul></li>
    <li>Placing structures with the Construction strategy card is not producing units; the structures have no cost, and production rules do not apply.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do I pay resources for the structures placed with Construction?&rdquo;: &ldquo;No &mdash; space docks and PDS have no cost. Construction places them; it isn&rsquo;t production, so production rules don&rsquo;t apply.&rdquo;</li>
        </ul></li>
    <li>Resolving the secondary ability of the <i>Construction</i> strategy card does not activate a system, and it does not matter whether the system has already been activated.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How does the Thunder&rsquo;s Edge Construction card differ?&rdquo;: &ldquo;It doesn&rsquo;t activate the system or care whether it was activated.&rdquo;</li>
        </ul></li>
    </ol>
