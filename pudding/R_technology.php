<h2>Rules Reference</h2>
    <ul>
    <li>(Thunder&rsquo;s Edge) A planet with two technology specialties can be exhausted to ignore either or both of the matching prerequisite symbols.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Dual Specialties: &ldquo;Some planets have two technology specialties. These planets can be exhausted when researching technology to satisfy either or both prerequisites simultaneously.&rdquo;</li>
        </ul></li>
    </ul>

<h2>Notes</h2>
    <ol class="note">
    <li>If a player is instructed to research a technology by any game effect, that player must meet the prerequisites for the technology they research.<sup>1,2,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;If an ability instructs you to &lsquo;research&rsquo; a technology, you require the prerequisites on that technology to do so.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;If an effect lets me research a technology, do I pay for it?&rdquo;: &ldquo;You still meet prerequisites (specialties can help).&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 90.9: &ldquo;Other game effects may also instruct a player to research technology.&rdquo;</li>
        </ul></li>
    <li>If a player is instructed to gain a technology, that player does not have to meet the prerequisites.<sup>1,2,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 90.5: &ldquo;If an ability instructs a player to gain a technology, they do not research it; they take it from their technology deck and place it in their play area, ignoring prerequisites.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;&rsquo;Gain&rsquo; is different from &lsquo;research&rsquo;: gaining ignores prerequisites.&rdquo;</li>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;If you are instructed to &lsquo;gain&rsquo; or &lsquo;replace&rsquo; a technology, you do not require prerequisites.&rdquo;</li>
        </ul></li>
    <li>If a player is playing a faction with a faction&ndash;specific unit upgrade, they cannot research or otherwise gain the generic upgrade for that unit type.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;Do faction technologies replace generic ones?&rdquo;: &ldquo;Only faction unit upgrades replace the matching generic upgrade; all other faction technologies are extras.&rdquo;</li>
        </ul></li>
    <li>An exhausted technology still satisfies prerequisites.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Does a technology I just researched, or one that is exhausted, count as a prerequisite?&rdquo;: &ldquo;Yes to both. Owned technologies always count, exhausted or not.&rdquo;</li>
        </ul></li>
    <li>The first technology researched with the primary ability of the <a href="/R_technology_sc"><i>Technology</i></a> strategy card may satisfy a prerequisite of the second technology researched with that ability.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> Same entry: &ldquo;the first technology from the Technology primary counts for the second.&rdquo;</li>
        </ul></li>
    <li>If an exhausted technology is returned to a player&rsquo;s technology deck and later researched again, it is gained readied.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;If an exhausted technology returns to my deck and is researched again, is it exhausted?&rdquo;: &ldquo;No &mdash; cards in the deck have no state, so it comes back ready.&rdquo;</li>
        </ul></li>
    </ol>
