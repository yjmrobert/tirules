<h2 id="exotrireme"><a href="https://twilight-imperium.fandom.com/wiki/Sardakk_N&#x27;orr#:~:text=Exotrireme">Exotrireme</a> <sub>(Unit)</sub></h2>
    <ol class="note">
    <li>When resolving the ability of an Exotrireme II, the N&rsquo;orr player chooses which ships are destroyed.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;The N&rsquo;orr player selects the units to be destroyed.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can Sustain Damage save a ship from Exotrireme II &hellip;?&rdquo;: &ldquo;For Exotrireme II, the Sardakk player chooses which ships (up to 2) are destroyed.&rdquo;</li>
        </ul></li>
    <ol><li>The N&rsquo;orr player cannot choose their own ships as targets.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Can abilities that destroy units, such as the &lsquo;Lucky Shot&rsquo; action card, be used by a player against their own units or planets? A: No. &lsquo;Lucky Shot&rsquo; and other similar effects can only be used against other player&rsquo;s units and planets.&rdquo;</li>
        </ul></li></ol>
    <li>Effects that cancel hits, such as the <a href="/R_sustain_damage"><sc>Sustain Damage</sc></a> ability, cannot be used to prevent ships from being destroyed.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 87.5: &ldquo;The &lsquo;Sustain Damage&rsquo; ability cannot be used to cancel an effect that directly destroys a unit.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;No &mdash; Sustain Damage only cancels hits, and these effects destroy units without producing hits.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;sustain damage cannot be used against abilities that &lsquo;destroy&rsquo;.&rdquo;</li>
        </ul></li>
    <li>If a player retreats, the N&rsquo;orr player will be unable to use the ability of an Exotrireme II to destroy an opponent&rsquo;s ship.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When exactly can Exotrireme II use its ability?&rdquo;: &ldquo;it can&rsquo;t be used if that Exotrireme was destroyed or a retreat was announced.&rdquo;</li>
        </ul></li>
    <li>If the N&rsquo;orr player is in a combat with the <a href="/F_yin">Yin</a> player, then the two players will alternate when resolving end of combat round abilities, starting with the attacker.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When both players have end-of-round abilities, like Yin&rsquo;s Devotion and Sardakk&rsquo;s Exotrireme II, who goes first?&rdquo;: &ldquo;The active player resolves one first, then the players alternate one ability at a time.&rdquo;</li>
        </ul></li>
    <li>An Exotrireme II that used its <a href="/R_sustain_damage"><sc>Sustain Damage</sc></a> ability during a combat round may still be destroyed to resolve its ability at the end of that round.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When exactly can Exotrireme II use its ability?&rdquo;: &ldquo;A dreadnought can use Sustain Damage that round and still be sacrificed afterwards.&rdquo;</li>
        </ul></li>
    </ol>

