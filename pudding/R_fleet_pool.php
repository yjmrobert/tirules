<p>The source text behind each note on <a href="/R_fleet_pool">Fleet Pool</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>Fighters and ground forces do not count toward capacity during combat. When combat ends however, units will need to be removed to meet capacity requirements.<sup>1,2,3,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 16.4c: &ldquo;A player&rsquo;s fighters and ground forces do not count against capacity during combat. At the end of combat, any excess units are removed.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;If my carrier is destroyed in combat &hellip;?&rdquo;: &ldquo;capacity isn&rsquo;t checked during combat, so they stay while it lasts.&rdquo;</li>
        <li><b>Implicit</b>: <sup>3</sup> Learn to Play: the excess units are destroyed &ldquo;If at any time&rdquo; capacity is exceeded, outside combat.</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;During a combat, the fighters would persist until the end of combat.&rdquo;</li>
        </ul></li>
    <li>Ships may be moved into or produced in a system even if doing so would exceed the fleet pool limit. However, some of those ships must immediately be removed to satisfy the limit.<sup>2,5,6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can I deliberately go over my fleet pool by moving or producing, then remove ships of my choice?&rdquo;: &ldquo;Yes &mdash; nothing stops you; you just remove the excess right away, choosing which.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;Once all ships are in, fleet supply is in violation and must immediately be dealt with.&rdquo;</li>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus, on Auto-Factories: &ldquo;with zero in fleet you can produce 3 ships, gain the fleet token, then remove 2 ships to fleet pool.&rdquo;</li>
        </ul></li>
    <ol><li>If some of those ships are fighters II, they may instead count toward that player&rsquo;s capacity in that system. If capacity is exceeded, fighters or ground forces must be removed to meet the limit.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can fighters stay in a system without a carrier or space dock?&rdquo;: &ldquo;Fighter IIs that don&rsquo;t fit in capacity count against your fleet pool like other ships.&rdquo;</li>
        </ul></li></ol>
    <li>During movement, a ship may move through a system regardless of how many ships are in that system relative to the fleet pool limit.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When is the fleet pool limit checked &hellip;?&rdquo;: &ldquo;At all times, except for ships that are only moving through other systems.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (Bocks, Mar 17, 2018): &ldquo;In neither instance do you need to destroy any ships due to fleet supply&rdquo;</li>
        </ul></li>
    </ol>
