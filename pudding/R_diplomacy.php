<p>The source text behind each note on <a href="/R_diplomacy">Diplomacy (Strategy Card)</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>If the player with <i>Diplomacy</i> controls no planets, or controls only <a href="/R_mecatol_rex">Mecatol Rex</a>, they may still perform a strategic action. However, other players will not place a command token in any system.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR 32.2: the active player &ldquo;chooses a system that contains a planet they control other than the Mecatol Rex system.&rdquo;</li>
        </ul></li>
    <li>If the player with <i>Diplomacy</i> controls fewer than two exhausted planets, they may still perform a strategic action. They will ready as many planets as possible.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How does the revised Diplomacy strategy card work?&rdquo;: the primary player may &ldquo;ready up to 2 exhausted planets they control.&rdquo; &ldquo;Up to&rdquo; covers fewer.</li>
        </ul></li>
    <li>The Diplomacy token represents a command token from each player other than the player with the <i>Diplomacy</i> strategy card. It may be used to simplify play when no player is expected to interact with the command tokens placed by the primary ability.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 12, Diplomacy Token: &ldquo;This token is a player aid included to facilitate ease of play when resolving simple uses of the &lsquo;Diplomacy&rsquo; strategy card&rsquo;s primary ability. It represents a command token from each player.&rdquo;</li>
        </ul></li>
    <ol>
        <li>A player cannot increase the number of tokens they have access to from the use of the Diplomacy token.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Same passage: &ldquo;It cannot be used to bring a player above the component limit for command tokens.&rdquo;</li>
        </ul></li>
        <li>Game effects that can remove a command token from a system may still be used to remove a command token from the system containing the Diplomacy token. Should this happen, players may first wish to replace the Diplomacy token with the corresponding command tokens, then remove the required command token, leaving the rest in the system.<sup>2,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can Warfare, Counterstroke or other effects remove a token placed by Diplomacy?&rdquo;: &ldquo;Yes &mdash; once placed it is an ordinary command token &hellip; Warfare, Counterstroke, Unexpected Action and similar effects can remove it.&rdquo;</li>
        <li><b>Implicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook, Diplomacy Token: &ldquo;should not be used when interacting with abilities that remove command tokens.&rdquo; such abilities handled without the token.</li>
        </ul></li>
        <li>The system that contains the Diplomacy token should be treated as containing a command token of the relevant players for all game effects.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 12: &ldquo;It represents a command token from each player.&rdquo;</li>
        </ul></li>
    </ol>
    </ol>
