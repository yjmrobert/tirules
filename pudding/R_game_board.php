<h2>Rules Reference</h2>
    <ul>
    <li>(Thunder&rsquo;s Edge) Each system in The Fracture is considered to be on the edge of the game board.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 9: &ldquo;Regardless of where The Fracture is placed, its systems are not adjacent to the systems it is touching, and each of its systems is considered to be on the edge of the game board.&rdquo;</li>
        </ul></li>
    </ul>

<h2>Notes</h2>
    <ol class="note">
    <li>If the edge of a system tile is touching a hyperlane tile, that edge does not cause that system tile to be on the edge of the game board.<sup>2,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;In maps utilizing hyperlanes (e.g. 5p map), what counts as the edge of the game board? A: Intention is that one of the edges of a system tile does not touch another system tile OR hyperlane tile in order to be considered on the edge of the board.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;With hyperlanes, which systems are on the edge of the board?&rdquo;: &ldquo;A system is on the edge only if one of its sides touches neither another system nor a hyperlane tile.&rdquo;</li>
        </ul></li>
    <ol>
        <li>When using the five&ndash; and seven&ndash;player hyperlane setups, the system tile in the center of the ring of hyperlanes is not on the edge of the game board.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> Same entry: &ldquo;tiles beside hyperlanes, and a system enclosed by them, aren&rsquo;t edge systems.&rdquo;</li>
        </ul></li>
        <li>When using the seven&ndash; and eight&ndash;player alternate setups, only the system tiles designated as &ldquo;Ring 3&rdquo; and home systems are on the edge of the game board, along with the <a href="/F_creuss">Creuss</a> home system and the wormhole nexus.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>
    </ol>
