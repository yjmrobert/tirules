<h2 id="construction-rider"><a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Construction%20Rider">Construction Rider</a></h2>
    <ol class="note">
    <li>After playing a <i>Construction Rider</i>, a player may play other rider cards.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;A player may play multiple rider action cards on a single agenda, and they may be played on opposing outcomes.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can one player play several riders on the same agenda, on different outcomes?&rdquo;: &ldquo;Yes &mdash; FFG confirmed by email that you can play several riders in the same vote.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (MATTPROV3, Nov 17, 2017): &ldquo;You can indeed play multiple rider cards in the same vote.&rdquo;</li>
        </ul></li>
    <ol><li>Any other riders may be played to predict the same or a different outcome.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;A player may play multiple rider action cards on a single agenda, and they may be played on opposing outcomes.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;Each rider is played on its own, so each can predict a different outcome, letting you cover both For and Against.&rdquo;</li>
        </ul></li></ol>
    <li>The effect of a successful <i>Construction Rider</i> will be resolved after the effect of the agenda.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When an agenda outcome and a rider both award points, which resolves first?&rdquo;: &ldquo;The agenda&rsquo;s outcome resolves first, then the riders that predicted it.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 8.22b: &ldquo;After resolving the outcome of the agenda, any abilities that were dependent upon predicting the outcome are resolved.&rdquo;</li>
        </ul></li>
    <li>A player who cannot vote may still play a <i>Construction Rider</i>.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;The Nekro player, or a player who cannot vote due to another effect, can still play rider action cards.&rdquo;</li>
        </ul></li>
    <li>If a player wishes to place a space dock, but there are none left in their reinforcements, they may remove a space dock from any system that does not contain one of their command tokens and place that instead.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 23.4a: &ldquo;When a player would place a unit, if there are none of that type left in their reinforcements, that player can remove a unit from any system that does not contain one of their command tokens and place that unit in their reinforcements.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;If all my space docks or PDS are on the board, can I place another?&rdquo;: &ldquo;if none are in reinforcements, you may take one from a system without your command token and place it where the effect directs.&rdquo;</li>
        </ul></li>
    <li>The <a href="/F_saar">Saar</a> player may play a <i>Construction Rider</i>, and may place a space dock in a system containing a planet they control if successful.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>If a player successfully resolves a <i>Construction Rider</i> while they own the <a href="https://twilight-imperium.fandom.com/wiki/Agenda_Cards#Directives:~:text=Minister%20of%20Industry"><i>Minister of Industry</i></a> law, they use the <a href="/R_production"><sc>Production</sc></a> ability of their units in the system where they place their space dock. They may exhaust planets for resources, but those planets cannot be used to cast votes for the remainder of the agenda phase.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;What triggers Minister of Industry?&rdquo;: &ldquo;a dock placed by a Construction Rider in the agenda phase does, payable only with planets you haven&rsquo;t exhausted.&rdquo;</li>
        </ul></li>
    <ol><li>All planets will be readied at the end of the agenda phase.<sup>3</sup>
        <ul>
        <li><b>Explicit</b>: <sup>3</sup> Learn to Play, Agenda Phase: &ldquo;3. READY PLANETS Each player readies all of their planet cards. Then, the agenda phase ends&rdquo;</li>
        </ul></li></ol>
    </ol>

