<h2 id="maneuvering-jets"><a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Maneuvering%20Jets">Maneuvering Jets</a></h2>
    <ol class="note">
    <li><i>Maneuvering Jets</i> may cancel hits produced during either the <b>Space Cannon Offense</b> or the <b>Space Cannon Defense</b> step.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Does Maneuvering Jets protect infantry from Space Cannon Defense?&rdquo;: &ldquo;Yes &mdash; it cancels Space Cannon hits on your ground forces as well as your ships.&rdquo;</li>
        </ul></li>
    <li><i>Maneuvering Jets</i> cannot be used to cancel hits during combat.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;Do Maneuvering Jets protect infantry from Space Cannon Defense?&rdquo;: &ldquo;it cancels Space Cannon hits on your ground forces as well as your ships.&rdquo; Space Cannon hits only.</li>
        </ul></li>
    <li>A player cannot play a second <i>Maneuvering Jets</i> to cancel a second hit produced by the same Space Cannon roll.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal, &ldquo;Can I play two copies of the same action card &hellip; in one timing window?&rdquo;: &ldquo;you cannot play more than one action card with the same name in a single timing window to affect the same units or effect.&rdquo;</li>
        </ul></li>
    <ol>
        <li>During the <b>Space Cannon Offense</b> step, each player makes their Space Cannon roll independent of each other player, in clockwise order. As such, a player may use one <i>Maneuvering Jets</i> after each other player makes a space cannon roll.<sup>2</sup>
        <ul>
        <li><b>Implicit</b>: <sup>2</sup> RulesPal: the limit on same-name cards applies to &ldquo;a single timing window &hellip; the same units or effect.&rdquo; Each player&rsquo;s roll is a separate effect.</li>
        </ul></li>
        <li>During the <b>Space Cannon Defense</b> step, the units on each planet make their Space Cannon roll independent of the units on each other planet. The active player chooses the order. As such, a player may use one <i>Maneuvering Jets</i> for each planet they are committing ground forces to.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>
    </ol>

