<h2 id="bribery"><a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Bribery">Bribery</a></h2>
    <ol class="note">
    <li>The text of <i>Bribery</i> is changed to: &ldquo;After the speaker votes on an agenda: Spend any number of trade goods. For each trade good spent, cast 1 additional vote for the outcome on which you voted.&rdquo;<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR errata: &ldquo;The text of the action card &lsquo;Bribery&rsquo; should read as follows: &lsquo;After the speaker votes on an agenda: Spend any number of trade goods. For each trade good spent, cast 1 additional vote for the outcome on which you voted.&rsquo;&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Who can play Bribery, and when?&rdquo;: &ldquo;Per its errata, Bribery is played after the speaker votes and each trade good spent adds a vote to the outcome you voted for.&rdquo;</li>
        </ul></li>
    <li><i>Bribery</i> may be played after the speaker has abstained, or would vote if they are unable to.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;even if the speaker cannot vote, or chooses not to vote, the &lsquo;Bribery&rsquo; action card &hellip; can still be played after the timing window in which the speaker would have cast votes.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (sigmazero13, Mar 7, 2018): &ldquo;You can still play Bribery even if the speaker does not vote.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Who can play Bribery, and when?&rdquo;: &ldquo;nor can a speaker who abstained, but others who voted still can.&rdquo;</li>
        </ul></li>
    <li>A player may spend zero trade goods when they play <i>Bribery</i>.<sup>1</sup>
        <ul>
        <li><b>Implicit</b>: <sup>1</sup> LRR errata, Bribery: &ldquo;Spend any number of trade goods.&rdquo; Any number includes zero.</li>
        </ul></li>
    <li>A player must have cast votes for an outcome to play <i>Bribery</i>, and the additional votes must be cast for the same outcome.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (sigmazero13, Jun 11, 2018): &ldquo;You can&rsquo;t use Bribery after abstaining and you can&rsquo;t use it if another effect is stopping you from casting votes.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Who can play Bribery, and when?&rdquo;: &ldquo;Only a player who actually voted. &hellip; each trade good spent adds a vote to the outcome you voted for.&rdquo;</li>
        <li><b>Explicit</b>: <sup>1</sup> LRR errata, Bribery: &ldquo;cast 1 additional vote for the outcome on which you voted.&rdquo;</li>
        </ul></li>
    <ol><li>If the <a href="/F_argent">Argent</a> player is speaker, only they can play <i>Bribery</i>, and must do so immediately after they cast votes.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Who can play Bribery, and when?&rdquo;: &ldquo;If an Argent speaker votes first with Zeal, Bribery comes right after that vote.&rdquo;</li>
        </ul></li></ol>
    <li>Casting additional votes with <i>Bribery</i> does not allow a player to play <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Distinguished%20Councilor"><i>Distinguished Councilor</i></a>; it can only be played after their normal vote.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Does an effect that casts &lsquo;additional votes,&rsquo; such as the &lsquo;Bribery&rsquo; action card, create a timing window for playing the &lsquo;Distinguished Councilor&rsquo; action card? A: No. The &lsquo;Distinguished Councilor&rsquo; action card can only be played after you vote during the &lsquo;Vote&rsquo; step of resolving an agenda.&rdquo;</li>
        </ul></li>
    <ol><li>The speaker may play <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Distinguished%20Councilor"><i>Distinguished Councilor</i></a> after they or another player play <i>Bribery</i>, as both are played in the timing window after the speaker votes.<sup>5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (0 hr, Jul 19, 2018), on resolving abilities in the same agenda-phase timing window: &ldquo;Once someone has played an ability, every other player will have exactly one chance to continue.&rdquo; Bribery (&ldquo;After the speaker votes&rdquo;) and the speaker&rsquo;s Distinguished Councilor (&ldquo;After you cast votes&rdquo;) share the window opened by the speaker&rsquo;s vote, so the speaker gets another chance after a Bribery. The LRR FAQ (&ldquo;Bribery&rdquo; does not &ldquo;create a timing window for playing the &lsquo;Distinguished Councilor&rsquo; action card&rdquo;) is about the Bribery player&rsquo;s own extra votes, not this case.</li>
        </ul></li></ol>
    <li><i>Bribery</i> is played before any effects that change the outcome of an agenda.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>

