<header><h1>Neutral Units: Proof</h1></header>
<article>
<p>The source text behind each note on <a href="/R_neutral_units">Neutral Units</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>Neutral units are placed in some systems within The Fracture when it enters play. Several other game effects also place neutral units.<sup>7,11</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 9: &ldquo;They then place neutral units as indicated on the back of The Fracture&rsquo;s tiles.&rdquo;</li>
        <li><b>Implicit</b>: <sup>11</sup> Codex IV, Minor Factions: &ldquo;that player places 3 neutral infantry on that system&rsquo;s planets.&rdquo;</li>
        </ul></li>
    <li>If a player has ships in a space area that contains neutral units, they will resolve a space combat against those units.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10, Neutral Units: &ldquo;Neutral units are non-player forces that engage a player in combat if the player moves units to the planet or space area that those neutral units occupy.&rdquo;</li>
        </ul></li>
    <li>If a player has ground forces on a planet that contains neutral units, they will resolve a ground combat against those units.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10, Neutral Units: the same passage: they &ldquo;engage a player in combat if the player moves units to the planet &hellip; that those neutral units occupy.&rdquo;</li>
        </ul></li>
    <li>Any player other than the active player may roll the combat and unit ability dice during a combat involving neutral units. The combat values and unit abilities are found on the neutral unit reference card.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10, Neutral Units: &ldquo;Neutral units&rsquo; combat stats are indicated on the neutral unit reference card, and their rolls are made by any player other than the active player.&rdquo;</li>
        </ul></li>
    <li>Neutral units will always use each and every unit ability that they can.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10, Neutral Units: &ldquo;Neutral units always use unit abilities when they can (sustain damage, space cannon, etc.).&rdquo;</li>
        </ul></li>
    <li>Neutral units do not take turns, own technology, or draw action cards, and so on.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10, Neutral Units: &ldquo;but are otherwise unable to use any other abilities. Neutral units do not take turns or perform&rdquo; actions.</li>
        </ul></li>
    <li>When a hit is assigned against a group of neutral units, it is assigned to the unit that is lowest on the neutral unit reference card.<sup>6,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10, Neutral Units: &ldquo;During combat, hits are assigned to neutral units in the order presented on the neutral unit reference, prioritizing&rdquo; units lower on the card.</li>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;prioritizing units lower on the reference card first.&rdquo;</li>
        </ul></li>
    <li>Neutral units are considered to be another player&rsquo;s ships for abilities and other game effects. However, there is no neutral player.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10, Neutral Units: &ldquo;Neutral units count as other player&rsquo;s units for the purpose of resolving players&rsquo; abilities and other game effects. There is, however, no &lsquo;neutral player.&rsquo;&rdquo;</li>
        </ul></li>
    <li>Neutral units with <a href="/R_sustain_damage"><sc>Sustain Damage</sc></a> use it to cancel hits before any remaining hits are assigned. For example, if a neutral destroyer and a neutral dreadnought take one hit, the dreadnought uses <a href="/R_sustain_damage"><sc>Sustain Damage</sc></a> to cancel it.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Sustain window occurs before assign hits and all units with SUSTAIN will use this to cancel hits before then assigning hits to neutral units.&rdquo;</li>
        </ul></li>
    <li>Neutral units cannot make decisions. If a decision must be made for a neutral unit, the speaker makes it.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10, Neutral Units: &ldquo;neutral units are incapable of making decisions; in the unlikely event that a decision needs to be made for a neutral unit, the speaker makes that decision instead.&rdquo;</li>
        </ul></li>
    <ol><li>During combat, hits against neutral units are always assigned in the order on the neutral unit reference card, so the speaker does not choose. The speaker does choose which neutral units are hit outside of combat, such as by <a href="/R_space_cannon"><sc>Space Cannon</sc></a>.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;How are hits assigned to neutral units outside of combat (for example, SPACE CANNON)? A: Speaker decides any decisions for the neutral units that are not hits during combat.&rdquo;</li>
        </ul></li></ol>
    <li>If there are no neutral units of a given type left in the supply, and one would be placed, it is not placed.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;What happens if there are no more neutral units of a given type available in the supply, and another is required to be placed? A: They are not placed.&rdquo;</li>
        </ul></li>
    </ol>
</article>
