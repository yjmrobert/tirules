<p>The source text behind each note on <a href="/R_trade">Trade (Strategy Card)</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>Say, for example, Alice is the active player, and is performing a strategic action with the <i>Trade</i> strategy card. To her left is Bob. To his left is Cheng, then Diego, then Esther, then Fahd. The full order of steps is:<sup>1,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 92.2&ndash;92.5: the active player gains 3 trade goods, replenishes commodities, chooses players; then &ldquo;each other player, beginning with the player to the left of the active player,&rdquo; may resolve the secondary.</li>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (sigmazero13, Jan 17, 2018): &ldquo;The freebie secondary players resolve the secondaries during the normal time and in clockwise order from the active player, intermingled with those paying for it manually.&rdquo; Supports secondary ordering only.</li>
        </ul></li>
    <ol>
        <li>Alice gains three trade goods.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 92.2: &ldquo;STEP 1&mdash;The active player gains 3 trade goods.&rdquo;</li>
        </ul></li>
        <li>Alice replenishes her commodities.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 92.3: &ldquo;STEP 2&mdash;The active player replenishes their commodities.&rdquo;</li>
        </ul></li>
        <li>Alice chooses players for the secondary.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 92.4: &ldquo;STEP 3&mdash;The active player chooses any number of other players.&rdquo;</li>
        </ul></li>
        <li>Bob may/must replenish his commodities by performing the secondary ability.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 92.4a: &ldquo;The chosen players must resolve the secondary ability of this card without spending a command token after the active player finishes resolving the primary ability.&rdquo; Others may by spending a token (92.5).</li>
        </ul></li>
        <li>Cheng may/must replenish her commodities by performing the secondary ability.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> Same rules, in clockwise order from the active player&rsquo;s left (92.5).</li>
        </ul></li>
        <li>Diego may/must replenish his commodities by performing the secondary ability.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> Same rules, in clockwise order (92.5).</li>
        </ul></li>
        <li>Esther may/must replenish her commodities by performing the secondary ability.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> Same rules, in clockwise order (92.5).</li>
        </ul></li>
        <li>Fahd may/must replenish his commodities by performing the secondary ability.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> Same rules, in clockwise order (92.5).</li>
        </ul></li>
    </ol>
    <li>Choosing players to resolve the secondary ability of <i>Trade</i> without spending a command token is not a transaction. Those players do not need to be neighbors of the active player, and it does not count towards the active player&rsquo;s transaction limit.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Is replenishing other players&rsquo; commodities with Trade a transaction?&rdquo;: &ldquo;No &mdash; it is a strategy card effect: recipients needn&rsquo;t be neighbors, can&rsquo;t refuse, it doesn&rsquo;t use up a transaction&rdquo;</li>
        </ul></li>
    <p>A deal made during a given step is non&ndash;binding if any part of it is to resolve during a later step. As such, if Alice makes a deal to chose a player with the primary ability in exchange for commodities from that player after they perform the secondary, then such a deal will be non&ndash;binding.<sup>2,5</sup></p>
    <li>If a player has their maximum number of commodities, and is instructed to replenish their commodities, they will take no commodities. However, they will still trigger any &ldquo;when [this] player replenishes commodities&rdquo; effects, most notably the <a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Trade_Agreement"><i>Trade Agreement</i></a> promissory note.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;If a player would refresh their commodities but already has the maximum amount, can another player still play that player&rsquo;s &lsquo;Trade Agreement&rsquo; promissory note against them? A: Yes. Even if that player gains zero commodities.&rdquo;</li>
        </ul></li>
    </ol>
