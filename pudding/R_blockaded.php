<h2>Rules Reference</h2>
    <ul>
    <li>(Thunder&rsquo;s Edge) <a href="/R_coexistence">Coexisting</a> units are always blockaded, so they can produce ground forces but cannot produce ships.<sup>7,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 11, Coexist: &ldquo;Coexisting structures are always blockaded.&rdquo;</li>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Coexistence and PRODUCTION&rdquo;: &ldquo;Coexisting units can produce ground forces but are always blockaded and cannot produce ships.&rdquo;</li>
        </ul></li>
    </ul>

<h2>Notes</h2>
    <ol class="note">
    <li>While a player is involved in a space combat in a system, their units in that system are not blockaded, as both players will have ships in the system.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;With Prophecy of Kings capture rules, when exactly is a space dock blockaded?&rdquo;: &ldquo;a system with another player&rsquo;s ships and none of yours &hellip; during combat both sides have ships, so a dock isn&rsquo;t blockaded until combat ends.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 14: &ldquo;A player&rsquo;s unit with &ldquo;Production&rdquo; is blockaded if it is in a system that does not contain any of their ships and contains other players&rsquo; ships.&rdquo; in combat both players have ships there, so the blockade condition fails.</li>
        </ul></li>
    <li>If, at the end of a combat, one player has no ships, but a space dock in the system, and the other player has only fighters, the space dock will be blockaded before the fighters are removed.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>When a ship moves, it does not blockade units in systems it moves through.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>
