<article>
<p>The source text behind each note on <a href="/R_space_stations">Space Stations</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>Several systems contain space stations.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: &ldquo;Some systems contain space stations.&rdquo;</li>
        </ul></li>
    <li>A player gains control of a space station when they are the only player with ships in that space station&rsquo;s system.<sup>2,6,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Same passage: &ldquo;A player gains control of a space station from the deck or from another player when they are the only player that has ships in its system.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When do I gain and lose control of a space station?&rdquo;: &ldquo;You gain it as soon as you are the only player with ships in its system.&rdquo;</li>
        <li><b>Implicit</b>: <sup>6</sup> Community consensus: &ldquo;Does a player gain control of a space station before combat against neutral units, as they will be the only player with units there?&rsquo; Answer: &lsquo;Yes, there is no Neutral Player.&rdquo;</li>
        </ul></li>
    <ol>
        <li>If another player moves ships into that system, they will not gain control of that space station unless they win the resulting space combat.<sup>7</sup>
        <ul>
        <li><b>Implicit</b>: <sup>7</sup> Same passage: control requires being &ldquo;the only player that has ships in its system.&rdquo;</li>
        </ul></li>
        <li>If the player who controls the space station moves their ships out of the system, they retain control of that space station.<sup>2,7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Same passage: &ldquo;They do not lose control of the station if those ships move out of its system.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;you keep it after leaving until another player becomes the only one with ships there.&rdquo;</li>
        </ul></li>
    </ol>
    <li>A player does not lose control of a space station if a neutral ship is placed in its system, as there is no neutral player.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Does a player lose control of a space station if a neutral ship is placed in its system? A: No, there is no Neutral Player.&rdquo;</li>
        </ul></li>
    <li>A player whose ships are in a space station&rsquo;s system with only neutral units gains control of that space station before resolving combat against those neutral units, as there is no neutral player.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Does a player gain control of a space station before combat against neutral units &hellip;? A: Yes, there is no Neutral Player.&rdquo;</li>
        </ul></li>
    <li>Each space station has a corresponding planet card. The space station may be exhausted for resources or influence as though it were a planet. The space station will be readied during the status phase as though it were a planet, or by other game effects that can ready planets.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: &ldquo;Each space station has a corresponding planet card, which is gained exhausted and is spent, readied as if it were a planet.&rdquo;</li>
        </ul></li>
    <ol><li>Space stations are also readied at the end of the agenda phase.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found. Owner ruling (2026-11-21): planets, including oceans, space stations and The Triad, are readied at the end of the agenda phase.</li>
        </ul></li></ol>
    <li>A player may exhaust a space station at any time to convert any commodities that they have into trade goods.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: &ldquo;players can exhaust a space station&rdquo; to convert commodities to trade goods.</li>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge reference: &ldquo;Exhaust to convert commodities to trade goods.&rdquo;</li>
        </ul></li>
    <li>For each space station a player controls, their commodity value is increased by one.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: &ldquo;A player&rsquo;s commodity value is increased by 1 for each space station they control.&rdquo;</li>
        </ul></li>
    <ol><li>Players may place a space station commodity token in the commodity area of their faction sheet as a reminder of their increased commodity value.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge reference: &ldquo;Increases commodity value by 1 (put space station token in commodity pool as a reminder).&rdquo;</li>
        </ul></li></ol>
    <li>A player who controls one or more space stations may resolve transactions with other players who control one or more space stations.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: &ldquo;A player that controls a space station can resolve transactions with other players that control a space station, even if they are not neighbors.&rdquo;</li>
        </ul></li>
    <ol><li>Players who resolve transactions in this manner need not be neighbors.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Same passage: &ldquo;even if they are not neighbors.&rdquo;</li>
        </ul></li></ol>
    <li>A player can exhaust space stations to cast votes. However, space stations are not planets, so they cannot be elected.<sup>6,7,9</sup>
        <ul>
        <li><b>Explicit</b>: <sup>9</sup> Designer Q&amp;A, &ldquo;Voting with Space Stations&rdquo;: &ldquo;can you vote with space stations &hellip;? A: Yeah you can vote with them.&rdquo;</li>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Can you vote using the influence from Trade stations? A: Yes, Space Stations are used for voting but may not be elected.&rdquo;</li>
        <li><b>Implicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: space stations &ldquo;do not count as planets for the purpose voting, objectives, or controlling a home system.&rdquo; Read with sources 6 and 9 as covering election, not casting votes.</li>
        </ul></li>
    <li>Space stations are not planets, so attachments such as the <a href="https://twilight-imperium.fandom.com/wiki/Relics#Codex_II:~:text=Nano-Forge"><i>Nano&ndash;Forge</i></a> relic and the <a href="/F_ul">Ul</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Titans_of_Ul#Faction_Promissory_Note:~:text=Terraform"><i>Terraform</i></a> promissory note cannot be attached to them.<sup>6</sup>
        <ul>
        <li><b>Explicit</b>: <sup>6</sup> Community consensus: &ldquo;Can Nano-Forge and/or Terraform be attached to a space station? A: No, Space Stations are not planets and can&rsquo;t have attachments.&rdquo;</li>
        </ul></li>
    <li>A space station is not a planet; controlling one does not prevent a player from being eliminated.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;A space station isn&rsquo;t a planet, so controlling one doesn&rsquo;t stop you being eliminated.&rdquo;</li>
        </ul></li>
    <li>Structures and ground forces cannot be committed to or placed on a space station.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Same passage: &ldquo;structures and ground forces cannot be placed on or committed to space stations.&rdquo;</li>
        </ul></li>
    <li>Space Stations do not count as planets for the purpose of scoring objectives, and a player may still score public objectives even if another player controls a space station in their home system.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 10: they &ldquo;do not count as planets for the purpose voting, objectives, or controlling a home system.&rdquo;</li>
        </ul></li>
    <li>If a system tile contains a space station, but no planets, then a frontier token will be placed in that system during game setup.<sup>7</sup>
        <ul>
        <li><b>Explicit</b>: <sup>7</sup> Thunder&rsquo;s Edge Rulebook p. 16: &ldquo;A system that contains a space station and no planets gets a frontier token during setup.&rdquo;</li>
        </ul></li>
    </ol>
