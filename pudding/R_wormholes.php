<h2>Notes</h2>
    <ol class="note">
    <li>A system containing a wormhole is not an anomaly.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Which systems count as anomalies?&rdquo;: &ldquo;Empty systems and wormhole systems are not anomalies unless bordered.&rdquo;</li>
        </ul></li>
    <li>If a system contains multiple wormholes of the same type, those are treated as separate wormholes.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>A system cannot be adjacent to itself, even if it has multiple wormholes in it.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 6.2a: &ldquo;A system is not adjacent to itself.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do ships in Mecatol Rex&rsquo;s system, or in an anomaly, count as adjacent to it for objectives?&rdquo;: &ldquo;No &mdash; a system isn&rsquo;t adjacent to itself.&rdquo;</li>
        </ul></li>
    <li>A player chooses the path of adjacent systems each ship moves through during movement.<sup>4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;When you move between systems that both contain a viable wormhole path, you can choose to use those wormholes, a different set of wormholes that are adjacent, or regular adjacency. The player moving the ships chooses the path their ships move through.&rdquo;</li>
        </ul></li>
    <ol>
        <li>If the two systems are adjacent because of a wormhole and because of a shared edge or another reason, the player may choose whether or not the ship moves through the wormhole.<sup>2,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;When you move between systems that both contain a viable wormhole path, you can choose to use those wormholes, a different set of wormholes that are adjacent, or regular adjacency. The player moving the ships chooses the path their ships move through.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;How do wormholes work, and must my ships use them?&rdquo;: &ldquo;A wormhole only adds connections: you don&rsquo;t have to use it.&rdquo;</li>
        </ul></li>
        <li>If the two systems are adjacent because of two types of wormholes, the player chooses which type of wormhole the ship moves through.<sup>2,4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;When you move between systems that both contain a viable wormhole path, you can choose to use those wormholes, a different set of wormholes that are adjacent, or regular adjacency. The player moving the ships chooses the path their ships move through.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;When does the Ion Storm flip, and does using a matching wormhole in the same system flip it?&rdquo;: &ldquo;With several wormhole routes, the moving player chooses which, if any, they use&rdquo;</li>
        </ul></li>
        <li>A player may move a ship back and forth through a wormhole between two systems any number of times, if its movement value is high enough.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
