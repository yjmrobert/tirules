<p>The source text behind each note on <a href="/R_action_cards">Action Cards</a>. <b>Explicit</b> sources state the note directly. <b>Implicit</b> sources support it without stating it.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>Players start the game with zero action cards.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Do players start the game with commodities, trade goods or action cards?&rdquo;: &ldquo;No &mdash; nobody starts with commodities, trade goods or action cards.&rdquo;</li>
        </ul></li>
    <li>The number of action cards in a player&rsquo;s hand is public information.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    <li>A player may choose to reveal any or all of the action cards in their hand.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;Can you intentionally reveal hidden information to another player, such as an action card from your hand &hellip;? A: Yes. This information is kept hidden by default, but it is permissible to reveal it.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can I show my action cards or secret objectives to other players?&rdquo;: &ldquo;Yes &mdash; you may reveal your own hidden cards to anyone at any time, and they still count as hidden afterwards.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (sigmazero13, Jan 16, 2018): &ldquo;There are no rules preventing players from showing an an action card from their hand.&rdquo;</li>
        </ul></li>
    <li>If the action card deck is depleted, immediately shuffle the discard pile to form a new action card deck.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 23.5: &ldquo;When a deck is depleted, players shuffle the deck&rsquo;s discard pile and place it facedown to create a new deck.&rdquo;</li>
        </ul></li>
    <li>During the status phase, action cards are drawn in initiative order, though this rarely matters in practice.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;In what order are action cards drawn in the status phase?&rdquo;: &ldquo;In initiative order, though it rarely matters in practice.&rdquo;</li>
        </ul></li>
    <ol>
        <li>If a player has the <a href="https://twilight-imperium.fandom.com/wiki/Biotic_Technologies#Neural_Motivator"><i>Neural Motivator</i></a> technology, they will draw both their action cards before the next player in order draws an action card.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
        <li>The <a href="/F_yssaril">Yssaril</a> player will draw all of their action cards, and discard for their <a href="https://twilight-imperium.fandom.com/wiki/The_Yssaril_Tribes#Faction_Abilities:~:text=Scheming"><sc>Scheming</sc></a> ability, before the next player in order draws an action card.<sup>*</sup>
        <ul>
        <li><b>Unverified</b>: No source found.</li>
        </ul></li>
    </ol>
    <li>If a player&rsquo;s action card is canceled, usually via a <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Sabotage"><i>Sabotage</i></a> action card, then if that player has a second copy of that action card, they may play it.<sup>2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;If my action card is cancelled by Sabotage, can I play another copy &hellip;?&rdquo;: &ldquo;Yes &mdash; a cancelled card is treated as never having been played.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling: &ldquo;Because the card was cancelled, yes, you can play another copy of the same action card.&rdquo;</li>
        </ul></li>
    <li>A player cannot use action cards that destroy units, such as <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Lucky%20Shot"><i>Lucky Shot</i></a>, against their own units.<sup>1,2,5</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR FAQ: &ldquo;&rsquo;Lucky Shot&rsquo; and other similar effects can only be used against other player&rsquo;s units and planets.&rdquo;</li>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal: &ldquo;abilities that destroy units can only be used against other players&rsquo; units and planets.&rdquo;</li>
        <li><b>Explicit</b>: <sup>5</sup> Designer ruling (Yin4Life, 12/10/2018): &ldquo;No, You cannot use Lucky Shot to target one of your own ships.&rdquo;</li>
        </ul></li>
    <li>If an action card targets &ldquo;each&rdquo; of a particular type of object, that action card may target zero of those objects. As such, these cards may be played even if they would cause no effect.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Can I play an action card whose effect would amount to nothing &hellip;?&rdquo;: &ldquo;Yes &mdash; doing the card&rsquo;s text with a result of zero still counts as resolving it.&rdquo;</li>
        </ul></li>
    <li>If an action card targets a specific number of a particular type of object, that action card cannot be played if those objects do not currently exist. For example, <a href="https://twilight-imperium.fandom.com/wiki/Action_Cards#Twilight_Imperium_Fourth_Edition:~:text=Repeal%20Law"><i>Repeal Law</i></a> cannot be played if there are no laws in play.<sup>5</sup>
        <ul>
        <li><b>Implicit</b>: <sup>5</sup> Designer ruling (x3n d0g, 1/25/2019): &ldquo;think Repeal Law when there are no laws in play&rdquo; Repeal Law is the cited example of a card with no legal target that cannot be played.</li>
        </ul></li>
