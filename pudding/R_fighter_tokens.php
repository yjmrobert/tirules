<h2>Notes</h2>
    <ol class="note">
    <li>As each player only has ten plastic fighter figures, a player cannot have fighters in more than ten systems.<sup>2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Are fighter and infantry tokens limited, and what are they for?&rdquo;: &ldquo;each stack of tokens must sit with at least one plastic piece of the same type. So your plastic fighters and infantry limit how many places you can have them.&rdquo;</li>
        </ul></li>
    <li>Players may also swap fighter tokens for plastic pieces at any time.<sup>1</sup>
        <ul>
        <li><b>Explicit</b>: <sup>1</sup> LRR 23.5: &ldquo;players can swap infantry and fighter tokens for plastic pieces&rdquo; as necessary.</li>
        </ul></li>
    <li>Fighter tokens are not component limited.<sup>1,2</sup>
        <ul>
        <li><b>Explicit</b>: <sup>2</sup> RulesPal, &ldquo;Are fighter and infantry tokens limited &hellip;?&rdquo;: &ldquo;Tokens are unlimited.&rdquo;</li>
        <li><b>Implicit</b>: <sup>1</sup> LRR 23.4: &ldquo;Units are limited to those included in the game, except for fighters and ground forces.&rdquo;</li>
        </ul></li>
    <li>Unaccompanied fighter tokens are intended to be removed, instead of destroyed.<sup>4</sup>
        <ul>
        <li><b>Explicit</b>: <sup>4</sup> Designer ruling: &ldquo;When you exceed the number of plastic infantry/fighters available, are unaccompanied tokens removed or destroyed? A: Removed.&rdquo;</li>
        </ul></li>
    </ol>
