<h2>Notes</h2>
    <ol class="note">
    <li>A breakthrough is a faction specific card.<sup>7</sup></li>
    <li>A breakthrough is commonly gained through an expedition. There are other game effects that can gain a player their faction&rsquo;s breakthrough.<sup>7</sup></li>
    <li>When a player gains their faction&rsquo;s breakthrough, they perform a breakthrough roll, which may cause The Fracture to enter play.<sup>2,7</sup></li>
    <li>A breakthrough has 1 or more abilities, and a synergy (other than for the <a href="/F_nekro">Nekro</a> player).<sup>7</sup></li>
    <ol><li>If a breakthrough has a passive ability and an exhaust ability, the passive ability always remains in effect, even when the breakthrough is exhausted.<sup>2</sup></li></ol>
    <li>A breakthrough itself is not a technology; it alone cannot be used to meet a prerequisite when researching a technology, nor can it alone be used to meet the technology requirement of an objective.<sup>2</sup></li>
    <li>The <a href="/F_rebellion">Rebellion</a> player gains their breakthrough as a starting component, which triggers a breakthrough roll during setup; The Fracture may be in play from the start of the game.<sup>2</sup></li>
    </ol>

