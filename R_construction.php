<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '24.' counter(item, decimal);} </style>
<p data-src="1,13">The <i>Construction</i> strategy card allows players to place structures on planets they control. This card&rsquo;s initiative value is &ldquo;4&rdquo;.</p>
    <ol class="lrr">
    <li data-src="1">During the action phase, if the active player has the <i>Construction</i> strategy card, they can perform a strategic action to resolve that card&rsquo;s primary ability.</li>
    <li>To resolve the primary ability on the <i>Construction</i> strategy card, the active player may either place one structure on a planet they control, or use the <a href="/R_production"><sc>Production</sc></a> ability of one of their space docks. Then, that player may place one structure on a planet they control.<sup>13</sup></li>
    <ol>
        <li data-src="1">The structures can be placed on the same planet or different planets.</li>
        <li data-src="1">The structures can be placed in any systems, regardless of whether the player has a command token in the system or not.</li>
    </ol>
    <li>After the active player resolves the primary ability of the <i>Construction</i> strategy card, each other player, beginning with the player to the left of the active player and proceeding clockwise, may spend one command token from their strategy pool to place one structure on a planet they control. The command token is not placed in any system.<sup>2,13</sup></li>
    <li data-src="1,13">When a player places a structure using the <i>Construction</i> strategy card, they take that structure from their reinforcements.</li>
    <ol><li data-src="1,2">If a player does not have the unit in their reinforcements, that player can remove a unit from any system that does not contain one of their command tokens and place that unit in their reinforcements. Then, that player must place the unit on the game board as instructed by the effect that is placing the unit.</li></ol>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>A player may have a maximum of one space dock on each planet.<sup>1,2,3</sup></li>
    <li>A player may have a maximum of two PDS units on each planet.<sup>1,2,3</sup></li>
    <li>Structures cannot be placed on the planet with the <a href="https://twilight-imperium.fandom.com/wiki/Agenda_Cards#Directives:~:text=Demilitarized%20Zone"><i>Demilitarized Zone</i></a> exploration card attached.<sup>*</sup></li>
    <li>Placing structures with the Construction strategy card is not producing units; the structures have no cost, and production rules do not apply.<sup>2</sup></li>
    <li>Resolving the secondary ability of the <i>Construction</i> strategy card does not activate a system, and it does not matter whether the system has already been activated.<sup>2</sup></li>
    </ol>

