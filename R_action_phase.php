<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '3.' counter(item, decimal);} </style>
<p data-src="1,3">During the action phase, each player takes a turn in initiative order. During a player&rsquo;s turn, they perform a single action. After each player has taken a turn, player turns begin again in initiative order. This process continues until all players have passed.</p>
    <ol class="lrr">
    <li data-src="1,2,3">During a player&rsquo;s turn, they may perform one of the following three types of actions: a strategic action, a tactical action, or a component action.</li>
    <li data-src="1">If a player cannot perform an action, they must pass.</li>
    <li data-src="1,3">After a player has passed, they have no further turns and cannot perform additional actions during that action phase.</li>
    <ol>
        <li data-src="1">During a turn that a player passes, they can resolve transactions and &ldquo;at the start of your turn&rdquo; abilities.</li>
        <li data-src="1,2,3">A player that has passed can still resolve the secondary ability of other players&rsquo; strategy cards.</li>
        <li data-src="1">It is possible for a player to perform multiple, consecutive actions during an action phase if all other players have passed during that action phase.</li>
    </ol>
    <li data-src="1,2,3">A player cannot pass until they have performed the strategic action of their strategy card.</li>
    <ol><li data-src="1,2,3">During a three&ndash;player or four&ndash;player game, a player cannot pass until they have exhausted both of their strategy cards.</li></ol>
    <li data-src="1,3">After all players have passed, play proceeds to the status phase.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>Any abilities that occur at the end of an action happen before any abilities that occur at the end of a player&rsquo;s turn.<sup>*</sup></li>
    <li>A player may resolve &ldquo;at the start of your turn&rdquo; and &ldquo;at the end of your turn&rdquo; abilities on the turn that they pass.<sup>1,4</sup></li>
    <li>If all other players have passed, a player will continue to resolve &ldquo;at the start of your turn&rdquo; and &ldquo;at the end of your turn&rdquo; abilities.<sup>*</sup></li>
    </ol>

