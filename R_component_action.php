<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '22.' counter(item, decimal);} </style>
<p data-src="1">A component action is a type of action that a player can perform during their turn of an action phase.</p>
    <ol class="lrr">
    <li data-src="1,3">Component actions can be found on various game components, including action cards, technology cards, leaders, exploration cards, relics, promissory notes, and faction sheets. Each component action is indicated by an &ldquo;Action&rdquo; header.</li>
    <li data-src="1">To perform a component action, a player reads the action&rsquo;s text and follows the instructions as described.</li>
    <li data-src="1,2,5">A component action cannot be performed if its ability cannot be completely resolved.</li>
    <li data-src="1,2">If a component action is canceled, it does not use that player&rsquo;s action.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>Action cards without the &ldquo;Action&rdquo; header are not used to perform component actions.<sup>1</sup></li>
    <li>There is no limit to how many component actions a player may perform during a round, other than any limit stated on the component itself. Each component action uses that player&rsquo;s action for the turn.<sup>2</sup></li>
    </ol>

