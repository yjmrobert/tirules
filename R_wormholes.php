<h2>Notes</h2>
    <ol class="note">
    <li>A system containing a wormhole is not an anomaly.<sup>2</sup></li>
    <li>If a system contains multiple wormholes of the same type, those are treated as separate wormholes.<sup>*</sup></li>
    <li>A system cannot be adjacent to itself, even if it has multiple wormholes in it.<sup>1,2</sup></li>
    <li>A player chooses the path of adjacent systems each ship moves through during movement.<sup>4</sup></li>
    <ol>
        <li>If the two systems are adjacent because of a wormhole and because of a shared edge or another reason, the player may choose whether or not the ship moves through the wormhole.<sup>2,4</sup></li>
        <li>If the two systems are adjacent because of two types of wormholes, the player chooses which type of wormhole the ship moves through.<sup>2,4</sup></li>
        <li>A player may move a ship back and forth through a wormhole between two systems any number of times, if its movement value is high enough.<sup>*</sup></li>
    </ol>
    </ol>

