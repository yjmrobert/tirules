<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '60.' counter(item, decimal);} </style>
<p data-src="1,2,3">Two players are neighbors if they both have a unit or control a planet in the same system. They are also neighbors if they both have a unit or control a planet in systems that are adjacent to each other.</p>
    <ol class="lrr">
    <li data-src="1,2,3">Players can resolve transactions with their neighbors.</li>
    <li data-src="1,2">Players are neighbors if the adjacency of systems is granted by a wormhole.</li>
    <li data-src="1">Players are neighbors with the Ghosts of <a href="/F_creuss">Creuss</a> if the Ghosts of <a href="/F_creuss">Creuss</a>&rsquo; &ldquo;Quantum Entanglement&rdquo; faction ability is causing adjacency from the perspective of the Ghosts of <a href="/F_creuss">Creuss</a> player.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>A player may make a deal with any player, however, these deals may only include a transaction if the two players are neighbors.<sup>1,2</sup></li>
    <ol><li>Some effects allow players who are not neighbors to resolve transactions, such as controlling <a href="/R_space_stations">space stations</a>, the <a href="/R_agenda_phase">agenda phase</a>, the <a href="/F_hacan">Hacan</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Emirates_of_Hacan#Faction_Abilities:~:text=Guild%20Ships"><sc>Guild Ships</sc></a> faction ability, the <a href="/F_nomad">Nomad</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Nomad#Faction_Technologies:~:text=Temporal%20Command%20Suite"><i>Temporal Command Suite</i></a> technology and the <a href="/F_yssaril">Yssaril</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Yssaril_Tribes#Breakthrough:~:text=Deepgloom%20Executable"><i>Deepgloom Executable</i></a> breakthrough.<sup>1,2,7</sup></li></ol>
    <li>A player may resolve one transaction with each other player per each agenda during the agenda phase, however, the agenda phase does not make all players neighbors.<sup>1,2,3,5</sup></li>
    <li>Ships that move through a system do not make their owner neighbors with players who have units in or adjacent to that system, as those ships are never in that system.<sup>2</sup></li>
    <li>Players in a space combat or ground combat with each other are neighbors, as they both have units in the same system.<sup>1,2</sup></li>
    </ol>

