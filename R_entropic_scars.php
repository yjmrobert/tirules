<h2>Rules Reference</h2>
<p>There currently does not exist a Living Rules Reference section regarding entropic scars.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>An entropic scar is an anomaly that affects unit abilities and faction technologies.<sup>7</sup></li>
    <li>A unit in an entropic scar cannot use unit abilities.<sup>2,7</sup></li>
    <ol>
        <li>Only unit abilities cannot be used; text abilities are unaffected.<sup>7</sup></li>
        <li>A unit in an entropic scar still has its unit abilities, even though it cannot use them. As such, a text ability that only requires a unit with a unit ability may still be used, such as the <a href="/F_arborec">Arborec</a> player&rsquo;s Dirzuga Rophal commander with a unit that has <a href="/R_production"><sc>Production</sc></a>.<sup>2</sup></li>
        <li>If a unit loses its <a href="/R_deploy"><sc>Deploy</sc></a> ability, then the text that describes how that unit&rsquo;s <a href="/R_deploy"><sc>Deploy</sc></a> ability is used will have no effect.<sup>*</sup></li>
    </ol>
    <li>A unit outside of an entropic scar cannot use unit abilities against units that are in an entropic scar.<sup>7</sup></li>
    <li>Wormhole tokens that would be placed in an entropic scar are discarded instead.<sup>6,7</sup></li>
    <ol>
        <li>A discarded wormhole token is returned to the supply, or to its owner&rsquo;s reinforcements if it belongs to a player, such as the <a href="/F_creuss">Creuss</a> player&rsquo;s wormhole tokens.<sup>*</sup></li>
        <li>The <a href="/F_creuss">Creuss</a> player may use the <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Faction_Technologies:~:text=Wormhole%20Generator"><i>Wormhole Generator</i></a> technology to place or move one of their wormhole tokens into an entropic scar; that token is discarded.<sup>6</sup></li>
        <li>The delta wormhole of the <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Flagship:~:text=Hil%20Colish"><i>Hil Colish</i></a> is not affected by an entropic scar, as the <a href="https://twilight-imperium.fandom.com/wiki/The_Ghosts_of_Creuss#Flagship:~:text=Hil%20Colish"><i>Hil Colish</i></a> is a ship, not a wormhole token.<sup>6</sup></li>
        <li>If an exploration card would place a gamma wormhole token in an entropic scar, the card is still purged as part of its resolution, and the token is discarded.<sup>6</sup></li>
        <li>If the <a href="https://twilight-imperium.fandom.com/wiki/Exploration#Prophecy_of_Kings_Expansion:~:text=Ion%20Storm"><i>Ion Storm</i></a> exploration card would place its token in an entropic scar, the card is still placed in the common play area, and the token is discarded.<sup>6</sup></li>
    </ol>
    <li>At the start of the status phase, a player with ships in an entropic scar may spend a command token from their strategy pool to gain one of their faction&ndash;specific technologies.<sup>7</sup></li>
    <ol>
        <li>A player need not meet the prerequisites for the technology they gain this way.<sup>2</sup></li>
        <li>If a player has ships in two (or more) entropic scars, they may spend two command tokens from their strategy pool at the start of the status phase to gain both of their faction&ndash;specific technologies.<sup>6</sup></li>
    </ol>
    </ol>

