<p data-src="1,2,3">Some cards can be exhausted. A player cannot resolve abilities or spend the resources or influence of an exhausted card.</p>
    <ol class="lrr">
    <li data-src="1,3">To exhaust a card, a player flips the card facedown.</li>
    <li data-src="1,3">During the <b><a href="/R_status_phase">Ready Cards</a></b> step of the status phase, each player readies all of their exhausted cards by flipping those cards faceup.</li>
    <li data-src="1,2,3">A player exhausts their planet cards to spend either the resources or influence on that card.</li>
    <li data-src="1">Abilities, including some found on technology cards, may instruct a player to exhaust a card to resolve those abilities. If a card is already exhausted, it cannot be exhausted again.</li>
    <ol><li data-src="1,2,5">Passive abilities on an exhausted card are still in effect while that card is exhausted.</li></ol>
    <li data-src="1,3">After a player performs a strategic action, they exhaust the strategy card that corresponds to that action.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>Planets will also ready at the end of each agenda phase.<sup>1,2,3</sup></li>
    <ol><li>This includes the Deepwrought player&rsquo;s <a href="/F_deepwrought#oceanbound">ocean cards</a>, <a href="/R_space_stations">space stations</a> and <a href="https://twilight-imperium.fandom.com/wiki/Relics#Thunder's_Edge:~:text=The%20Triad"><i>The Triad</i></a>.<sup>3,6,7</sup></li></ol>
    <li>If a game effect instructs a player to exhaust a planet, the exhausted planet must be controlled by that player, unless the game effect specifies otherwise.<sup>*</sup></li>
    </ol>

