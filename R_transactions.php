<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '94.' counter(item, decimal);} </style>
<p data-src="1,2">A transaction is a way for a player to exchange commodities, trade goods, promissory notes, and relic fragments.</p>
    <ol class="lrr">
    <li data-src="1,2,3">During the active player&rsquo;s turn, they may resolve up to one transaction with each of their neighbors.</li>
    <ol><li data-src="1,2,3">A player can resolve a transaction at any time during their turn, even during a combat.</li></ol>
    <li data-src="1,2,3,8">To resolve a transaction, a player gives any number of trade goods and commodities and up to one promissory note to a neighbor in exchange for any number of trade goods, commodities, and relic fragments, and up to one promissory note.</li>
    <li data-src="1,2">Players can exchange commodities, trade goods, promissory notes, and relic fragments, but cannot exchange other types of cards or tokens.</li>
    <ol><li data-src="1,2">The Emirates of <a href="/F_hacan">Hacan</a> can also exchange action cards with other players as part of their transactions.</li></ol>
    <li data-src="1,2">A transaction does not have to be even. A player may exchange components of unequal value or give components without receiving something in return.</li>
    <ol><li data-src="1">The players agree on the terms of the transaction before exchanging any components. After the components are traded, the transaction cannot be undone.</li></ol>
    <li data-src="1,3">Players can resolve a transaction as part of a deal.</li>
    <li data-src="1,2,3">While resolving <b>each</b> agenda during the agenda phase, a player may perform one transaction with each other player.</li>
    <ol><li data-src="1,2,3,5">Players do not need to be neighbors to perform these transactions.</li></ol>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>Players cannot resolve transactions during the strategy phase or the status phase. Players may still negotiate during these phases, but the terms of a deal that involves trade goods cannot be resolved immediately, so that deal is not binding.<sup>2,5</sup></li>
    <ol><li>The <a href="/F_nomad">Nomad</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Nomad#Faction_Technologies:~:text=Temporal%20Command%20Suite"><i>Temporal Command Suite</i></a> technology and the <a href="/F_yssaril">Yssaril</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Yssaril_Tribes#Breakthrough:~:text=Deepgloom%20Executable"><i>Deepgloom Executable</i></a> breakthrough may allow a transaction at these times.<sup>*</sup></li></ol>
    <li>Relic fragments may be traded. Relics themselves cannot be.<sup>1,8</sup></li>
    <li>Captured non&ndash;fighter ships and mechs may be returned to the player that originally owned them as part of a transaction.<sup>1,8</sup></li>
    <li>If a player becomes neighbors with another player on their turn, they may then perform a transaction with that player.<sup>1</sup></li>
    <ol>
        <li>If a player stops being neighbors with another player that they have performed a transaction with this turn, but then become neighbors with that player again later that same turn, they cannot perform a second transaction with that player.<sup>1</sup></li>
        <ol><li>The <a href="/F_nomad">Nomad</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Nomad#Faction_Technologies:~:text=Temporal%20Command%20Suite"><i>Temporal Command Suite</i></a> technology may allow a second transaction with the same player in one turn.<sup>4</sup></li></ol>
        <li>A player may perform a transaction during combat with their opponent, even if they are neighbors only in the active system.<sup>2</sup></li>
    <li>Commodities received in a transaction cannot be given back as part of that same transaction; doing so would require a second transaction.<sup>2</sup></li>
    </ol>
    <li>If a player may perform multiple actions on their turn, they may still only resolve one transaction with each of their neighbors.<sup>1,2</sup></li>
    <li>If an agenda is discarded and replaced with another, players who resolved a transaction during the discarded agenda may resolve another transaction during the replacement agenda.<sup>5</sup></li>
    </ol>

