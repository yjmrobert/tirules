<p data-src="1,3">The custodians token begins each game on <a href="/R_mecatol_rex">Mecatol Rex</a>. The token represents the caretakers that safeguard the seat of the empire until such time as the galactic council can be reconvened.</p>
    <ol class="lrr">
    <li data-src="1,3">Units can move into the system that contains <a href="/R_mecatol_rex">Mecatol Rex</a> following normal rules; however, players cannot commit ground forces to land on <a href="/R_mecatol_rex">Mecatol Rex</a> until the custodians token is removed from the planet.</li>
    <li data-src="1,2,3">Before the <b><a href="/R_invasion">Commit Ground Forces</a></b> step of an invasion, the active player can remove the custodians token from <a href="/R_mecatol_rex">Mecatol Rex</a> by spending six influence. Then, that player must commit at least one ground force to land on the planet.</li>
    <ol><li data-src="1">If a player cannot commit ground forces to land on <a href="/R_mecatol_rex">Mecatol Rex</a>, they cannot remove the custodians token.</li></ol>
    <li data-src="1,2,3">When a player removes the custodians token from <a href="/R_mecatol_rex">Mecatol Rex</a>, they take the token from the game board and place it in their play area. Then, they gain one victory point.</li>
    <li data-src="1,2,3">After a player removes the custodians token from <a href="/R_mecatol_rex">Mecatol Rex</a>, the agenda phase is added to all subsequent game rounds, including the game round during which the custodians token was removed from <a href="/R_mecatol_rex">Mecatol Rex</a>.</li>
    </ol>

<h2>Notes</h2>
