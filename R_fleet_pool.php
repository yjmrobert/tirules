<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '37.' counter(item, decimal);} </style>
<p data-src="1,3">The fleet pool is an area of a player&rsquo;s command sheet.</p>
    <ol class="lrr">
    <li data-src="1,2,3">The number of command tokens in a player&rsquo;s fleet pool indicates the maximum number of non&ndash;fighter ships that a player can have in a system.</li>
    <ol>
        <li data-src="1">Units that are on planets or that count against a player&rsquo;s capacity do not count against that player&rsquo;s fleet pool.</li>
        <li data-src="1">Units that are being transported through systems do not count against a player&rsquo;s fleet pool in those systems.</li>
    </ol>
    <li data-src="1,3">Players place command tokens in their fleet pools with the ship silhouette faceup.</li>
    <li data-src="1,2,3">If at any time the number of a player&rsquo;s non&ndash;fighter ships in a system exceeds the number of tokens in that player&rsquo;s fleet pool, they choose and remove excess ships in that system, returning those units to their reinforcements.</li>
    <li data-src="1,3">Players do not spend command tokens from this pool unless a game effect specifically allows it.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>Fighters and ground forces do not count toward capacity during combat. When combat ends however, units will need to be removed to meet capacity requirements.<sup>1,2,3,5</sup></li>
    <li>Ships may be moved into or produced in a system even if doing so would exceed the fleet pool limit. However, some of those ships must immediately be removed to satisfy the limit.<sup>2,5,6</sup></li>
    <ol><li>If some of those ships are fighters II, they may instead count toward that player&rsquo;s capacity in that system. If capacity is exceeded, fighters or ground forces must be removed to meet the limit.<sup>2</sup></li></ol>
    <li>During movement, a ship may move through a system regardless of how many ships are in that system relative to the fleet pool limit.<sup>2,5</sup></li>
    </ol>

