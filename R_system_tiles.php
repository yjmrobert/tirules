<p data-src="1">A system tile represents an area of the galaxy. Players place system tiles during setup to create the game board.</p>
    <ol class="lrr">
    <li data-src="1">The back of each system tile is colored green, blue, or red.</li>
    <li data-src="1">System tiles with a green&ndash;colored back are home systems and faction&ndash;specific tiles. Each home system is unique to one of the game&rsquo;s factions.</li>
    <li data-src="1">System tiles with a blue&ndash;colored back each contain one or more planets.</li>
    <li data-src="1">System tiles with a red&ndash;colored back are anomalies or are systems that do not contain planets.</li>
    <li data-src="1">Planets are located in systems. Ground forces and structures are usually placed on planets.</li>
    <li data-src="1">Any area on a system tile that is not a planet is space. Ships are usually placed in the space area.</li>
    <li data-src="1,7,8">Double&ndash;sided tiles that have lines crossing from one edge to another are hyperlane tiles. Hyperlane tiles are not systems.</li>
    </ol>

