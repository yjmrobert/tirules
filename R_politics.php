<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '66.' counter(item, decimal);} </style>
<p data-src="1">The <i>Politics</i> strategy card allows players to draw action cards. Additionally, the active player chooses a new speaker and looks at cards in the agenda deck. This card&rsquo;s initiative value is &ldquo;3&rdquo;.</p>
    <ol class="lrr">
    <li data-src="1">During the action phase, if the active player has the <i>Politics</i> strategy card, they can perform a strategic action to resolve that card&rsquo;s primary ability.</li>
    <li data-src="1">To resolve the primary ability on the <i>Politics</i> strategy card, the active player resolves the following effects in order:</li>
    <ol class="roman">
        <li data-src="1,2,3">The active player chooses any player that does not have the speaker token. The active player may choose themselves as long as they do not have the speaker token. The chosen player places the speaker token in their play area; they are now the speaker.</li>
        <li data-src="1,3">The active player draws two action cards.</li>
        <li data-src="1,3">The active player secretly looks at the top two cards of the agenda deck. Then, that player places each card on either the top or the bottom of the deck. If they place both cards on either the top or bottom, they can place them in any order.</li>
    </ol>
    <li data-src="1,3">After the active player resolves the primary ability of the <i>Politics</i> strategy card, each other player, beginning with the player to the left of the active player and proceeding clockwise, may spend one command token from their strategy pool to draw two action cards.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>If there are few cards remaining in the action card deck, they will be dealt out in clockwise order from the active player. After those players have discarded down to their seven card hand limit, if necessary, the discard pile will be shuffled to form a new deck. The remaining players (including the player who received the last action card from the previous deck, if applicable) will then be dealt their action cards.<sup>*</sup></li>
    <li>When resolving the primary ability of the <i>Politics</i> card, the active player cannot show the agenda cards they drew to any other player.<sup>2</sup></li>
    <ol><li>Other players may see whether each agenda card is placed on the top or the bottom of the agenda deck. Although the active player cannot show the cards, they may tell other players what the cards are, truthfully or not.<sup>2</sup></li></ol>
    <li>The speaker token cannot be exchanged in a transaction. However, the active player may make a deal with another player, including receiving a transaction, in exchange for choosing them as the new speaker, following the normal rules for deals and transactions.<sup>2</sup></li>
    <li>The active player looks at and places the top two cards of the agenda deck even if the custodians token has not yet been removed from <a href="/R_mecatol_rex">Mecatol Rex</a>.<sup>2</sup></li>
    </ol>

