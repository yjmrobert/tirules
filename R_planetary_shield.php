<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '65.' counter(item, decimal);} </style>
<p data-src="1,2,3">Units cannot use the <a href="/R_bombardment"><sc>Bombardment</sc></a> ability against a planet that contains a unit that has the <sc>Planetary Shield</sc> ability.</p>
    <ol class="lrr">
    <li data-src="1">The <sc>Planetary Shield</sc> ability does not prevent a planet from being affected by the <a href="https://twilight-imperium.fandom.com/wiki/Biotic_Technologies#X-89_Bacterial_Weapon"><i>X&ndash;89 Bacterial Weapon</i></a> technology.</li>
    <li data-src="1">The <sc>Planetary Shield</sc> ability prevents an <a href="/F_lizix">L1Z1X</a> player from using their <a href="https://twilight-imperium.fandom.com/wiki/The_L1Z1X_Mindnet#Faction_Abilities:~:text=Harrow"><sc>Harrow</sc></a> faction ability.</li>
    <li data-src="1,2">If a war sun is in a system with any number of other players&rsquo; units that have the <sc>Planetary Shield</sc> ability, those units are treated as if they do not have that ability.</li>
    <ol>
        <li data-src="1">Units treated as if they do not have a <sc>Planetary Shield</sc> ability cannot use the <a href="https://twilight-imperium.fandom.com/wiki/Warfare_Technologies#Magen_Defense_Grid"><i>Magen Defense Grid</i></a> technology.</li>
        <li data-src="1,2">A war sun can use its <a href="/R_bombardment"><sc>Bombardment</sc></a> ability against planets that contain units that have the <sc>Planetary Shield</sc> ability.</li>
    </ol>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>A unit with the <sc>Planetary Shield</sc> ability on a planet does not stop the use of a unit&rsquo;s <a href="/R_bombardment"><sc>Bombardment</sc></a> ability on other planets in the same system.<sup>1</sup></li>
    <li class="removed">If the <sc>Planetary Shield</sc> ability prevents the use of a <a href="/R_bombardment"><sc>Bombardment</sc></a> ability, then the ability of the <a href="https://twilight-imperium.fandom.com/wiki/Biotic_Technologies#X-89_Bacterial_Weapon"><i>X&ndash;89 Bacterial Weapon &Omega;</i></a> technology cannot be used.<sup>2,10</sup></li>
    <li class="removed">If a war sun causes a unit to be treated as if it does not have a <sc>Planetary Shield</sc> ability, that unit may still use the ability of the <a href="https://twilight-imperium.fandom.com/wiki/Warfare_Technologies#Magen_Defense_Grid"><i>Magen Defense Grid &Omega;</i></a> technology.<sup>2</sup></li>
    <li>If a war sun causes a unit to be treated as if it does not have a <sc>Planetary Shield</sc> ability, all units in that system with a <a href="/R_bombardment"><sc>Bombardment</sc></a> ability may use it against the planet that unit is on.<sup>2</sup></li>
    </ol>

