<h2>Rules Reference</h2>
<p>There currently does not exist a Living Rules Reference section regarding space stations.</p>

<h2>Notes</h2>
    <ol class="note">
    <li>Several systems contain space stations.<sup>7</sup></li>
    <li>A player gains control of a space station when they are the only player with ships in that space station&rsquo;s system.<sup>2,6,7</sup></li>
    <ol>
        <li>If another player moves ships into that system, they will not gain control of that space station unless they win the resulting space combat.<sup>7</sup></li>
        <li>If the player who controls the space station moves their ships out of the system, they retain control of that space station.<sup>2,7</sup></li>
    </ol>
    <li>A player does not lose control of a space station if a neutral ship is placed in its system, as there is no neutral player.<sup>6</sup></li>
    <li>A player whose ships are in a space station&rsquo;s system with only neutral units gains control of that space station before resolving combat against those neutral units, as there is no neutral player.<sup>6</sup></li>
    <li>Each space station has a corresponding planet card. The space station may be exhausted for resources or influence as though it were a planet. The space station will be readied during the status phase as though it were a planet, or by other game effects that can ready planets.<sup>7</sup></li>
    <ol><li>Space stations are also readied at the end of the agenda phase.<sup>*</sup></li></ol>
    <li>A player may exhaust a space station at any time to convert any commodities that they have into trade goods.<sup>7</sup></li>
    <li>For each space station a player controls, their commodity value is increased by one.<sup>7</sup></li>
    <ol><li>Players may place a space station commodity token in the commodity area of their faction sheet as a reminder of their increased commodity value.<sup>7</sup></li></ol>
    <li>A player who controls one or more space stations may resolve transactions with other players who control one or more space stations.<sup>7</sup></li>
    <ol><li>Players who resolve transactions in this manner need not be neighbors.<sup>7</sup></li></ol>
    <li>A player can exhaust space stations to cast votes. However, space stations are not planets, so they cannot be elected.<sup>6,7,9</sup></li>
    <li>Space stations are not planets, so attachments such as the <a href="https://twilight-imperium.fandom.com/wiki/Relics#Codex_II:~:text=Nano-Forge"><i>Nano&ndash;Forge</i></a> relic and the <a href="/F_ul">Ul</a> player&rsquo;s <a href="https://twilight-imperium.fandom.com/wiki/The_Titans_of_Ul#Faction_Promissory_Note:~:text=Terraform"><i>Terraform</i></a> promissory note cannot be attached to them.<sup>6</sup></li>
    <li>A space station is not a planet; controlling one does not prevent a player from being eliminated.<sup>2</sup></li>
    <li>Structures and ground forces cannot be committed to or placed on a space station.<sup>7</sup></li>
    <li>Space Stations do not count as planets for the purpose of scoring objectives, and a player may still score public objectives even if another player controls a space station in their home system.<sup>7</sup></li>
    <li>If a system tile contains a space station, but no planets, then a frontier token will be placed in that system during game setup.<sup>7</sup></li>
    </ol>

