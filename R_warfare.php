<p data-src="1,2,13">The <a href="https://twilight-imperium.fandom.com/wiki/Warfare_(Strategy_card)"><i>Warfare</i></a> strategy card allows a player to perform a tactical action without placing a command token, and to redistribute their command tokens between their tactic, fleet, and strategy pools. This card&rsquo;s initiative value is &ldquo;6&rdquo;. During the action phase, if the active player has the <a href="https://twilight-imperium.fandom.com/wiki/Warfare_(Strategy_card)"><i>Warfare</i></a> strategy card, they can perform a strategic action to resolve that card&rsquo;s primary ability.</p>
<p>To resolve the primary ability on the <a href="https://twilight-imperium.fandom.com/wiki/Warfare_(Strategy_card)"><i>Warfare</i></a> strategy card, the active player performs the following:<sup>13</sup></p>
    <ol class="lrr">
    <li>The active player performs a tactical action in any system without placing a command token, even if the system already has their command token in it; that system still counts as being activated.<sup>2,13</sup></li>
    <li>The active player may redistribute their command tokens before and after this tactical action.<sup>2,13</sup></li>
    <li>After the active player resolves the primary ability of the <a href="https://twilight-imperium.fandom.com/wiki/Warfare_(Strategy_card)"><i>Warfare</i></a> strategy card, each other player, beginning with the player to the left of the active player and proceeding clockwise, may spend one command token from their strategy pool to resolve the <a href="https://twilight-imperium.fandom.com/wiki/Production"><sc>Production</sc></a> abilities of units in their home system.<sup>2,13</sup></li>
    <ol><li data-src="1,13">The command token is <b>not</b> placed in their home system.</li></ol>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>Resolving the secondary ability of Warfare does not activate the player&rsquo;s home system. It may be resolved even if that system already contains one of their command tokens.<sup>2</sup></li>
    <li>If a tactical action that is part of the <a href="https://twilight-imperium.fandom.com/wiki/Warfare_(Strategy_card)"><i>Warfare</i></a> primary ability is cancelled, or the resolving player&rsquo;s turn is ended, the rest of the strategy card is still resolved.<sup>7</sup></li>
    <li>Ships may move into a system that has already been activated during the tactical action of the <a href="https://twilight-imperium.fandom.com/wiki/Warfare_(Strategy_card)"><i>Warfare</i></a> primary ability, but ships cannot move out of a system that has already been activated.<sup>2</sup></li>
    </ol>

