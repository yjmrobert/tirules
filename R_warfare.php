<p data-src="1,2,13">The <i>Warfare</i> strategy card allows a player to perform a tactical action without placing a command token, and to redistribute their command tokens between their tactic, fleet, and strategy pools. This card&rsquo;s initiative value is &ldquo;6&rdquo;. During the action phase, if the active player has the <i>Warfare</i> strategy card, they can perform a strategic action to resolve that card&rsquo;s primary ability.</p>
<p>To resolve the primary ability on the <i>Warfare</i> strategy card, the active player performs the following:<sup>13</sup></p>
    <ol class="lrr">
    <li>The active player performs a tactical action in any system without placing a command token, even if the system already has their command token in it; that system still counts as being activated.<sup>2,13</sup></li>
    <li>The active player may redistribute their command tokens before and after this tactical action.<sup>2,13</sup></li>
    <li>After the active player resolves the primary ability of the <i>Warfare</i> strategy card, each other player, beginning with the player to the left of the active player and proceeding clockwise, may spend one command token from their strategy pool to resolve the <a href="/R_production"><sc>Production</sc></a> abilities of units in their home system.<sup>2,13</sup></li>
    <ol><li data-src="1,13">The command token is <b>not</b> placed in their home system.</li></ol>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>Resolving the secondary ability of Warfare does not activate the player&rsquo;s home system. It may be resolved even if that system already contains one of their command tokens.<sup>2</sup></li>
    <li>If a tactical action that is part of the <i>Warfare</i> primary ability is canceled, or the resolving player&rsquo;s turn is ended, the rest of the strategy card is still resolved.<sup>7</sup></li>
    <li>During the tactical action of the <i>Warfare</i> primary ability, ships may move into a system that contains one of the player&rsquo;s command tokens, but ships still cannot move out of a system that contains one of the player&rsquo;s command tokens.<sup>2</sup></li>
    <ol><li>No command token is placed in the system where the <i>Warfare</i> primary ability is resolved, so ships in that system, including ones produced there, may move during a later tactical action that round.<sup>2</sup></li></ol>
    </ol>

