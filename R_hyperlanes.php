<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '44.' counter(item, decimal);} </style>
<p data-src="1">Hyperlanes are tiles that are used in some game board setups to create adjacency of system tiles that are not touching each other.</p>
    <ol class="lrr">
    <li data-src="1,7,8">Systems that are connected by lines drawn across one or more hyperlane tiles are adjacent for all purposes.</li>
    <li data-src="1,7,8">Hyperlane tiles are not systems. They cannot have units on them and they cannot be targets for effects or abilities.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>If the edge of a system tile is touching a hyperlane tile, that edge does not cause that system tile to be on the edge of the game board.<sup>2,4</sup></li>
    <ol>
        <li>When using the five&ndash; and seven&ndash;player hyperlane setups, the system tile in the center of the ring of hyperlanes is not on the edge of the game board.<sup>2</sup></li>
        <li>When using the seven&ndash; and eight&ndash;player alternate setups, only the system tiles designated as &ldquo;Ring 3&rdquo; and home systems are on the edge of the game board, along with the <a href="/F_creuss">Creuss</a> home system and the wormhole nexus.<sup>*</sup></li>
    </ol>
    <li>&ldquo;Adjacent for all purposes&rdquo; includes:<sup>1</sup></li>
    <ol>
        <li><a href="https://twilight-imperium.fandom.com/wiki/PDS#Upgraded_Unit:~:text=Deep%20Space%20Cannon"><sc>Deep Space Cannon</sc></a>.<sup>1</sup></li>
        <li>Movement.<sup>1</sup></li>
        <li>Neighbors.<sup>1</sup></li>
        <li>Any other game effect that specifies adjacent systems.<sup>1</sup></li>
    </ol>
    <li>Hyperlanes on the same tile that converge at a point on the tile edge are not connected. For example, with the &ldquo;Five&ndash;Player Galaxy Setup (With Hyperlanes)&rdquo; in the <a href="https://twilight-imperium.fandom.com/wiki/Prophecy_of_Kings"><i>Prophecy of Kings</i></a> Map Appendix, the hyperlanes on tile 87A do not connect tiles 39 and 63, and the hyperlanes on tile 88A do not connect tiles 41 and 80.<sup>*</sup></li>
    </ol>

