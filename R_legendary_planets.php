<p data-src="1,7,8">Legendary planets grant the player that controls them unique, planet&ndash;specific abilities.</p>
    <ol class="lrr">
    <li data-src="1,7,8">A legendary planet is indicated by the legendary planet icon.</li>
    <li data-src="1,7,8">When a player gains control of a legendary planet, they also place its legendary planet ability card in their play area.</li>
    <ol>
        <li data-src="1,2,6">If a player gains control of a legendary planet ability card from the deck, it is readied.</li>
        <li data-src="1,2,7,8">If a player gains control of an exhausted legendary planet ability card, it remains exhausted.</li>
    </ol>
    <li data-src="1">Players can use the abilities on the legendary planet ability cards in their play area.</li>
    <li data-src="1">If a legendary planet&rsquo;s planet card is purged, its corresponding legendary planet ability card is also purged.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>Legendary planet ability cards exhaust and ready independently from their respective planet card.<sup>2</sup></li>
    <li>A legendary planet ability card will ready in the status phase.<sup>1</sup></li>
    <li>An ability that readies a planet cannot be used to ready a legendary planet ability card.<sup>2</sup></li>
    <li>If an effect instructs a player to &ldquo;end your turn&rdquo;, that player may still resolve any &ldquo;at the end of your turn&rdquo; abilities, including those of legendary planets.<sup>4,6</sup></li>
    <li><a href="/R_mecatol_rex">Mecatol Rex</a> is a legendary planet when the Thunder&rsquo;s Edge Mecatol Rex system tile (tile 112) is used. Its legendary planet ability card is <a href="/C_legendary_planets"><i>The Galactic Council</i></a>.<sup>7</sup></li>
    </ol>

