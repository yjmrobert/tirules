<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '69.' counter(item, decimal);} </style>
<p data-src="1">Each player begins the game with one unique and five generic promissory note cards that can be given to other players.</p>
    <ol class="lrr">
    <li data-src="1,3">Each promissory note contains timing text and ability text. A player can resolve any of their promissory note cards by following the text on the card.</li>
    <ol><li data-src="1,2">Promissory notes are <b>not</b> mandatory unless otherwise specified.</li></ol>
    <li data-src="1,3">A player cannot play their color&rsquo;s or faction&rsquo;s promissory notes. Since the cards are only valuable to other players, promissory notes can be traded as powerful negotiation tools.</li>
    <li data-src="1">Promissory notes that are returned to a player are returned after their abilities have been completely resolved.</li>
    <li data-src="1,3">If a promissory note is returned to a player, that player may give it to other players again as part of a future transaction.</li>
    <ol><li data-src="1,2">An unrevealed promissory note is not subject to effects in its ability text that return the card if certain conditions are met.</li></ol>
    <li data-src="1,2,3">When resolving a transaction, a player can trade a maximum of one promissory note from their hand to another player, even if that card originally belonged to another player.</li>
    <ol><li data-src="1,2">Promissory notes in the play area cannot be traded.</li></ol>
    <li data-src="1">Players should keep their hands of promissory notes hidden.</li>
    <li data-src="1">If a player is eliminated, all of the promissory notes that match their color or faction are returned to the game box, including those that are in play or owned by other players.</li>
    <ol><li data-src="1">Other players&rsquo; promissory notes are returned to those players.</li></ol>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>The number of promissory notes in a player&rsquo;s hand is public information.<sup>*</sup></li>
    <li>A player may choose to reveal any or all of the promissory notes in their hand.<sup>1,2</sup></li>
    <li>When two players make a trade for a promissory note, the specific promissory note that was traded may be hidden from other players.<sup>1,2</sup></li>
    <ol>
        <li>However, it is public information that a promissory note was traded.<sup>*</sup></li>
        <li>The <a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Alliance"><i>Alliance</i></a> and <a href="https://twilight-imperium.fandom.com/wiki/Promissory_Notes#Support_for_the_Throne"><i>Support for the Throne</i></a> promissory notes must be played immediately when received. As such, trading either of these notes cannot be kept hidden.<sup>3</sup></li>
    </ol>
    <li>If a player receives a card, such as a promissory note, in a transaction during that card&rsquo;s timing window, they may play it immediately. For example, a promissory note with &ldquo;At the start of your turn:&rdquo; timing may be played immediately if the transaction occurred during the &ldquo;start of turn&rdquo; timing window.<sup>1,2,5</sup></li>
    <li>Returning a promissory note to its owner as part of resolving it is not a transaction. The note is returned even if the two players are not neighbors.<sup>2</sup></li>
    </ol>

