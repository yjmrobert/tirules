<p data-src="1,3">Various game effects can cause a unit to be destroyed. When a player&rsquo;s unit is destroyed, it is removed from the game board and returned to their reinforcements.</p>
    <ol class="lrr">
    <li data-src="1,3">When a player assigns hits that were produced against their units, that player chooses a number of their units to be destroyed equal to the number of hits produced against those units.</li>
    <li data-src="1,2,10">If a player&rsquo;s unit is removed from the board by a game effect, it is not treated as being destroyed; effects that trigger when a unit is destroyed are not triggered.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>A ship removed by a <a href="/R_gravity_rift">gravity rift</a> is not destroyed.<sup>2,10</sup></li>
    <li>Units that are removed due to <a href="/R_capacity">capacity</a> limits are not destroyed. For example, removed Infantry II units do not roll for the Infantry II unit upgrade&rsquo;s ability.<sup>2</sup></li>
    <li>Ships that are removed because they exceed a player&rsquo;s <a href="/R_fleet_pool">fleet pool</a> limit are not destroyed.<sup>1</sup></li>
    <li>If a player has a <a href="/R_fighter_tokens">fighter token</a> or <a href="/R_infantry_tokens">infantry token</a> that is not accompanied by a plastic piece of the same type and cannot replace it, the token is removed instead of destroyed.<sup>4</sup></li>
    <li>Units destroyed by <a href="/R_space_cannon">space cannon</a> or <a href="/R_bombardment">bombardment</a> rolls are not destroyed during combat. Units destroyed by <a href="/R_anti_fighter_barrage">anti&ndash;fighter barrage</a> rolls are destroyed during combat.<sup>2</sup></li>
    </ol>

