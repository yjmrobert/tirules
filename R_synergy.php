<h2>Notes</h2>
    <ol class="note">
    <li>Certain abilities, primarily breakthroughs, grant synergy between two colors of technology, allowing components of one color to be treated as the other for some game effects.<sup>7</sup></li>
    <li>When researching a technology, a player may treat each technology they own and/or each technology specialty on a planet they control that matches one color of their synergy as any color of that synergy.<sup>7</sup></li>
    <li>When scoring an objective, a player may treat each technology they own that matches one color of their synergy as any color of that synergy.<sup>2,7</sup></li>
    <li>These choices are made individually for each technology and/or each technology specialty.<sup>7</sup></li>
    <li>Each technology and/or each technology specialty can only be one color of technology at any given point in time.<sup>7</sup></li>
    <li>A technology and/or each technology specialty may be treated as different colors of technologies at different points in time.<sup>7</sup></li>
    <ol><li>For example, say a player currently has just one biotic technology, and they are resolving the primary ability of the <a href="/R_technology_sc"><i>Technology</i></a> strategy card to research two technologies; they have a propulsion/biotic synergy ability. They may first treat the biotic technology as a propulsion technology in order to research a technology with one propulsion prerequisite. Then, they may treat both the original biotic technology and the new propulsion technology as biotic technologies in order to research a technology with two biotic prerequisites.<sup>*</sup></li></ol>
    </ol>

