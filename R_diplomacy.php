<h2>Rules Reference</h2>
<style> .lrr > li:before, .lrr > h2 > li:before {content: '32.' counter(item, decimal);} </style>
<p data-src="1">The <i>Diplomacy</i> strategy card can be used to preemptively prevent other players from activating a specific system. It can also be used to ready planets. This card&rsquo;s initiative value is &ldquo;2&rdquo;.</p>
    <ol class="lrr">
    <li data-src="1">During the action phase, if the active player has the <i>Diplomacy</i> strategy card, they can perform a strategic action to resolve that card&rsquo;s primary ability.</li>
    <li data-src="1,2,10">To resolve the primary ability on the <i>Diplomacy</i> strategy card, the active player chooses a system that contains a planet they control other than the <a href="/R_mecatol_rex">Mecatol Rex</a> system; each other player places one command token from their reinforcements in that system. Then, the active player readies any two of their exhausted planets.</li>
    <ol>
        <li data-src="1,2">If a player has no command tokens in their reinforcements, that player places one command token of their choice from their command sheet.</li>
        <li data-src="1,2">If a player already has a command token in the chosen system, they do not place a command token there.</li>
    </ol>
    <li data-src="1,2,3">After the active player resolves the primary ability of the <i>Diplomacy</i> strategy card, each other player, beginning with the player to the left of the active player and proceeding clockwise, may spend one command token from their strategy pool to ready up to two exhausted planets they control.</li>
    </ol>

<h2>Notes</h2>
    <ol class="note">
    <li>If the player with <i>Diplomacy</i> controls no planets, or controls only <a href="/R_mecatol_rex">Mecatol Rex</a>, they may still perform a strategic action. However, other players will not place a command token in any system.<sup>1</sup></li>
    <li>If the player with <i>Diplomacy</i> controls fewer than two exhausted planets, they may still perform a strategic action. They will ready as many planets as possible.<sup>2</sup></li>
    <li>The Diplomacy token represents a command token from each player other than the player with the <i>Diplomacy</i> strategy card. It may be used to simplify play when no player is expected to interact with the command tokens placed by the primary ability.<sup>7</sup></li>
    <ol>
        <li>A player cannot increase the number of tokens they have access to from the use of the Diplomacy token.<sup>7</sup></li>
        <li>Game effects that can remove a command token from a system may still be used to remove a command token from the system containing the Diplomacy token. Should this happen, players may first wish to replace the Diplomacy token with the corresponding command tokens, then remove the required command token, leaving the rest in the system.<sup>2,7</sup></li>
        <li>The system that contains the Diplomacy token should be treated as containing a command token of the relevant players for all game effects.<sup>7</sup></li>
    </ol>
    </ol>

